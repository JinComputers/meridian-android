/**
 * Непрозрачные обозначения путей подключения.
 *
 * В клиентском логе путь называется буквой: «подключено, путь B, за 4 с».
 * Нам этого достаточно, чтобы понять, каким плечом поднялся туннель;
 * постороннему это не говорит ничего.
 *
 * СООТВЕТСТВИЕ БУКВ И ПУТЕЙ ДЕРЖИМ У СЕБЯ, в этом комментарии, а не в
 * приложении. Буквы раздаются по ПОРЯДКУ, в котором пути перечислены в
 * настройках: первый прямой — A, второй — B, третий — C; релейный — R.
 *
 * Порядок в настройках менять можно, но тогда старые логи начнут
 * читаться неверно. Если менять придётся — добавлять в конец.
 *
 * ИМЕНА, КОТОРЫЕ УХОДЯТ В ДВИЖОК, ТОЖЕ БУКВЫ. Иначе описания вроде
 * «прямой 56005 без DTLS» попадали бы и в лог человеку, и в сам пакет:
 * в логе их видит человек, в пакете — любой, кто его вскроет.
 */
object Paths {

    /** Буква релейного пути. */
    const val RELAY = "R"

    /** Имя ступени для движка. Оно же буква пути. */
    fun directName(index: Int): String = ('A' + index).toString()

    /**
     * Буква по имени, которое вернул движок.
     *
     * Имена мы сами задали буквами, так что работы почти нет — но
     * функция нужна: если движок вернёт что-то неожиданное, в логе
     * появится «?» вместо непонятной строки, и она точно не утечёт.
     */
    fun letterOf(winner: String): String = when {
        winner.isEmpty() -> "?"
        winner.length <= 2 -> winner
        else -> "?"
    }
}

/**
 * Отказ, у которого свой ЗАКОНЧЕННЫЙ текст.
 *
 * Приставку «Не удалось подключиться» к нему добавлять нельзя: «Не
 * удалось подключиться: Пробный период закончился» — это два разных
 * сообщения, слипшихся в одно, и человек читает первое, а важно второе.
 */
fun standsAlone(e: Throwable): Boolean =
    e.message.orEmpty().contains("FATAL_DEACTIVATED")

/**
 * Ключ отключён — что это значит ИМЕННО ДЛЯ ЭТОГО человека.
 *
 * Шлюз шлёт одну причину на всех, а случая три, и они требуют разных
 * действий. Различаем по источнику ключа, который приложение и так
 * хранит с момента получения.
 *
 * Поддержка уместна РОВНО В ОДНОМ случае — ключ введён руками, человек
 * знает, откуда он взялся, и ему есть о чём спрашивать. Пробному
 * периоду поддержка не поможет ничем, а владельцу подписки нужна не
 * поддержка, а способ продлить.
 *
 * Второе предложение про пробный обязательно: без него человек пойдёт
 * нажимать «начать сутки» ещё раз. Тот же довод записан в
 * Access.keyProblemText, где такой же разбор сделан для ответа службы.
 */
fun deactivatedText(): String = when (Access.sourceOfKey()) {
    Access.SOURCE_TRIAL ->
        "Пробный период закончился. Пробный период даётся один раз на устройство"
    Access.SOURCE_SUB ->
        "Подписка неактивна. " + purchaseHint()
    else ->
        "Ключ отключён. " + supportHint()
}

/**
 * Причина отказа ЧЕЛОВЕЧЕСКИМИ СЛОВАМИ.
 *
 * Текст исключения из движка сюда не годится: в нём и «лестница», и
 * «ступень», и «FATAL_AUTH». Клиентскому логу нужно, ЧТО случилось, а
 * не как оно называется внутри.
 *
 * Разбор по подстроке, а не по типу исключения: через gomobile ошибки
 * приезжают обычными Exception с текстом, и типов у них нет.
 *
 * Незнакомая ошибка даёт общую фразу. Молча пропустить её нельзя, но и
 * показать сырой текст тоже: он и есть то, что мы прячем. Сам текст при
 * этом остаётся в техническом логе отладочной сборки.
 */
fun humanReason(e: Throwable): String {
    val m = e.message.orEmpty()
    return when {
        m.contains("FATAL_POOL_FULL") -> "сервер сейчас переполнен, попробуйте позже"
        m.contains("FATAL_AUTH") -> "ключ не принят сервером"
        // МАРКЕР ОДИН, А ТЕКСТА ТРИ. Служба знает только, что ключ
        // отключён; что это был пробный или подписка — помним мы.
        m.contains("FATAL_DEACTIVATED") -> deactivatedText()
        // Шлюз промолчал: пакет до него дошёл, но разобрать его он не
        // смог — значит ключа, выведенного из нашего пароля, он не
        // знает. Чаще всего ключ просто свежий: список паролей шлюз
        // перечитывает раз в минуту.
        //
        // Ищем по кириллической части ошибки движка, а не по слову
        // протокола: образец поиска уезжает в dex релизной сборки, и
        // класть туда лишние приметы незачем.
        m.contains("шлюз не ответил") -> "сервер не ответил"
        m.contains("нет ключа доступа") -> "нет ключа доступа"
        m.contains("сеть") -> "сеть сменилась во время подключения"
        m.contains("не остановилась") -> "прежнее подключение не завершилось"
        else -> "подключиться не удалось"
    }
}

/**
 * ЧТО ДЕЛАТЬ ЧЕЛОВЕКУ — по коду причины из движка (Engine.failureKind(),
 * engine/failure.go). null — совета нет, остаётся humanReason.
 *
 * Главный случай — белые списки: сервер напрямую недоступен, а запасной
 * путь через VK-звонки не настроен или не сработал. По тексту ошибки
 * лестницы это не видно (последней падает то «сервер не ответил», то
 * «хешей нет»), движок решает по уликам всей лестницы.
 *
 * «Похоже на белые списки», а не «белые списки»: недоступный сервер из
 * этой сети выглядит так же и при аварии на нём. Путь к экрану называем
 * дословно, как он подписан в приложении.
 */
fun failureAdvice(kind: String): String? {
    val where = "добавьте ссылку на звонок ВКонтакте в «Настройки → Обход белых списков»"
    val blocked = "Сервер недоступен из этой сети напрямую — похоже, оператор включил белые списки"
    return when (kind) {
        Engine.FailBlockedNoLinks ->
            "$blocked. Обход через ВК-звонок не настроен: $where"
        Engine.FailBlockedLinksDead ->
            "$blocked. Все ссылки на ВК-звонки больше не работают: $where, свежую"
        Engine.FailBlockedCaptcha ->
            "$blocked. ВКонтакте просит капчу: решите её из уведомления и подключитесь снова, " +
                "или $where, другую"
        Engine.FailBlockedLinks ->
            "$blocked. ВКонтакте не дал доступ по ссылкам на звонки: повторите позже или $where, другую"
        Engine.FailBlockedRelay ->
            "Сервер недоступен из этой сети ни напрямую, ни через ВК-звонок. " +
                "Попробуйте другую сеть (например, Wi-Fi) или повторите позже"
        Engine.FailBlocked -> when {
            TransportSetting.mode.value == Config.TransportMode.DIRECT_ONLY ->
                "$blocked. В настройках выбран транспорт «только прямой» — " +
                    "переключите его на «авто», чтобы работал обход через ВК-звонок"
            else ->
                "Сервер недоступен из этой сети. Попробуйте другую сеть (например, Wi-Fi) " +
                    "или повторите позже"
        }
        Engine.FailSilent ->
            "Сервер не узнал ключ. Если ключ получен только что — подождите минуту " +
                "и подключитесь снова"
        else -> null
    }
}

/**
 * Тип сети одним словом.
 *
 * Только тип, без имени интерфейса и без адресов: 61.4 разрешает знать,
 * «что за сеть», 61.5 запрещает всё остальное.
 */
fun Context.shortNetworkType(): String = try {
    val cm = getSystemService(ConnectivityManager::class.java)
    val caps = cm?.activeNetwork?.let { cm.getNetworkCapabilities(it) }
    when {
        caps == null -> "нет"
        caps.hasTransport(NetworkCapabilities.TRANSPORT_WIFI) -> "Wi-Fi"
        caps.hasTransport(NetworkCapabilities.TRANSPORT_CELLULAR) -> "мобильная"
        caps.hasTransport(NetworkCapabilities.TRANSPORT_ETHERNET) -> "кабель"
        else -> "иная"
    }
} catch (e: Throwable) {
    "неизвестна"
}
