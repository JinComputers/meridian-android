package org.meridianvpn.app

import androidx.compose.runtime.mutableStateOf

/**
 * Строка состояния на главном экране.
 *
 * ПУСТА В ОБЫЧНОЙ РАБОТЕ, и это её главное свойство. Раньше там всегда
 * висело «Отключено» или «Туннель активен» — то есть строка занимала
 * место, повторяя то, что и так видно по планете.
 *
 * Теперь она появляется только когда есть что сказать, и поводов
 * ровно два:
 *
 *   изменилось состояние ключа — принят, продлён, истёк, отозван;
 *   туннель не поднялся, и мы сдались.
 *
 * Всё остальное — ход подключения, смена ступеней, переподключения —
 * живёт в логе. Человеку на главном экране это не нужно: если в конце
 * туннель встал, промежуточные шаги ему безразличны, а если не встал,
 * он увидит одну внятную строку вместо потока.
 *
 * СТРОКА ЖИВЁТ ТОЛЬКО В ПАМЯТИ. Так и задумано: это сообщение о
 * событии, а не настройка. Перезапуск приложения её убирает, и это
 * правильно — событие уже прошло.
 */
object Notice {

    /** Текст. Пусто — показывать нечего. */
    val text = mutableStateOf("")

    /** Тревожное ли сообщение: от этого зависит цвет. */
    val bad = mutableStateOf(false)

    /** Обычная новость: ключ принят, срок продлён. */
    fun say(s: String) {
        text.value = s
        bad.value = false
    }

    /** Плохая новость: ключ истёк, подключиться не вышло. */
    fun problem(s: String) {
        text.value = s
        bad.value = true
    }

    /**
     * Убрать.
     *
     * Зовётся, когда туннель поднялся: прежняя жалоба к этому моменту
     * устарела, а оставленная на экране она противоречила бы работающей
     * планете.
     */
    fun clear() {
        text.value = ""
        bad.value = false
    }
}
