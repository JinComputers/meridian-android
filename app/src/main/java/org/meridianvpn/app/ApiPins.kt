package org.meridianvpn.app

import java.io.IOException
import java.security.MessageDigest
import java.security.cert.Certificate
import java.util.Base64
import javax.net.ssl.SSLSession

/**
 * Закрепление ключа нашего API.
 *
 * ЗАКРЕПЛЯЕТСЯ ОТКРЫТЫЙ КЛЮЧ, А НЕ СЕРТИФИКАТ. Пин считается от SPKI —
 * SubjectPublicKeyInfo, — то есть от самого ключа. Сертификат с тем же
 * ключом можно перевыпускать сколько угодно, пин не изменится, и
 * обновление сертификата не потребует нового релиза в Play.
 *
 * ПОЧЕМУ НЕ network_security_config. Декларативный <pin-set> в Android
 * не годится нам по двум причинам сразу: он привязывается к доменному
 * имени, а два адреса из трёх у нас будут голыми IP, для которых он не
 * работает; и у него есть срок годности, по истечении которого
 * закрепление молча выключается. Здесь проверка ручная и без срока.
 *
 * ЗАПАСНОГО ПУТИ НЕТ. В этом файле нет и не должно появиться ни одного
 * условия вида «если не совпало, но сборка отладочная» или «если не
 * совпало, но другого пути нет». Закрепление, которое можно обойти
 * флагом, не закрепление вовсе: тот, кто сумеет подсунуть свой
 * сертификат, сумеет и выставить флаг.
 *
 * ОТКАЗ ВЫГЛЯДИТ КАК ОТСУТСТВИЕ СЕТИ. verify() бросает IOException, а
 * не своё исключение, именно затем: клиент API ловит IOException как
 * «ответа не было» (договор, 47.4) и падает на локальные данные. Для
 * человека это «не дозвонились», а не «плохой ключ» — потому что
 * плохой ключ здесь ни при чём, и говорить ему про ключ значило бы
 * послать его чинить не то.
 *
 * ВЫЗЫВАЕТСЯ, И НА ДВУХ РУБЕЖАХ. Здесь стояло «сегодня не вызывается,
 * клиента API ещё нет» — с тех пор клиент появился, и запись устарела,
 * оставаясь на виду. Сегодня matches() зовут свой X509TrustManager в
 * ApiClient.pinnedFactory() и проверяющий имени в pinnedVerifier(): без
 * совпадения рукопожатие не состоится, а второй рубеж ловит случай,
 * если фабрику сокетов однажды подменят на обычную.
 */
object ApiPins {

    /**
     * Основной пин.
     *
     * Подтверждён с работающего порта независимой проверкой — не тем
     * файлом, из которого снимался.
     *
     * ГДЕ СНЯТ — ЧАСТЬ ЗНАЧЕНИЯ. Порт 21947, ОБА адреса из ADDRESSES:
     *
     *     for a in jinelectronics.ru 138.249.246.89; do
     *       openssl s_client -connect $a:21947 </dev/null 2>/dev/null \
     *         | openssl x509 -pubkey -noout \
     *         | openssl pkey -pubin -outform der \
     *         | openssl dgst -sha256 -binary | base64
     *     done
     *
     * НА 443 У ТОГО ЖЕ ИМЕНИ СТОИТ ПРОКСИ С ЧУЖИМ КЛЮЧОМ, и клиент туда
     * не ходит НИКОГДА. Кот 2 померил 05.09 именно 443, получил
     * несовпадение и едва не объявил аварию, которой нет. Строка про 443
     * стоит здесь затем, чтобы следующий не повторил: без неё замер
     * выглядит правильным и даёт ложную тревогу.
     *
     * Оба адреса на 21947 обязаны отдавать ОДИН ключ. Проверено 24.08,
     * перепроверено 05.09 котом 3 и котом 2 независимо.
     */
    const val MAIN = "bYxJBY7Uhz34CkyyssvHci+ihjsypwu//acXo1fsIbw="

    /**
     * Запасной пин.
     *
     * Нужен ровно для одного случая: основной ключ скомпрометирован и
     * его надо сменить немедленно. Без запасного такая смена означает
     * новый релиз в Play и дни ожидания ревью, в течение которых API
     * недоступен вообще никому.
     *
     * Приватная часть с машины снята и хранится отдельно.
     * Владелец подтвердил её наличие 10.09.2026 — до этого дня договор
     * с API считал запасной путь неподтверждённым, и переезд на этот
     * ключ пришлось бы делать новой сборкой всем.
     *
     * Отпечаток закрытой половины против этого пина СЛИЧЁН НЕ БЫЛ:
     * подтверждено наличие файла, не совпадение. Сличить можно, не
     * вынося секрета никуда:
     *
     *     openssl pkey -in ЗАПАСНОЙ.pem -pubout -outform der      *       | openssl dgst -sha256 -binary | base64
     *
     * Разница существенна: файл, не подходящий к этому пину, выглядит
     * запасом ровно до того часа, когда запас понадобится.
     */
    const val BACKUP = "Lsn4bXD0gvNi/FGV0N12f3Uj4i/iuu8iHmtzO2geYV0="

    private val PINS = setOf(MAIN, BACKUP)

    /**
     * Пин одного сертификата: base64(sha256(SPKI)).
     *
     * getPublicKey().getEncoded() у X.509 отдаёт именно DER
     * SubjectPublicKeyInfo — то, что и надо хешировать.
     */
    fun pinOf(cert: Certificate): String {
        val spki = cert.publicKey.encoded
        val hash = MessageDigest.getInstance("SHA-256").digest(spki)
        return Base64.getEncoder().encodeToString(hash)
    }

    /**
     * Есть ли в цепочке хоть один закреплённый ключ.
     *
     * Смотрим ВСЮ цепочку, а не только лист: пин может стоять и на
     * промежуточном звене. Совпадения одного звена достаточно.
     */
    fun matches(chain: Array<out Certificate>?): Boolean {
        if (chain == null) return false
        for (cert in chain) {
            if (pinOf(cert) in PINS) return true
        }
        return false
    }

    /**
     * Проверяет соединение. Зовётся ПОСЛЕ рукопожатия, до чтения тела.
     *
     * Бросает IOException при несовпадении — см. заголовок файла.
     * Молча пропустить не может ни при каких условиях.
     */
    @Throws(IOException::class)
    fun verify(session: SSLSession?) {
        val chain = try {
            session?.peerCertificates
        } catch (e: Throwable) {
            // Цепочку не отдали — проверять нечего, значит не совпало.
            null
        }
        if (!matches(chain)) {
            // В тексте НЕТ ни пинов, ни того, что пришло: строка уходит
            // в лог, а лог человек копирует и присылает.
            throw IOException("соединение с API не подтвердилось")
        }
    }
}
