    /** Чем кончилась попытка получить пробный ключ. */
    sealed class TrialAnswer {
        /**
         * Ключ выдан.
         *
         * `repeat` — устройство уже обращалось, и это ТОТ ЖЕ ключ.
         * Переустановка приложения второго ключа не даёт: помнит сервер,
         * а не мы.
         */
        data class Granted(
            val key: String,
            val repeat: Boolean,
            val expiresAt: Long,
        ) : TrialAnswer()

        /**
         * Служба отказала. Это ЗНАНИЕ, и человеку надо его показать.
         *
         * `rateLimited` — предел выдачи с адреса (429). Отличается от
         * прочих отказов одним: повторять имеет смысл, но не сейчас.
         */
        data class Refused(
            /**
             * Текст СЛУЖБЫ. Показывать человеку как есть, разбирать
             * нельзя — правило про message.
             */
            val text: String,

            /**
             * Предел выдачи с адреса (429).
             *
             * Нужен не для текста — текст даёт служба, и он лучше
             * нашего, — а для того, чтобы НЕ повторять попытку сразу и
             * не жечь этим лимит.
             */
            val rateLimited: Boolean,
        ) : TrialAnswer()

        /** Спросить не удалось. Доступ НЕ запрещаем — см. вызывающего. */
        data class NoAnswer(val why: String) : TrialAnswer()
    }

    /**
     * Просит пробный ключ.
     *
     * ФОРМА СНЯТА С ЖИВОЙ СЛУЖБЫ котом 2, а не угадана. Два места из
     * трёх я до этого угадал неверно, и оба сломались бы молча:
     * посылал токен, которого ручка не проверяет, и слал тело, которое
     * она не читает.
     *
     *   POST /v1/trial?device_id=<id>, тело ПУСТОЕ, токена НЕТ.
     *
     * ГЛАВНОЕ В РАЗБОРЕ — ЧТО ЗНАЧИТ ОТКАЗ.
     *
     * При исчерпанном пределе служба отвечает кодом 429, но телом ПО
     * ДОГОВОРУ: status "answered", contract "v1", а ключ — ПУСТАЯ
     * СТРОКА. Поля verdict при этом нет вовсе.
     *
     * Значит признак выдачи — непустой key, и только он. Читать verdict
     * нельзя: при отказе его не существует. Читать status нельзя: он
     * "answered" в обоих случаях — служба ведь действительно ответила.
     *
     * expires_at и repeat присутствуют всегда, включая нулевые, — на
     * них можно опираться без проверки существования.
     */
    fun startTrial(): TrialAnswer {
        val r = ApiClient.call("/v1/trial", post = true)
        return when (r) {
            is ApiClient.Result.Ok -> {
                val key = r.body.optString("key")
                if (key.isEmpty()) {
                    // Ответ по договору, а ключа нет: это отказ. Текст
                    // берём у службы — он один и тот же во всех
                    // клиентах и уже написан для человека.
                    val text = r.body.optString("message")
                        .ifEmpty { "пробный ключ выдать не удалось" }
                    val limited = r.code == 429
                    TunnelLog.add(
                        "триал: ключ не выдан" +
                            (if (limited) " (предел выдачи с адреса)" else "") +
                            " — $text"
                    )
                    return TrialAnswer.Refused(text, limited)
                }
                val repeat = r.body.optBoolean("repeat", false)
                // Сам ключ в лог не пишем — это пароль подключения.
                TunnelLog.add(
                    if (repeat) "триал: сервер вернул РАНЕЕ выданный ключ этого устройства"
                    else "триал: выдан новый пробный ключ"
                )
                TrialAnswer.Granted(key, repeat, readExpires(r.body))
            }

            is ApiClient.Result.Refused -> {
                TunnelLog.add("триал: отказ — ${r.error}")
                TrialAnswer.Refused(r.error, r.code == 429)
            }

            is ApiClient.Result.Incompatible -> TrialAnswer.NoAnswer("договор ${r.theirs}")
            is ApiClient.Result.Unavailable -> TrialAnswer.NoAnswer(r.why)
        }
    }

    // ------------------------------------------------------------------
    // Спроектированы, но НЕ НАПИСАНЫ на сервере
    // ------------------------------------------------------------------
    //
    // Оставлены здесь заготовками намеренно: так видно, что появление
    // каждой из них — это функция на десяток строк в ЭТОМ файле, и
    // ничего больше. Транспорт трогать не придётся.
    //
    //   /v1/params  — адрес шлюза и порты вместо зашитых в Config.kt.
    //                 fun params(): ApiClient.Result = ApiClient.call("/v1/params")
    //                 Ответ кэшируется целиком; кэш НЕ протухает по
    //                 времени (договор, 47.5), иначе упавший сервер
    //                 оставит человека без адреса шлюза.
    //
    //   /v1/unbind  — отвязать ключ от прежнего устройства. Нужна ровно
    //                 после Bound.OTHER выше, и кнопка появится только
    //                 в этом случае.
    //
    // Ни одна из них не пишется сегодня: на сервере их нет, а писать
    // клиента к несуществующей ручке — это гадать о форме ответа.
}
