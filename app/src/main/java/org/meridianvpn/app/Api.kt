package org.meridianvpn.app

/**
 * Ручки API.
 *
 * Здесь и только здесь живёт знание о том, какие бывают пути и что
 * лежит в телах. Транспорт — обход адресов, пины, сроки, конверт,
 * разбор общей части — в ApiClient и про ручки не знает ничего.
 *
 * ДОБАВИТЬ РУЧКУ — это дописать сюда функцию на несколько строк.
 * ApiClient при этом не меняется вообще. Три спроектированные, но пока
 * не написанные ручки показаны заготовками внизу файла — ровно затем,
 * чтобы было видно, что добавление стоит.
 *
 * Все функции здесь БЛОКИРУЮЩИЕ и зовутся только с фонового потока.
 */
object Api {

    // ------------------------------------------------------------------
    // /v1/health — есть ли служба вообще
    // ------------------------------------------------------------------

    /**
     * Приложение эту ручку САМО НЕ ЗОВЁТ (договор, 47.7). Она здесь для
     * отладки: проверить обход адресов и пины, не трогая ключей.
     */
    fun health(): ApiClient.Result = ApiClient.call("/v1/health")

    // ------------------------------------------------------------------
    // /v1/key — проверка ключа
    // ------------------------------------------------------------------

    /**
     * Что API сказал про ключ.
     *
     * СЛОВАРЬ ЗАКРЫТ котом 2: шесть слов, больше не будет без правки
     * договора и его версии. Раньше здесь были угаданные синонимы —
     * active, valid, alive и прочие; они убраны намеренно. Пока клиент
     * понимает слова, которых служба не шлёт, он не может отличить
     * «договор поменялся» от «всё как было», а именно это и нужно
     * заметить.
     */
    enum class KeyState {
        /** `ok` — жив и не истёк. Пускаем. */
        ACTIVE,

        /** `expired` — срок закончился. Человеку: продлевать. */
        EXPIRED,

        /** `revoked` — доступ отозван, вышел из платной группы. */
        REVOKED,

        /** `deleted` — удалён администратором. */
        DELETED,

        /** `deactivated` — отключён администратором, но не удалён. */
        DEACTIVATED,

        /** `unknown` — такого ключа нет и надгробия нет. */
        UNKNOWN,

        /**
         * Служба сказала что-то, чего мы не знаем.
         *
         * ОТДЕЛЬНОЕ СОСТОЯНИЕ, И ЭТО ГЛАВНЫЙ УРОК ЗАДАЧИ 51.2.
         *
         * Раньше неизвестное слово молча падало в UNKNOWN, то есть
         * «такого ключа нет». Служба ответила «ok» вместо ожидаемого
         * «active» — и рабочий ключ владельца был объявлен
         * несуществующим. Ошибка понимания притворилась вердиктом.
         *
         * Теперь непонятое слово ведёт себя как молчание сервера:
         * проверяем подключением, ключ не хороним, а в лог уходит
         * само слово — чтобы добавить его сюда заняло одну строку.
         */
        UNRECOGNISED,
    }

    /** К чему ключ привязан. */
    enum class Bound {
        /** Ни к чему — первое устройство заберёт его само. */
        NONE,

        /** К нам. */
        THIS,

        /** К другому устройству. Единственный случай, ради которого нужна отвязка. */
        OTHER,
    }

    /**
     * Вердикт по ключу.
     *
     * Есть вердикт — служба высказалась о ключе. Нет вердикта
     * (KeyAnswer.NoAnswer) — это НЕ «ключ плохой», а «спросить не
     * удалось». Разница принципиальная: в первом случае говорим
     * человеку прямо, во втором проверяем подключением.
     */
    data class KeyVerdict(
        val state: KeyState,
        val bound: Bound,
        val expiresAt: Long,
        /**
         * Дата из надгробия: когда ключ УДАЛЁН или отозван.
         *
         * Это НЕ то же самое, что конец срока, и кот 2 не стал их
         * смешивать намеренно. Истёкший ключ уборщик сносит в течение
         * часа; пока он в базе, приходит настоящий expires_at, после —
         * ноль и вот это since, которое расходится с концом срока на
         * время до часа.
         */
        val since: Long,

        /**
         * Вердикт настоящий, но СТАРЫЙ: база была недоступна, и служба
         * ответила из кэша последнего успешного ответа.
         *
         * Отдельное поле рядом с verdict, а не значение status: status
         * при этом остаётся "answered". Поле присутствует всегда,
         * включая false.
         */
        val stale: Boolean,

        /**
         * Сколько секунд данным. Длительность, НЕ метка времени.
         *
         * Присутствует всегда, включая ноль. Ноль здесь осмысленное
         * значение: ответ моложе секунды. Кот 2 замерил, что с
         * omitempty мы видели бы «stale есть, а возраста нет».
         */
        val staleAge: Long,

        /** Готовый текст от службы. Пусто — скажем своими словами. */
        val message: String,
    ) {
        /** Годен ли ключ к употреблению прямо сейчас. */
        fun usable(): Boolean = state == KeyState.ACTIVE && bound != Bound.OTHER

        /**
         * МОЖНО ЛИ ХОРОНИТЬ КЛЮЧ ПО ЭТОМУ ВЕРДИКТУ.
         *
         * По договору кэшируется ТОЛЬКО «ok», поэтому плохого вердикта
         * со старыми данными не бывает вовсе. Если он всё-таки придёт —
         * это ошибка службы, и вести себя надо как при молчании: ключ
         * не трогать.
         *
         * Почему именно так, а не наоборот. Цена ошибки несимметрична:
         * ошибиться в сторону «пустить» стоит одной неудачной попытки
         * подключения — шлюз проверяет пароль сам и с негодным ключом не
         * пустит. Ошибиться в сторону «стереть» стоит потерянного ключа
         * у заплатившего человека, а при покупке через Play он этого
         * ключа даже не видел и ввести заново не сможет.
         */
        fun trustworthyRefusal(): Boolean = !stale

        /** «3 ч назад», «12 мин назад». Для оговорки при старых данных. */
        fun ageText(): String {
            val m = staleAge / 60
            return when {
                m >= 60 -> "${m / 60} ч назад"
                m >= 1 -> "$m мин назад"
                else -> "только что"
            }
        }

        /**
         * Какую дату показывать. 0 — показывать нечего.
         *
         * Правило кота 2: есть expires_at — он; иначе since; нет ни
         * того ни другого — говорим без даты.
         */
        fun dateToShow(): Long = when {
            expiresAt > 0L -> expiresAt
            since > 0L -> since
            else -> 0L
        }
    }

    // ------------------------------------------------------------------
    // MESSAGE — ТЕКСТ ДЛЯ ЧЕЛОВЕКА. РАЗБИРАТЬ ЕГО НЕЛЬЗЯ.
    //
    // Предупреждение кота 2, и оно не формальность. Поле message
    // существует, чтобы одно и то же событие объяснялось одинаково во
    // всех клиентах, — значит его текст будут править, переводить и
    // смягчать, ни у кого не спрашивая. Любое сравнение с ним
    // сломается молча и не при сборке, а у человека на телефоне.
    //
    // Разбирать надо verdict, expires_at и since. Их значения закрыты
    // договором и меняются только вместе с его версией.
    //
    // Мест, где message читается, ТРИ, и все три — показ, ни одного
    // сравнения (проверено grep):
    //   Api.kt, отсутствие вердикта  — причина в лог;
    //   Api.kt, разбор вердикта      — текст на экран человеку;
    //   ApiClient.kt, отказ службы   — подпись отказа в лог.
    // ------------------------------------------------------------------

    /** Итог проверки: либо вердикт, либо причина, по которой его нет. */
    sealed class KeyAnswer {
        data class Verdict(val v: KeyVerdict) : KeyAnswer()

        /** Служба ответила отказом — ключ ни при чём. */
        data class Refused(val error: String, val retryAfter: Int) : KeyAnswer()

        /** Спросить не удалось. Проверять придётся подключением. */
        data class NoAnswer(val why: String) : KeyAnswer()
    }

    /**
     * Проверка ключа.
     *
     * ЗАПРОС ИДЁТ МЕТОДОМ GET, ключ уходит параметром строки запроса —
     * так устроена работающая служба (проверено 24.08.2026: на POST она
     * отвечает «только GET»). В договоре описан POST с телом, и это
     * расхождение названо в отчёте, а не выбрано молча.
     *
     * У формы GET есть цена, и её надо знать: ключ — это пароль
     * подключения, а строка запроса обычно целиком попадает в журнал
     * обращений сервера. По проводу его не видно, TLS на месте, но в
     * логе службы он окажется. Перевод ручки на POST это чинит.
     *
     * ПРИЗНАК УСПЕХА И ИМЯ ПОЛЯ ВЕРДИКТА разошлись были: бумажный
     * договор называл их `ok` и `key_state`, служба отдаёт `status` и
     * `verdict`. Спор закрыт замером кота 2 (07.09): полей `ok` и
     * `key_state` служба не шлёт НИГДЕ. Читаем только то, что она
     * действительно говорит; поддержка вторых имён убрана.
     */
    /**
     * Срок неизвестен.
     *
     * ОТ ПРОТОКОЛА ЭТО ЗНАЧЕНИЕ БОЛЬШЕ НЕ ПРИХОДИТ. Кот 2 замерил и
     * починил у себя: `expires_at` присутствует ВСЕГДА, включая ноль,
     * а ноль означает бессрочный ключ. Раньше у поля стоял omitempty,
     * и бессрочный ключ уходил без поля — то есть служба говорила
     * «не знаю» там, где знала точно. Мой вопрос эту ошибку и нашёл.
     *
     * Значение оставлено ровно для двух случаев, оба наши, не его:
     *   ключ подтверждён туннелем, а API в тот момент молчал;
     *   служба ответила status: unavailable, и вердикта в ответе нет.
     *
     * В обоих мы честно говорим «срок неизвестен» вместо «бессрочный».
     */
    const val UNKNOWN_EXPIRY = -1L

    /** То же чтение срока, но доступное соседям: им нужна та же логика. */
    fun readExpiresPublic(body: org.json.JSONObject): Long = readExpires(body)

    private fun readExpires(body: org.json.JSONObject): Long {
        for (name in listOf("expires_at", "expiresAt", "ExpiresAt")) {
            if (body.has(name)) return body.optLong(name, 0L)
        }
        return UNKNOWN_EXPIRY
    }

    /**
     * Словарь вердиктов. ЗАКРЫТ, шесть слов, источник — кот 2.
     *
     * Угаданных синонимов здесь больше нет: слово, которого служба не
     * шлёт, только маскирует смену договора. Всё, чего нет в этой
     * таблице, попадает в UNRECOGNISED и ведёт себя как молчание.
     */
    private val VERDICTS = mapOf(
        "ok" to KeyState.ACTIVE,
        "expired" to KeyState.EXPIRED,
        "revoked" to KeyState.REVOKED,
        "deleted" to KeyState.DELETED,
        "deactivated" to KeyState.DEACTIVATED,
        "unknown" to KeyState.UNKNOWN,
    )

    /**
     * Свежая версия приложения из ответа службы.
     *
     * Зачем это здесь, а не отдельным запросом: сборка прямой раздачи
     * обновляется, беря описание релиза с GitHub, а GitHub в России
     * доступен неровно — не достучались, и человек про обновление не узнал
     * вовсе. Наш API отвечает по уже пинованному каналу, который у людей
     * работает, и версию он теперь кладёт в каждый ответ о ключе. То есть
     * проверка достаётся бесплатно, без единого лишнего запроса.
     *
     * ОТСУТСТВИЕ ПОЛЕЙ — ЗАКОННОЕ СОСТОЯНИЕ, а не ошибка: служба не
     * настроена, ведём себя как раньше. Кот 2 поставил там omitempty
     * осознанно, и это не отступление от нашего уговора не прятать нули:
     * ноль в expires_at был ЗНАЧЕНИЕМ, а нулевого кода версии не бывает.
     *
     * Половину подсказки не берём: без имени показать нечего, без кода не
     * с чем сравнивать. Служба и сама половину не отдаёт, но полагаться на
     * это здесь незачем.
     *
     * updateHint — разный в двух вариантах сборки. В прямой раздаче он
     * поднимает строку версии в настройках, в сборке для Play не делает
     * ничего: там обновлениями занимается магазин.
     */
    private fun noteLatestVersion(body: org.json.JSONObject) {
        val code = body.optLong("latest_version_code", 0L)
        val name = body.optString("latest_version_name")
        // ГОВОРИМ В ОБОИХ СЛУЧАЯХ, и это не многословие.
        //
        // Первый заход я написал молчащим в обеих ветках, и по логу
        // нельзя было отличить «служба не прислала» от «клиент не
        // прочитал» — а это два совершенно разных места для починки.
        // Одна строка на проверку ключа, зато вопрос закрывается
        // взглядом.
        if (code <= 0L || name.isEmpty()) {
            TunnelLog.add("API: свежей версии в ответе нет (служба её не настроила)")
            return
        }
        TunnelLog.add("API: служба сообщила свежую версию: $code ($name)")
        updateHint(code, name)
    }

    fun checkKey(key: String): KeyAnswer {
        val r = ApiClient.call("/v1/key", mapOf("key" to key))
        return when (r) {
            is ApiClient.Result.Ok -> {
                // ПОДСКАЗКА ОБ ОБНОВЛЕНИИ — ПЕРВОЙ СТРОКОЙ, до разбора
                // вердикта. Она не про ключ и не должна зависеть от
                // того, понравился ли нам вердикт: даже непонятый или
                // отсутствующий вердикт не повод не узнать про новую
                // версию.
                noteLatestVersion(r.body)

                // ВЕРДИКТА МОЖЕТ НЕ БЫТЬ ВОВСЕ, и это не сбой разбора.
                // При status: unavailable служба намеренно не кладёт
                // поле: «не смогли проверить» не должно выглядеть
                // приговором ключу. Единственное место во всём договоре,
                // где отсутствие поля осмысленно.
                // ПОЛЕ ОДНО — verdict. Здесь стоял запасной путь к
                // key_state, и он не срабатывал никогда: кот 2 замерил
                // по коду службы, что таких полей она не шлёт нигде,
                // живут только status в конверте и verdict внутри.
                //
                // Вреда он не приносил — непонятый вердикт у нас и так
                // уходит как молчание службы, — но описывал договор,
                // которого нет. Понимать слова, которых служба не
                // говорит, значит оставлять следующему ложную карту:
                // он решит, что имён у поля два, и будет искать, когда
                // же приходит второе. Формулировка кота 4, поймавшего
                // это у себя.
                if (!r.body.has("verdict")) {
                    val why = r.body.optString("message").ifEmpty { "вердикта в ответе нет" }
                    TunnelLog.add("API: служба не смогла проверить ключ ($why)")
                    return KeyAnswer.NoAnswer(why)
                }
                val state = r.body.optString("verdict").lowercase()
                val bound = r.body.optString("bound")
                val v = KeyVerdict(
                    state = VERDICTS[state] ?: run {
                        TunnelLog.add(
                            "API: вердикт «$state» мне неизвестен — " +
                                "ключ НЕ хороню, проверю подключением"
                        )
                        KeyState.UNRECOGNISED
                    },
                    bound = when (bound) {
                        "this" -> Bound.THIS
                        "other" -> Bound.OTHER
                        else -> Bound.NONE
                    },
                    expiresAt = readExpires(r.body),
                    since = r.body.optLong("since", 0L),
                    stale = r.body.optBoolean("stale", false),
                    staleAge = r.body.optLong("stale_age", 0L),
                    message = r.body.optString("message"),
                )
                // Сам ключ в лог не пишем никогда — это пароль подключения.
                TunnelLog.add("API: ключ — $state, привязка $bound")
                // Непонятый вердикт — это НЕ суждение о ключе, а наше
                // незнание. Наружу отдаём как молчание сервера, чтобы
                // ниже сработала проверка подключением.
                if (v.state == KeyState.UNRECOGNISED) {
                    KeyAnswer.NoAnswer("непонятный вердикт «$state»")
                } else {
                    KeyAnswer.Verdict(v)
                }
            }
            is ApiClient.Result.Refused -> KeyAnswer.Refused(r.error, r.retryAfter)
            is ApiClient.Result.Incompatible -> KeyAnswer.NoAnswer("договор ${r.theirs}")
            is ApiClient.Result.Unavailable -> KeyAnswer.NoAnswer(r.why)
        }
    }


