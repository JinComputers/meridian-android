    private const val K_DEVICE = "trial_device"
    /**
     * Ключ доступа.
     *
     * Лежит в ТОМ ЖЕ файле, что и якорь триала, а значит уезжает в
     * резервную копию. Это решение владельца, а не недосмотр: ключ по
