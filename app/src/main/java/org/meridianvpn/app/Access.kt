    /**
     * КОГДА ДЛЯ ЭТОГО УСТРОЙСТВА НАЧАЛСЯ ТРИАЛ. 0 — не начинался.
     *
     * ЭТО ТА САМАЯ ТОЧКА, КУДА ВСТАНЕТ СЕРВЕРНАЯ ПРОВЕРКА (задачи 44.2 и 45.2 — одна и та же).
     * Больше нигде время старта не читается — менять надо здесь и в
     * markTrialStarted(), и больше нигде.
     *
     * СЕЙЧАС отвечает по локальным данным: SharedPreferences плюс Auto
     * Backup с правилом на один файл (res/xml/backup_rules.xml и
     * data_extraction_rules.xml). Это половинчато и мы это знаем:
     * копия возвращается только при установке через восстановление —
     * новое устройство, перенос, установка из Play при включённом
     * копировании. Обычная переустановка APK не вернёт ничего, и триал
     * начнётся заново.
     *
     * ПОЗЖЕ пойдёт на сервер: клиент отдаёт хеш ANDROID_ID, сервер
     * возвращает время первого обращения. Тогда переустановка перестанет
     * что-либо давать вовсе.
     *
     * Что учесть при подключении сервера — три вещи, каждая из которых
     * иначе всплывёт на устройстве, а не здесь:
     *
     *  1. ВЫЗОВ СТАНЕТ СЕТЕВЫМ, а зовут его из attach(), то есть с
     *     главного потока в onCreate. Сетевой вызов оттуда — это либо
     *     NetworkOnMainThreadException, либо ANR. Значит, attach()
     *     останется на локальном значении, а поход на сервер придётся
     *     делать отдельным вызовом с фонового потока, и состояние
     *     пересчитывать по его возвращении.
     *  2. СЕРВЕР МОЖЕТ БЫТЬ НЕДОСТУПЕН — и именно тогда, когда человек
     *     без туннеля. Отказ в доступе по молчанию сервера означает
     *     заблокированное приложение у честного человека. Падать надо на
     *     локальное значение, а не в запрет.
     *  3. ХОДИТЬ НАДО ДО ПОДКЛЮЧЕНИЯ, вне туннеля: сам туннель мы и
     *     решаем, поднимать ли. Куда именно ходить — вопрос к серверу,
     *     публичной ручки пока нет.
     */
    private fun trialStartedAt(ctx: Context, device: String): Long =
        prefs(ctx)?.getLong(K_START, 0L) ?: 0L

    /**
     * Записывает начало триала.
     *
     * Вторая половина точки из trialStartedAt(): когда чтение уйдёт на
     * сервер, запись уйдёт туда же.
     */
    private fun markTrialStarted(ctx: Context, device: String, at: Long) {
        prefs(ctx)?.edit()
            ?.putLong(K_START, at)
            ?.putString(K_DEVICE, device)
            ?.putBoolean(K_VOID, false)
            ?.putLong(K_SEEN, at)
            ?.apply()
    }

    /** Забывает триал целиком — вместе с отметками часов. */
    private fun forgetTrial(ctx: Context) {
        start = 0L
        voided = false
        lastSeen = 0L
        prefs(ctx)?.edit()
            ?.remove(K_START)
            ?.remove(K_DEVICE)
            ?.remove(K_VOID)
            ?.remove(K_SEEN)
            ?.apply()
    }

    /**
     * ИДЕНТИФИКАТОР УСТРОЙСТВА. Одно значение на всё приложение.
     *
     * Основной источник — ANDROID_ID. С Android 8 он считается от
     * подписи приложения: один и тот же при переустановке той же
     * сборки, разный у разных приложений, меняется от заводского сброса
     * и от смены ключа подписи. И то и другое нам как раз и надо
     * считать новым устройством.
     *
     * ЗАПАСНОЙ ИСТОЧНИК — свой UUID. ANDROID_ID на части устройств
     * возвращается пустым, и раньше мы подставляли вместо него строку
     * "unknown" — то есть у ВСЕХ таких телефонов идентификатор
     * получался одинаковый. Они делили бы между собой и привязку ключа,
     * и якорь триала: первый начавший сутки закрывал бы их всем
     * остальным.
     *
     * UUID лежит в том же файле, что и якорь, значит уезжает в
     * резервную копию и переживает переустановку. Это здесь не
     * побочный эффект, а требование: иначе запасной источник давал бы
     * новое устройство при каждой установке.
     *
     * Пишется через commit(), а не apply(): значение становится
     * личностью устройства, и потерять его из-за падения процесса
     * сразу после генерации нельзя. Файл крошечный, запись мгновенная.
     */
    @Synchronized
    fun deviceId(ctx: Context): String {
        val android = try {
            Settings.Secure.getString(ctx.contentResolver, Settings.Secure.ANDROID_ID)
        } catch (e: Throwable) {
            null
        }
        if (!android.isNullOrBlank()) return android

        val p = prefs(ctx) ?: return ""
        val saved = p.getString(K_UUID, "") ?: ""
        if (saved.isNotBlank()) return saved

        val fresh = java.util.UUID.randomUUID().toString()
        p.edit().putString(K_UUID, fresh).commit()
        TunnelLog.add("ANDROID_ID пуст — устройство опознаю по своему UUID")
        return fresh
    }

    private fun prefs(ctx: Context) = try {
        ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
    } catch (e: Throwable) {
        null
    }

