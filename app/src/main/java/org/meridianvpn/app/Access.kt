package org.meridianvpn.app

import android.content.Context
import android.provider.Settings
import androidx.compose.runtime.mutableStateOf

/**
 * Доступ: суточный триал и ключ.
 *
 * Ключ здесь — это ПАРОЛЬ ПОДКЛЮЧЕНИЯ. Отдельной проверки на сервере
 * пока нет, и она не нужна: шлюз и так не пустит с неверным паролем.
 * Поэтому проверка ключа — это попытка подключения, а «встал туннель»
 * и есть подтверждение.
 *
 * ЧТО ЗДЕСЬ МОЖНО ОБОЙТИ. Всё. Приложение сносится, устройство
 * сбрасывается, часы переводятся. Задача не в том, чтобы сделать обход
 * невозможным — на клиенте это недостижимо, — а в том, чтобы он стоил
 * человеку больше, чем ключ.
 */
object Access {

    /**
     * Трое суток. Пробный период — 72 часа.
     *
     * ЭТО ЗАПАСКА НА ОФЛАЙН, а не главный срок. В обычном случае клиент
     * живёт по серверному expires_at пробного ключа, и его срок держит
     * кот 2 (72 часа). Здесь — только местный отсчёт на случай, когда
     * сервер недоступен в момент старта триала. Оба обязаны совпадать:
     * разъедутся — на офлайне отсчёт соврёт против серверного ключа.
     */
    const val TRIAL_MS = 72L * 60L * 60L * 1000L

    /**
     * Насколько часам позволено уйти назад без подозрений.
     *
     * Секунды назад отыгрывает обычная синхронизация времени: телефон
     * поднялся с ушедшим вперёд RTC и поправился по сети. Десять минут
     * — с запасом на такой случай.
     *
     * Сдвиг меньше десяти минут проходит незамеченным, и это осознанно:
     * чтобы так растянуть сутки, часы придётся крутить назад полторы
     * сотни раз руками. Неудобно — этого достаточно.
     */
    private const val CLOCK_SLACK_MS = 10L * 60L * 1000L

    /** Реже этого отметку «последний раз видели» на диск не пишем. */
    private const val SEEN_WRITE_MS = 60L * 1000L

    enum class State {
        /** Ключа нет, триал не начинался. */
        NO_TRIAL,

        /** Триал идёт. */
        TRIAL,

        /** Триал кончился, ключа нет. */
        OVER,

        /** Ключ подтверждён подключением. */
        KEYED,
    }

    /** Для экрана. Обновляется через refresh(). */
    val state = mutableStateOf(State.NO_TRIAL)

    /** Подтверждён ли сохранённый ключ подключением. Для экрана. */
    val checked = mutableStateOf(false)

    /** Срок ключа для экрана. Значения — см. keyExpires. */
    val expires = mutableStateOf(Api.UNKNOWN_EXPIRY)

    /**
     * Почему ключ перестал годиться. Пусто — всё в порядке.
     *
     * Заполняется, когда очередная проверка вернула не «ok»: истёк,
     * отозван, удалён, отключён. Человек обязан прочитать причину, а не
     * обнаружить, что кнопка вдруг пропала.
     */
    val problem = mutableStateOf("")

    /**
     * Ключ, про который служба сказала «занят другим устройством».
     * Пусто — переносить нечего, кнопки переноса нет.
     *
     * ОТДЕЛЬНОЕ ПОЛЕ, А НЕ ВЫВОД ИЗ problem. Соблазн был: текст про
     * чужую привязку уже лежит в problem, и кнопку можно было бы
     * показывать по нему. Но problem — это ТЕКСТ ДЛЯ ЧЕЛОВЕКА, его
     * правят и переводят; кнопка, привязанная к сравнению со строкой,
     * тихо исчезнет при первой же правке формулировки. Ровно то
     * правило, по которому мы не разбираем message от службы.
     *
     * Второй довод: самого ключа в problem нет, а перенос без ключа
     * невозможен — звать /v1/unbind нечем.
     *
     * Заполняется в ДВУХ местах, потому что чужая привязка приходит
     * двумя путями: при вводе ключа руками (AccessScreen.applyVerdict)
     * и при перепроверке уже сохранённого (refreshKey). Оба зовут
     * noteRebindable().
     */
    val rebindable = mutableStateOf("")

    /**
     * Есть ли у переносимого ключа путь восстановления (Api.recoverable).
     * null — служба не сказала, говорим осторожнее.
     *
     * Живёт рядом с rebindable и заполняется вместе с ним: подтверждение
     * переноса должно знать это ДО нажатия, а не после. Нажатие
     * необратимо и тратит попытку из четырёх за год — узнать цену
     * постфактум значит узнать её поздно.
     */
    val rebindRecoverable = mutableStateOf<Boolean?>(null)

    /** Сколько осталось триала, миллисекунды. 0 вне состояния TRIAL. */
    val leftMs = mutableStateOf(0L)

    private var appCtx: Context? = null
    private var loaded = false

    @Volatile
    private var start = 0L

    @Volatile
    private var key = ""

    /**
     * Ключ проверен ПОДКЛЮЧЕНИЕМ, а не только словом сервера.
     *
     * Два утверждения, и они разные (задача 50.3):
     *   «ключ принят сервером» — API нашёл его в базе и не возражает;
     *   «ключ проверен подключением» — с ним встал туннель.
     *
     * Первое сохраняет ключ и снимает блок доступа сразу: человек ввёл
     * ключ и обязан немедленно увидеть исход, а не гадать. Второе —
     * подтверждение, которое приходит позже и никого не задерживает.
     */
    @Volatile
    private var keyChecked = false

    /**
     * До какого времени годен ключ, Unix-секунды.
     *
     * Три значения, и все три разные:
     *   > 0  — дата, до которой ключ действует;
     *     0  — БЕССРОЧНЫЙ ключ, так сказала служба;
     *    -1  — СРОКА МЫ НЕ ЗНАЕМ. Так бывает, когда ключ подтвердился
     *          подключением, а API в этот момент молчал.
     *
     * Ноль и минус единица — не одно и то же, и человеку они
     * показываются по-разному. Слить их значило бы объявить бессрочным
     * ключ, о котором мы ничего не выяснили.
     */
    @Volatile
    private var keyExpires = Api.UNKNOWN_EXPIRY

    /** Когда в последний раз спрашивали службу про этот ключ. */
    @Volatile
    private var keyCheckedAt = 0L

    /**
     * Ключ получен из /v1/trial, а не введён человеком.
     *
     * Нужно ровно для одной строки на экране. Через 72 часа сервер
     * пометит пробный ключ деактивированным, и общий текст сказал бы
     * «ключ отключён — напишите в поддержку». Для пробного это неправда
     * и вредный совет: он не отключён, он ЗАКОНЧИЛСЯ, и в поддержку
     * идти незачем.
     *
     * Служба такого текста дать не может — она не знает, что перед ней
     * пробный ключ. Мы знаем: помним, как он получен.
     */
    /**
     * ОТКУДА ВЗЯЛСЯ КЛЮЧ. Пусто — человек ввёл его руками.
     *
     * Нужно ради текста, который человек прочтёт, когда ключ перестанет
     * работать. Служба не знает, откуда ключ у этого устройства, — мы
     * знаем, потому что помним, как его получили.
     *
     *   пробный, деактивирован → «пробный период закончился»,
     *     а не «ключ отключён — напишите в поддержку»;
     *   по подписке, отозван   → «подписка закончилась»,
     *     а не «доступ отозван — напишите в поддержку». Отзыв здесь —
     *     обычное следствие отмены или возврата, и поддержка ни при чём.
     *
     * Раньше это был флаг keyIsTrial. Строка вместо второго флага:
     * третий источник появится раньше, чем третий булев признак
     * перестанет путать.
     */
    @Volatile
    private var keySource = ""

    /**
     * Пробный период на этом устройстве уже израсходован.
     *
     * БЕЗ ЭТОГО ФЛАГА КНОПКА «НАЧАТЬ 3 ДНЯ» ВОЗВРАЩАЛАСЬ БЫ.
     *
     * Серверный пробный ключ не заводит местный якорь: start остаётся
     * нулём. Когда через 72 часа ключ деактивируется и стирается,
     * состояние по одному лишь start посчиталось бы как NO_TRIAL — то
     * есть «триал не начинался», и человек снова увидел бы кнопку.
     *
     * Нажав её, он получил бы repeat: true с ТЕМ ЖЕ, уже мёртвым
     * ключом, мы бы его приняли, следующая перепроверка снова его
     * стёрла — и так по кругу.
     */
    @Volatile
    private var trialSpent = false

    /**
     * Ключ, введённый, но ещё не подтверждённый подключением.
     *
     * Живёт только в памяти: сохранять непроверенный ключ нельзя, иначе
     * опечатка навсегда заменила бы рабочий пароль.
     */
    @Volatile
    private var pending = ""

    /** Триал объявлен законченным из-за перевода часов назад. */
    @Volatile
    private var voided = false

    /** Когда приложение в последний раз видело часы идущими вперёд. */
    @Volatile
    private var lastSeen = 0L

    @Synchronized
    fun attach(ctx: Context) {
        if (loaded) return
        loaded = true
        appCtx = ctx.applicationContext

        val p = prefs(ctx)
        if (p == null) {
            refresh()
            return
        }
        key = p.getString(K_KEY, "") ?: ""
        keyChecked = p.getBoolean(K_KEY_CHECKED, false)
        // Срок сохранён вместе с ключом: после перезапуска идти за ним
        // в API незачем, он не меняется сам по себе.
        keyExpires = p.getLong(K_KEY_EXPIRES, Api.UNKNOWN_EXPIRY)
        keyCheckedAt = p.getLong(K_KEY_ASKED_AT, 0L)
        keySource = p.getString(K_KEY_SOURCE, "") ?: ""
        trialSpent = p.getBoolean(K_TRIAL_SPENT, false)
        // ЧУЖАЯ ПРИВЯЗКА ПЕРЕЖИВАЕТ ПЕРЕЗАПУСК, и это не украшение.
        //
        // Без сохранения кнопка переноса ждала бы СУТОЧНОГО ОПРОСА:
        // refreshKey() при недавней проверке выходит сразу, не спросив
        // службу (checkDue), а значит и вердикта, из которого мы узнаём
        // про привязку, не будет до следующих суток. Человек с чужой
        // привязкой видел бы объяснение без двери — ровно то, чего мы
        // избегали веткой при KEYED.
        //
        // Замечено владельцем 14.09 на дебажной сборке: кнопка не
        // появилась, потому что ключ проверяли незадолго до того.
        if (p.getBoolean(K_KEY_BOUND_OTHER, false) && key.isNotEmpty()) {
            rebindable.value = key
            rebindRecoverable.value = when (p.getInt(K_KEY_RECOVERABLE, -1)) {
                1 -> true
                0 -> false
                else -> null
            }
        }

        val device = deviceId(ctx)
        val savedDevice = p.getString(K_DEVICE, "") ?: ""
        val savedStart = trialStartedAt(ctx, device)

        // ПРИВЯЗКА К УСТРОЙСТВУ. Запись, приехавшая с другого устройства
        // (перенос данных, восстановление копии на новый телефон), триал
        // сюда не переносит: здесь он начинается заново.
        //
        // Чистим при этом ВСЁ, что связано с триалом, а не только время
        // старта. Иначе оставшаяся отметка «часы переводили» встретила
        // бы человека на новом устройстве и закончила ему триал, ещё не
        // начавшийся.
        if (savedStart != 0L && savedDevice != device) {
            TunnelLog.add("триал: запись с другого устройства — не засчитываю")
            forgetTrial(ctx)
        } else {
            start = savedStart
            voided = p.getBoolean(K_VOID, false)
            lastSeen = p.getLong(K_SEEN, 0L)
        }
        refresh()
    }

    /** Пересчитывает состояние. Звать при показе экрана и по таймеру. */
    fun refresh() {
        val now = System.currentTimeMillis()
        watchClock(now)

        when {
            key.isNotEmpty() -> {
                state.value = State.KEYED
                leftMs.value = 0L
                checked.value = keyChecked
                expires.value = keyExpires
            }
            // Израсходованный пробный период проверяется ДО start:
            // серверный ключ местного якоря не заводит, и по одному
            // лишь start это выглядело бы как «триал не начинался».
            trialSpent -> {
                state.value = State.OVER
                leftMs.value = 0L
            }
            start == 0L -> {
                state.value = State.NO_TRIAL
                leftMs.value = 0L
            }
            voided -> {
                state.value = State.OVER
                leftMs.value = 0L
            }
            now < start + TRIAL_MS -> {
                state.value = State.TRIAL
                leftMs.value = start + TRIAL_MS - now
            }
            else -> {
                state.value = State.OVER
                leftMs.value = 0L
            }
        }
    }

    /**
     * Перевод часов назад.
     *
     * Сравниваем нынешнее время с тем, когда приложение видело часы в
     * последний раз. Ушли назад больше чем на CLOCK_SLACK_MS — значит
     * их перевели, и триал считается законченным.
     *
     * Отметка «законченный» СОХРАНЯЕТСЯ. Без этого обход был бы
     * тривиальным: перевести часы назад, попользоваться, вернуть как
     * было — и триал снова идёт.
     *
     * Владельца ключа это не касается вовсе: у него часы — его дело.
     */
    private fun watchClock(now: Long) {
        val ctx = appCtx
        if (ctx == null || key.isNotEmpty()) return

        if (start != 0L && !voided &&
            (now < lastSeen - CLOCK_SLACK_MS || now < start - CLOCK_SLACK_MS)
        ) {
            voided = true
            prefs(ctx)?.edit()?.putBoolean(K_VOID, true)?.apply()
            TunnelLog.add("часы переведены назад — пробный период считаю законченным")
        }

        // Отметку двигаем только вперёд и не чаще раза в минуту: refresh()
        // зовётся с экрана каждые полминуты, и писать на диск столько же
        // раз незачем.
        if (now > lastSeen + SEEN_WRITE_MS) {
            lastSeen = now
            prefs(ctx)?.edit()?.putLong(K_SEEN, now)?.apply()
        }
    }

    /**
     * Можно ли поднимать туннель.
     *
     * Непроверенный ключ пускает: иначе его нечем было бы проверить —
     * проверка и есть подключение.
     */
    fun allowed(): Boolean {
        refresh()
        if (pending.isNotEmpty()) return true
        return state.value == State.KEYED || state.value == State.TRIAL
    }

    /**
     * Пароль для AUTH: непроверенный ключ, затем сохранённый.
     *
     * ТЕСТОВЫЙ ПАРОЛЬ ЕСТЬ ТОЛЬКО В ОТЛАДОЧНОЙ СБОРКЕ (задача 56.4).
     * В релизе его нет по двум причинам сразу:
     *
     *   он один на всех, а адрес в туннеле шлюз выдаёт по хешу пароля —
     *   значит все, у кого нет ключа, выбивали бы друг друга;
     *
     *   он лежал бы в APK открытым текстом, то есть был бы известен
     *   любому, кто этот APK вскроет.
     *
     * ПОСЛЕДСТВИЕ, КОТОРОЕ НАДО ЗНАТЬ: в релизе у человека на триале
     * пароля нет вовсе, и туннель не поднимется. Триал станет рабочим
     * только когда появится серверная ручка /v1/trial, выдающая ключ на
     * устройство. Пустая строка здесь — не заглушка, а честный признак
     * того, что подключаться не с чем.
     */
    fun password(): String = when {
        pending.isNotEmpty() -> pending
        key.isNotEmpty() -> key
        BuildConfig.DEBUG -> Config.PASSWORD
        else -> ""
    }

    /** Идёт ли проверка введённого ключа прямо сейчас. */
    fun checking(): Boolean = pending.isNotEmpty()

    fun startTrial() {
        val ctx = appCtx ?: return
        if (start != 0L || trialSpent) return
        val now = System.currentTimeMillis()
        start = now
        voided = false
        lastSeen = now
        markTrialStarted(ctx, deviceId(ctx), now)
        refresh()
        TunnelLog.add("триал начат, 72 часа пошли")
        TrialAlarm.arm(ctx)
    }

    /**
     * Служба отказала в пробном НЕ по пределу выдачи — значит период
     * этого устройства кончился. Запираем триал.
     *
     * Без этого кнопка «Начать 3 дня» оставалась бы после конца периода
     * и честно отказывала на каждое нажатие: сервер теперь ведёт конец
     * периода сам (вариант B кота 2), при переустановке локальная
     * отметка стирается, и по одному лишь ей кнопка возвращалась.
     *
     * Предел выдачи (429) сюда НЕ ведёт — он временный, и запирать по
     * нему значило бы отнять пробный у того, кому он положен.
     */
    fun trialEnded() {
        val ctx = appCtx ?: return
        if (trialSpent) return
        trialSpent = true
        prefs(ctx)?.edit()?.putBoolean(K_TRIAL_SPENT, true)?.apply()
        TunnelLog.add("служба: пробный период кончился — кнопку начала прячу")
        refresh()
    }

    /**
     * Принимает введённый ключ. Возвращает, что сообщить человеку.
     *
     * Ключ пока НЕ сохраняется: сохранит его confirmPending() после
     * того, как туннель действительно встанет.
     */
    fun setPending(raw: String): String {
        val k = raw.trim()
        if (k.isEmpty()) return "ключ пустой"
        if (k.length < 8) return "ключ слишком короткий"
        pending = k
        // Сам ключ в лог НЕ пишем: это пароль подключения.
        TunnelLog.add("ключ принят, проверяю подключением (${k.length} символов)")
        return "проверяю ключ подключением"
    }

    /**
     * Ключ принят СЕРВЕРОМ. Сохраняем сразу.
     *
     * Раньше ключ сохранялся только после вставшего туннеля, и человек,
     * получив «ключ ok», не видел никакого исхода — сохранять было
     * нечем и нечего показывать. Теперь вердикт API сам по себе
     * событие: ключ сохранён, доступ открыт, а подтверждение
     * подключением придёт следом.
     */
    /** Источники ключа. Значения хранятся, менять нельзя. */
    const val SOURCE_TRIAL = "trial"
    const val SOURCE_SUB = "sub"

    fun acceptKey(
        k: String,
        expiresAt: Long = Api.UNKNOWN_EXPIRY,
        staleAge: Long = 0L,
        source: String = "",
    ) {
        val ctx = appCtx ?: return
        if (k.isEmpty()) return
        pending = ""
        key = k
        keyChecked = false
        keyExpires = expiresAt
        keySource = source
        prefs(ctx)?.edit()
            ?.putString(K_KEY, k)
            ?.putBoolean(K_KEY_CHECKED, false)
            ?.putString(K_KEY_SOURCE, source)
            ?.putLong(K_KEY_EXPIRES, expiresAt)
            ?.putLong(K_KEY_ASKED_AT, System.currentTimeMillis() - staleAge * 1000L)
            // Новый ключ — новая привязка. Прежняя отметка «занят
            // другим» к нему не относится ни при каких условиях.
            ?.remove(K_KEY_BOUND_OTHER)
            ?.apply()
        // Как и при перепроверке: отметка свежести ставится на возраст
        // данных, а не на «сейчас».
        keyCheckedAt = System.currentTimeMillis() - staleAge * 1000L
        problem.value = ""
        // Ключ принят — переносить больше нечего. Снимаем здесь, в одном
        // месте на все пути: ввод руками, перенос, пробный, подписка.
        rebindable.value = ""
        refresh()
        // Сам ключ в лог не пишем — это пароль подключения.
        TunnelLog.add("ключ сохранён (источник: ${source.ifEmpty { "введён" }}), " +
            "подключением ещё не проверен")
        // Фраза считается ОДИН раз и идёт и на экран, и в лог: два
        // места с одним смыслом расходятся, мы это уже проходили.
        val said = when (source) {
            SOURCE_TRIAL -> "Пробный период начался"
            SOURCE_SUB -> "Подписка активна"
            else -> "Ключ принят"
        }
        Notice.say(said)
        // СОБЫТИЕМ, а не только add: в релизе add молчит, и до 0.1.113
        // про доступ там не было НИ ОДНОЙ строки — ровно про то, на чём
        // мы 06.09 ослепли с подписчиком из Play. Внутренностей здесь
        // нет: что случилось, без слова о том, как оно устроено.
        TunnelLog.event(said.lowercase())
        // Ключ есть — напоминать про конец триала больше не о чем.
        TrialAlarm.cancel(ctx)
    }

    /**
     * Туннель встал — ключ рабочий.
     *
     * Закрывает оба пути сразу: и непроверенный ключ, введённый когда
     * API молчал, и уже сохранённый по слову сервера.
     */
    fun confirmPending() {
        val ctx = appCtx ?: return
        val p = pending
        if (p.isNotEmpty()) {
            pending = ""
            key = p

            // ВМЕСТЕ С КЛЮЧОМ МЕНЯЕТСЯ И ВСЁ, ЧТО МЫ ПРО НЕГО ЗНАЛИ.
            //
            // Здесь стояла одна строка — сохранить ключ. Источник и срок
            // оставались от ПРЕЖНЕГО ключа, и это тихо ломало доступ.
            //
            // Разбор случая 06.09, дефект владельца. Человек начинает
            // пробный период: acceptKey кладёт триальный ключ, source =
            // trial, expires = конец триала. Потом вводит ключ из бота —
            // ручной ввод идёт через setPending и приходит СЮДА. Ключ
            // подменялся, а source оставался "trial" и expires — концом
            // триала. Дальше:
            //
            //   срок. Экран показывал оплаченный ключ истекающим ровно
            //   через 72 часа, а checkDue у самого срока начинал
            //   переспрашивать службу при каждом открытии;
            //
            //   источник. Ветка trialOver в rejectKey срабатывает по
            //   keySource == SOURCE_TRIAL. Любой плохой вердикт по
            //   ботовому ключу выставлял trialSpent — то есть клиент
            //   ЗАПИРАЛ пробный период навсегда и говорил заплатившему
            //   «пробный период закончился, он даётся один раз на
            //   устройство».
            //
            // Отсюда и жалоба «ключ отваливается через трое суток, как
            // при пробном периоде»: он и вёл себя как пробный, потому
            // что мы сами его так пометили.
            //
            // Ключ пришёл из ручного ввода: источника у него нет, срок
            // неизвестен до ответа службы. Отметку свежести обнуляем,
            // чтобы ближайший опрос узнал настоящий срок, а не ждал
            // сутки от чужого замера.
            keySource = ""
            keyExpires = Api.UNKNOWN_EXPIRY
            keyCheckedAt = 0L
            prefs(ctx)?.edit()
                ?.putString(K_KEY, p)
                ?.remove(K_KEY_SOURCE)
                ?.putLong(K_KEY_EXPIRES, Api.UNKNOWN_EXPIRY)
                ?.putLong(K_KEY_ASKED_AT, 0L)
                ?.apply()
            TrialAlarm.cancel(ctx)
        }
        if (key.isEmpty() || keyChecked) {
            refresh()
            return
        }
        keyChecked = true
        prefs(ctx)?.edit()?.putBoolean(K_KEY_CHECKED, true)?.apply()
        refresh()
        TunnelLog.add("ключ проверен подключением")
        TunnelLog.event("ключ проверен подключением")
    }

    /** Подключение не удалось — ключ не подтверждён. */
    fun dropPending(why: String) {
        if (pending.isEmpty()) return
        pending = ""
        TunnelLog.add("ключ НЕ подтвердился: $why")
        TunnelLog.event("ключ не подтвердился: $why")
        refresh()
    }

    /**
     * Что написать про ключ.
     *
     * Три случая из задачи 53.1, и ни один не выдуман: срок берётся из
     * ответа службы, а когда его там не было — так и говорится.
     */
    fun keyText(): String {
        // Читаем ИМЕННО состояния Compose, а не @Volatile-поля рядом.
        // Экран так перерисовывается сам при любой смене срока; иначе
        // пришлось бы трогать их на экране голыми выражениями, а такую
        // строку первый же читающий примет за мусор и удалит.
        val until = expires.value
        val confirmed = checked.value
        return when {
            until > 0L -> "Доступ до " + dateText(until)

            until == 0L -> "Бессрочный ключ"

            // Ключ работает — это подтвердил туннель, — но срока мы не
            // спрашивали или не дозвонились. Врать про бессрочность нельзя.
            confirmed -> "Ключ работает, срок неизвестен"

            else -> "Ключ принят, проверяю подключением"
        }
    }

    /** «5 ч 12 мин» */
    fun leftText(): String {
        val ms = leftMs.value
        if (ms <= 0L) return "0 мин"
        val min = ms / 60000L
        val h = min / 60
        val m = min % 60
        val d = h / 24
        val hr = h % 24
        // Пробный период теперь трёхдневный: часами его уже не показать
        // ("71 ч 30 мин" читается плохо). До суток — часы и минуты,
        // дальше — дни и часы.
        return when {
            d > 0 -> "$d дн $hr ч"
            h > 0 -> "$h ч $m мин"
            else -> "$m мин"
        }
    }

    /** Спрашивали ли уже разрешение на уведомления. */
    fun notifAsked(): Boolean = appCtx?.let { prefs(it)?.getBoolean(K_NOTIF_ASKED, false) } ?: true

    fun markNotifAsked() {
        val ctx = appCtx ?: return
        prefs(ctx)?.edit()?.putBoolean(K_NOTIF_ASKED, true)?.apply()
    }

    // ------------------------------------------------------------------
    // ПЕРЕПРОВЕРКА КЛЮЧА
    //
    // Ключ могут продлить, отозвать или удалить, и человек должен это
    // увидеть. Спрашивать при каждом подключении нельзя: потолок
    // /v1/key — десять обращений в час (договор, 47.2), а подъёмов
    // туннеля в мигающей сети бывает до девяноста.
    //
    // Отсюда три повода, принятые владельцем:
    //
    //   1. раз в сутки при открытии приложения;
    //   2. при каждом открытии, если до конца срока меньше трёх суток —
    //      это как раз тот отрезок, когда человек идёт продлевать и
    //      хочет убедиться, что продление дошло;
    //   3. немедленно, если туннель не поднялся, а ключ у нас числится
    //      годным. Расхождение между нашей записью и отказом шлюза —
    //      самый вероятный признак того, что ключ больше не тот.
    //
    // Повод 1 закрывает и случай «срок неизвестен»: у такого ключа
    // отметка времени нулевая, и первое же открытие с сетью его
    // выяснит.
    // ------------------------------------------------------------------

    private const val DAY_MS = 24L * 60L * 60L * 1000L
    private const val NEAR_END_MS = 3L * DAY_MS

    /** Есть ли сохранённый ключ. */
    fun hasKey(): Boolean = key.isNotEmpty()

    /**
     * Подтверждён ли ключ УСПЕШНЫМ ПОДКЛЮЧЕНИЕМ, а не ответом API.
     *
     * Разница существенная: наш API знает ключ сразу, а шлюз читает
     * список паролей раз в минуту и всё это время о свежем ключе не
     * подозревает. Пока ключ не подтверждён подключением, отказ шлюза
     * — ожидаемое состояние, а не отказ. См. MeridianVpnService.
     */
    fun keyProven(): Boolean = keyChecked

    /**
     * Откуда взялся нынешний ключ: SOURCE_TRIAL, SOURCE_SUB или пусто
     * (введён руками).
     *
     * Нужен там, где текст для человека зависит не от ответа службы, а
     * от того, как ключ попал в приложение: служба про пробный период и
     * подписку не знает, а мы помним. См. deactivatedText в Paths.kt.
     */
    fun sourceOfKey(): String = keySource

    /**
     * Идёт ли ПРОБНЫЙ период — в любой из двух его форм.
     *
     * Форм две, и это не очевидно: локальный якорь (State.TRIAL, когда
     * сервер молчал) и СЕРВЕРНЫЙ пробный КЛЮЧ (source=trial). Второй
     * хранится как обычный ключ, поэтому state у него KEYED, а не TRIAL —
     * ровно на этом 13.09 не появилось предложение купить в настройках:
     * условие смотрело только на State.TRIAL, а у владельца был пробный
     * ключ с датой («Доступ до 15.09.26»), то есть KEYED.
     *
     * Купленный ключ (source sub или введён вручную) сюда НЕ попадает:
     * там доступ уже оплачен, предлагать покупку незачем.
     */
    fun onTrial(): Boolean =
        state.value == State.TRIAL ||
            (state.value == State.KEYED && keySource == SOURCE_TRIAL)

    /**
     * Тот ли это ключ, что уже сохранён.
     *
     * Сравнение, а не выдача: наружу ключ не отдаём никогда — это
     * пароль подключения. Нужно, чтобы не объявлять человеку об
     * «активной подписке» при каждом открытии экрана.
     */
    fun sameKey(k: String): Boolean = key.isNotEmpty() && key == k

    /** Настал ли повод спросить службу (поводы 1 и 2). */
    private fun checkDue(now: Long): Boolean {
        if (key.isEmpty()) return false
        if (now - keyCheckedAt >= DAY_MS) return true
        // Меньше трёх суток до конца — включая уже прошедший срок:
        // истёкший ключ надо переспрашивать при каждом открытии, пока
        // служба не подтвердит, что он и правда кончился.
        if (keyExpires > 0L && keyExpires * 1000L - now <= NEAR_END_MS) return true
        return false
    }

    /**
     * Пока идут МЕСТНЫЕ сутки — догнать серверный ключ.
     *
     * ЗАЧЕМ. Кнопка «начать сутки» при молчащем API запускает местный
     * якорь. Если на этом остановиться, местные сутки и серверный ключ
     * разойдутся НАВСЕГДА: состояние уже TRIAL, кнопки на экране нет, и
     * второй попытки взять ключ не будет никогда.
     *
     * ЗВАТЬ ТОЛЬКО С ФОНОВОГО ПОТОКА.
     *
     * ПРО ЧАСТОТУ — отступление от буквы задачи, и вот его причина.
     * Просили спрашивать при каждом открытии. Сегодняшний предел выдачи
     * — три в час НА АДРЕС, и три открытия приложения подряд его
     * исчерпают, после чего в логе будут одни отказы. Поэтому здесь
     * пауза в полчаса: расхождение всё равно сходится за минуты, а
     * лимит остаётся цел.
     *
     * Когда предел станет 10 в час и повторы перестанут его жечь
     * (задача 59.6), паузу можно снять — это одна константа.
     */
    fun upgradeLocalTrial() {
        val ctx = appCtx ?: return
        refresh()
        // Ключ есть — догонять нечего. Триала нет — просить не за что.
        if (key.isNotEmpty() || state.value != State.TRIAL) return

        val now = System.currentTimeMillis()
        val asked = prefs(ctx)?.getLong(K_TRIAL_ASKED_AT, 0L) ?: 0L
        if (now - asked < TRIAL_ASK_EVERY_MS) return
        prefs(ctx)?.edit()?.putLong(K_TRIAL_ASKED_AT, now)?.apply()

        TunnelLog.add("триал местный — пробую догнать серверный ключ")
        when (val answer = Api.startTrial()) {
            is Api.TrialAnswer.Granted -> {
                // Серверный ключ главнее местного счёта: с ним туннель
                // поднимется, а местные сутки — только отсчёт.
                acceptKey(answer.key, answer.expiresAt, source = SOURCE_TRIAL)
            }
            // Отказ и молчание одинаково безобидны: местные сутки идут
            // дальше, доступ не трогаем. Причина уже в логе.
            is Api.TrialAnswer.Refused -> Unit
            is Api.TrialAnswer.NoAnswer -> Unit
        }
    }

    /**
     * Спрашивает службу про сохранённый ключ.
     *
     * ЗВАТЬ ТОЛЬКО С ФОНОВОГО ПОТОКА — внутри поход в сеть до 10 секунд.
     *
     * @param force повод 3: спросить независимо от сроков
     */
    fun refreshKey(force: Boolean = false) {
        val ctx = appCtx ?: return
        val k = key
        if (k.isEmpty()) return
        val now = System.currentTimeMillis()
        if (!force && !checkDue(now)) return

        when (val answer = Api.checkKey(k)) {
            is Api.KeyAnswer.Verdict -> {
                val v = answer.v
                // ОТМЕТКА СВЕЖЕСТИ СТАВИТСЯ НА ВОЗРАСТ ДАННЫХ, а не на
                // «сейчас». Ответ из кэша может быть суточной давности;
                // если считать его свежим, повод «раз в сутки» не
                // сработает ещё сутки, и мы никогда не спросим базу
                // по-настоящему. Вычитая возраст, мы говорим правду:
                // данные настолько стары, насколько стары.
                keyCheckedAt = System.currentTimeMillis() - v.staleAge * 1000L
                prefs(ctx)?.edit()?.putLong(K_KEY_ASKED_AT, keyCheckedAt)?.apply()

                // Занят ли ключ другим устройством — решаем на КАЖДОМ
                // вердикте, а не только на плохом: иначе кнопка переноса,
                // раз появившись, осталась бы висеть и после того, как
                // ключ снова стал нашим.
                noteRebindable(key, v)

                if (v.usable()) {
                    // РАСХОЖДЕНИЕ ШЛЮЗА И СЛУЖБЫ — НАЗЫВАЕМ ВСЛУХ.
                    //
                    // С force=true сюда приходят ТОЛЬКО после отказа
                    // подключения (повод 3). Годный вердикт в этот миг
                    // означает, что шлюз пароль не принял, а служба
                    // считает ключ живым — то есть беда не в ключе, и
                    // искать её в ключе бесполезно.
                    //
                    // 06.09 это стоило дня разбирательства: у владельца
                    // ключ из бота «отваливался» через трое суток.
                    // Оказалось, что триал и ключ висят на одном
                    // device_id, у устройства один пир, и по истечении
                    // ТРИАЛА сервер сносил пир целиком — ключ при этом
                    // оставался годным с длинным сроком (кот 2, замер по
                    // живой базе: 49 ботовых ключей, сроки 20-40 суток,
                    // ни одного с 72 часами).
                    //
                    // Без этой строки в логе видно только «подключиться
                    // не удалось», и вина ложится на ключ, который ни
                    // при чём. Ключ мы при этом НЕ трогаем — он и правда
                    // годен, и когда пир вернут, доступ поднимется сам.
                    if (force) {
                        TunnelLog.add(
                            "ключ: шлюз его НЕ ПРИНЯЛ, а служба считает годным до " +
                                dateText(v.expiresAt) + " — расхождение на стороне службы, " +
                                "ключ не трогаю"
                        )
                        TunnelLog.event(
                            "сервер подтверждает ключ, но подключение не принято"
                        )
                    }
                    if (v.expiresAt != keyExpires) {
                        keyExpires = v.expiresAt
                        prefs(ctx)?.edit()?.putLong(K_KEY_EXPIRES, v.expiresAt)?.apply()
                        TunnelLog.add("ключ: срок обновлён — " + keyText())
                        Notice.say(keyText())
                    }

                    // СНИМАЕМ ЧУЖУЮ МЕТКУ «ПРОБНЫЙ» САМИ, БЕЗ ПОВТОРНОГО
                    // ВВОДА КЛЮЧА.
                    //
                    // До 0.1.111 confirmPending менял ключ, оставляя
                    // источник от прежнего: у того, кто сначала взял
                    // пробный период, а потом ввёл ключ из бота, ботовый
                    // ключ оставался помеченным пробным. Правка чинит
                    // будущие вводы, но уже сохранённую метку не трогает
                    // — она лежит в настройках и сама не исчезнет.
                    //
                    // Повторный ввод её бы снял, но в сборке для Play
                    // ввода ключа больше нет, а пострадавший как раз
                    // оттуда. Значит чинить надо без него.
                    //
                    // ВЫВОД ЗДЕСЬ СТРОГИЙ, А НЕ ДОГАДКА: пробный ключ по
                    // построению не живёт дольше пробного периода. Служба
                    // даёт срок ДАЛЬШЕ, чем TRIAL_MS от сегодня — значит
                    // это заведомо не пробный ключ, чем бы его ни
                    // пометили у нас.
                    //
                    // Цена ошибки в эту сторону мала: метка влияет на
                    // формулировки и на ветку trialOver, которая запирает
                    // пробный период. Снять её лишний раз — потерять
                    // запирание у того, кто пробный и так истратил;
                    // оставить чужую — сказать заплатившему «пробный
                    // период закончился» и запереть пробный по чужому
                    // поводу.
                    if (keySource == SOURCE_TRIAL && v.expiresAt > 0L &&
                        v.expiresAt * 1000L - System.currentTimeMillis() > TRIAL_MS
                    ) {
                        keySource = ""
                        prefs(ctx)?.edit()?.remove(K_KEY_SOURCE)?.apply()
                        TunnelLog.add(
                            "ключ помечен пробным, а служба даёт срок дольше пробного " +
                                "периода — метка чужая, снимаю"
                        )
                        TunnelLog.event(
                            "отметка пробного периода снята — ключ действует дольше"
                        )
                    }
                    problem.value = ""
                    if (v.stale) {
                        TunnelLog.add("ключ: подтверждён по данным ${v.ageText()} — база была недоступна")
                    }
                } else if (!v.trustworthyRefusal()) {
                    // ЭТОГО НЕ ДОЛЖНО СЛУЧАТЬСЯ: в кэш кладётся только
                    // «ok», значит плохого вердикта со старыми данными
                    // не бывает. Пришло — это ошибка службы, и ключ мы
                    // не трогаем. Разбор цены ошибки — у
                    // Api.KeyVerdict.trustworthyRefusal().
                    TunnelLog.add(
                        "ключ: плохой вердикт пришёл со СТАРЫХ данных (${v.ageText()}) — " +
                            "так быть не должно, ключ НЕ стираю"
                    )
                } else if (force) {
                    // СТИРАЕМ ТОЛЬКО ПРИ ОТКАЗЕ ПОДКЛЮЧЕНИЯ (force=true,
                    // повод 3): шлюз ключ не принял И /v1/key говорит
                    // «негоден» — смерть подтверждена обоими.
                    rejectKey(v)
                } else {
                    // СУТОЧНЫЙ ОПРОС (повод 1/2) РАБОЧИЙ КЛЮЧ НЕ СТИРАЕТ.
                    //
                    // Баг тестировщика 29.08: ключ из бота слетал ровно
                    // через сутки. Причина — вот здесь: первые сутки
                    // опроса нет, на исходе суток он срабатывает, /v1/key
                    // отвечает «негоден», и ключ стирался — при том что
                    // шлюз его исправно принимал, туннель работал.
                    //
                    // Власть над доступом у ШЛЮЗА, а не у /v1/key: ключ,
                    // с которым встаёт туннель, годен по определению.
                    // Опрос — совет, и стереть по совету рабочий ключ
                    // значит потерять оплаченное (у подписки Play человек
                    // ключа даже не видел). Асимметрия та же, что в
                    // trustworthyRefusal: ошибка «оставил негодный» стоит
                    // одной неудачной попытки — шлюз сам не пустит; ошибка
                    // «стёр рабочий» стоит доступа у заплатившего.
                    //
                    // Настоящую смерть ловит повод 3: как только ключ
                    // перестанет поднимать туннель, refreshKey(force=true)
                    // придёт сюда с тем же вердиктом и сотрёт. Расхождение
                    // /v1/key со шлюзом — вопрос к службе, не повод рушить
                    // доступ у человека.
                    TunnelLog.add(
                        "ключ: /v1/key вернул «${v.state}», но туннель его принимает — " +
                            "по суточному опросу НЕ стираю, решит подключение"
                    )
                }
                refresh()
            }

            // МОЛЧАНИЕ НЕ ОТБИРАЕТ ДОСТУП. Ни отказ службы, ни
            // недоступный сервер, ни непонятый вердикт. Правило одно на
            // весь клиент: наша неспособность спросить — не повод
            // наказывать человека.
            is Api.KeyAnswer.Refused ->
                TunnelLog.add("ключ: перепроверить не вышло («${answer.error}»), оставляю как есть")

            is Api.KeyAnswer.NoAnswer ->
                TunnelLog.add("ключ: перепроверить не вышло (${answer.why}), оставляю как есть")
        }
    }

    /**
     * Ключ больше не годится: истёк, отозван, удалён, отключён.
     *
     * Ключ стирается — иначе он молча оставался бы паролем подключения,
     * с которым шлюз всё равно не пустит. Причина остаётся на экране.
     *
     * Живой туннель это НЕ рвёт: доступ проверяется только там, где
     * туннель начинает подниматься (MeridianVpnService), а здесь мы
     * лишь меняем запись.
     */
    private fun rejectKey(v: Api.KeyVerdict) {
        val ctx = appCtx ?: return
        // Текст причины считаем ДО того, как забудем признак пробного:
        // иначе про пробный период сказать будет уже нечем.
        val text = keyProblemText(v)
        // Потеря доступа — самое важное, что вообще может случиться с
        // человеком, и до 0.1.113 в релизе она не оставляла ни строки.
        TunnelLog.event("доступ прекращён: $text")
        key = ""
        // Ключа больше нет — переносить нечего. Кнопка над стёртым
        // ключом звала бы потратить попытку впустую.
        rebindable.value = ""
        keyChecked = false
        keyExpires = Api.UNKNOWN_EXPIRY

        // Пробный период считается израсходованным ТОЛЬКО ПО СРОКУ.
        //
        // Раньше сюда годилась любая причина смерти ключа, и это было
        // ошибкой с тяжёлыми последствиями: флаг ставится навсегда,
        // переживает перезапуск и уезжает в резервную копию, а
        // startTrial() после него не делает ничего. Снять его можно
        // было только стиранием данных приложения.
        //
        // 26.08 кот 2 нашёл у себя дефект, который бьёт ровно сюда:
        // неподключённые пробные забираются через два часа, а признак
        // "подключались" наши RAW-соединения не проставляют никогда.
        // То есть работающий пробный ключ удалялся из-под человека, наш
        // клиент видел deleted — и запирал пробный период НАСОВСЕМ,
        // хотя сервер разрешает попросить его заново.
        //
        // expired — да, сутки прошли, израсходован честно. Всё
        // остальное (deleted, revoked, deactivated, непонятный ответ) —
        // это "ключ забрали", а не "человек попользовался", и запирать
        // за это нельзя.
        //
        // ПОПРАВКА ОТ 26.08, ПОЗЖЕ В ТОТ ЖЕ ДЕНЬ. Сначала я оставил
        // здесь один expired, и это было слишком узко: кончившийся
        // пробный приходит от службы как DEACTIVATED, а не EXPIRED —
        // на этом же построен keyProblemText ниже. С одним expired
        // человек после конца суток мог нажать "начать сутки" снова и
        // получить обратно тот же самый мёртвый ключ.
        //
        // Итог: expired и deactivated — пробный отработал своё,
        // запираем. deleted, revoked, непонятный ответ — ключ забрали,
        // не запираем.
        val trialOver = keySource == SOURCE_TRIAL &&
            (v.state == Api.KeyState.EXPIRED || v.state == Api.KeyState.DEACTIVATED)
        if (trialOver) {
            trialSpent = true
        } else if (keySource == SOURCE_TRIAL) {
            TunnelLog.add("пробный ключ забрали не по сроку — пробный период не запираю")
        }
        keySource = ""

        prefs(ctx)?.edit()
            ?.remove(K_KEY)
            ?.remove(K_KEY_CHECKED)
            ?.remove(K_KEY_EXPIRES)
            ?.remove(K_KEY_SOURCE)
            ?.remove(K_KEY_BOUND_OTHER)
            ?.putBoolean(K_TRIAL_SPENT, trialSpent)
            ?.apply()

        // КОНЕЦ ПРОБНОГО ПЕРИОДА НЕ ДУБЛИРУЕМ.
        //
        // Когда пробный отработал своё, экран уже показывает это
        // заголовком (AccessScreen, State.OVER: «Пробный период
        // закончился…»). Синяя строка problem повторяла тот же текст
        // слово в слово — человек видел одну и ту же надпись дважды.
        //
        // Поэтому для этого случая problem пустой: единственный источник
        // — заголовок. Причина всё равно уходит в лог, диагностику это
        // не обедняет. Прочие причины смерти ключа (подписка кончилась,
        // доступ отозван) заголовком НЕ покрыты, и для них строка нужна.
        if (trialOver) {
            problem.value = ""
            TunnelLog.add("пробный период закончился ($text) — сказано заголовком, синюю строку не дублирую")
        } else {
            problem.value = text
            TunnelLog.add("ключ больше не годится: $text")
            Notice.problem(problem.value)
        }
        // Ключа нет — напоминания о конце триала снова уместны.
        TrialAlarm.arm(ctx)
    }

    /**
     * Что сказать человеку про негодный ключ.
     *
     * Текст службы главнее нашего: он один и тот же во всех клиентах.
     * Свои строки — запасные, и в них дата берётся по правилу кота 2:
     * есть expires_at — он, иначе since, иначе без даты.
     */
    /**
     * Запомнить ключ, который занят другим устройством, — или забыть.
     *
     * Зовётся из ОБОИХ мест, куда приходит вердикт: ввод руками и
     * перепроверка сохранённого. Больше нигде кнопка переноса не
     * заводится и не гасится — иначе два места разошлись бы, и кнопка
     * осталась бы висеть над ключом, который давно принят.
     *
     * ЗАМЕНЁННЫЙ КЛЮЧ (ROTATED) СЮДА НЕ ПОПАДАЕТ НАМЕРЕННО. Его нельзя
     * перенести — его больше нет, и /v1/unbind ответит bad_key, потратив
     * человеку попытку впустую. Дверь для него другая, и о ней говорит
     * keyProblemText: взять новый ключ там, куда его прислал сервер.
     */
    fun noteRebindable(k: String, v: Api.KeyVerdict) {
        val other = k.isNotEmpty() &&
            v.bound == Api.Bound.OTHER &&
            v.state != Api.KeyState.ROTATED
        rebindable.value = if (other) k else ""
        rebindRecoverable.value = if (other) v.recoverable else null
        // Сохраняем ТОЛЬКО для своего ключа. Ключ, набранный в поле и
        // ещё не принятый, сохранять нельзя по тому же правилу, по
        // которому не сохраняется pending: опечатка пережила бы
        // перезапуск и звала бы переносить несуществующее.
        if (k == key) {
            prefs(appCtx ?: return)?.edit()
                ?.putBoolean(K_KEY_BOUND_OTHER, other)
                // Три состояния в одном числе: -1 не знаем, 0 нет, 1 да.
                // Отдельным булевым полем их не выразить, а заводить два
                // ключа настроек ради одного признака — хуже.
                ?.putInt(K_KEY_RECOVERABLE, if (!other) -1 else when (v.recoverable) {
                    true -> 1
                    false -> 0
                    null -> -1
                })
                ?.apply()
        }
    }

    fun keyProblemText(v: Api.KeyVerdict): String {
        // ПРОБНЫЙ КЛЮЧ, КОТОРЫЙ ДЕАКТИВИРОВАЛИ, — это конец пробного
        // периода, а не отключённый ключ. Здесь мы главнее службы: она
        // не знает, что ключ пробный, а мы помним, как его получили.
        //
        // Второе предложение обязательно: без него человек пойдёт
        // нажимать «начать сутки» ещё раз и получит тот же самый ключ.
        if (keySource == SOURCE_TRIAL && v.state == Api.KeyState.DEACTIVATED) {
            return "пробный период закончился. Пробный период даётся " +
                "один раз на устройство"
        }
        // ОТМЕНА ИЛИ ВОЗВРАТ ПОДПИСКИ. Google перестал подтверждать
        // покупку, наш сервер отозвал ключ. Для человека это «подписка
        // закончилась», а не «неверный ключ» и не «идите в поддержку»:
        // он сам её и отменил, либо вернул деньги.
        if (keySource == SOURCE_SUB &&
            (v.state == Api.KeyState.REVOKED ||
                v.state == Api.KeyState.EXPIRED ||
                v.state == Api.KeyState.DEACTIVATED)
        ) {
            return "подписка закончилась"
        }
        // ПРИВЯЗКА К ЧУЖОМУ УСТРОЙСТВУ — РАНЬШЕ СООБЩЕНИЯ СЛУЖБЫ.
        //
        // Особый случай: ключ сам жив (verdict=ok), поэтому message от
        // службы положительный — «ключ действует, срок не ограничен».
        // Показать его тут значит соврать: ключ действует, но НЕ на этом
        // устройстве, а человек видит хорошее и не понимает, почему
        // ничего не происходит (лог владельца 13.09, дебаг с device_id
        // отличным от релизного). Про привязку говорим сами и до message.
        // ЗАМЕНЁННЫЙ КЛЮЧ ОБЪЯСНЯЕМ ДО ПРИВЯЗКИ, а не после.
        //
        // Порядок здесь — часть смысла, а не стиль. Ключ, заменённый при
        // переносе, может прийти и с чужой привязкой (новым владельцем
        // стало другое устройство). Сказать про привязку значит послать
        // человека переносить ключ, которого больше нет, — он потратит
        // попытку и получит bad_key.
        //
        // «Заменён» — знание более точное и ведёт к нужной двери: взять
        // новый ключ там, где сервер его прислал.
        if (v.state == Api.KeyState.ROTATED) {
            val since = if (v.since > 0L) " " + dateText(v.since) else ""
            return "этот ключ заменён$since при переносе на другое " +
                "устройство — возьмите новый в боте"
        }
        if (v.bound == Api.Bound.OTHER) {
            return "этот ключ уже используется на другом устройстве"
        }
        if (v.message.isNotEmpty()) return v.message
        val when_ = v.dateToShow()
        val date = if (when_ > 0L) " " + dateText(when_) else ""
        return when (v.state) {
            Api.KeyState.EXPIRED -> "подписка кончилась$date — нужно продлить"
            Api.KeyState.REVOKED -> "доступ отозван$date — напишите в поддержку"
            Api.KeyState.DELETED -> "ключ удалён$date — напишите в поддержку"
            Api.KeyState.DEACTIVATED -> "ключ отключён$date — напишите в поддержку"
            Api.KeyState.UNKNOWN -> "такого ключа нет — проверьте, что ввели"
            else -> "ключ занят другим устройством"
        }
    }

    private fun dateText(unixSeconds: Long): String =
        java.text.SimpleDateFormat("dd.MM.yy", java.util.Locale.US)
            .format(java.util.Date(unixSeconds * 1000L))

    /** Когда кончается триал. 0 — не начинался. */
    fun endsAt(): Long = if (start == 0L) 0L else start + TRIAL_MS

