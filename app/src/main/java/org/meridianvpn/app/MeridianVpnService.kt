     * Пропала сеть. Наша ли — решаем сравнением с запомненной.
     *
     * Приходит НЕ с главного потока.
     */
    /**
     * Сменилась ли сеть с начала текущей попытки.
     *
     * Обе неизвестны — считаем, что не менялась: отказывать без причины
     * хуже, чем попробовать.
