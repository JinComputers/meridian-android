    /**
     * Прибить сокет к сети оператора, поверх protect().
     *
     * Зачем ВТОРОЕ действие, если protect() уже отработал: protect()
     * уводит мимо туннеля МАРШРУТ, но не прибивает адрес источника.
     * bindSocket() ставит сокету метку конкретной сети, и по ней ядро
     * берёт и таблицу маршрутов, и адрес источника из этой сети — на
     * всю жизнь сокета, а не на один sendto.
     *
     * Разбор дефекта — в комментарии к listenProtected в engine/race.go:
     * AUTH проходил всегда, а сразу после establish() отправка
     * переставала доходить до шлюза.
     *
     * fromFd ДУБЛИРУЕТ дескриптор. Метка живёт на самом сокете, общем у
     * оригинала и дубликата, поэтому закрытие дубликата ничего не
     * ломает, а оригиналом по-прежнему владеет движок. Инвариант про
     * владение дескриптором не нарушается.
     *
     * НЕУДАЧА ЗДЕСЬ НЕ ФАТАЛЬНА. Решает protect(), он уже сказал да;
     * это добавка, и если сети нет или bindSocket отказал, остаётся
     * прежнее поведение, а не отказ подключаться.
     */
    private fun bindToUnderlying(fd: Int) {
        val net = sessionNetwork
        if (net == null) {
            TunnelLog.add("сокет: нижележащая сеть неизвестна — только protect()")
            return
        }
        try {
            val dup = ParcelFileDescriptor.fromFd(fd)
            try {
                net.bindSocket(dup.fileDescriptor)
                TunnelLog.add("сокет прибит к сети ${netWatch.ifaceOf(net)}")
            } finally {
                dup.close()
            }
        } catch (e: Throwable) {
            TunnelLog.add("сокет: bindSocket отказал (${e.javaClass.simpleName}) — только protect()")
        }
    }

    /**
     * Забыть путь, который поднялся и не понёс трафика.
     *
     * «Встал» и «работает» — разные вещи, а память путей считала их
     * одним. Запомненный путь пробуется БЕЗ ГОНКИ, то есть остальные
     * даже не проверяются, и выйти из этого круга было нечем: забывали
     * мы только при провале всей лестницы, а здесь лестница не
     * проваливалась — туннель вставал.
     *
     * ПОЧЕМУ БОЛЬШЕ НЕ СУДИМ ПО rx == 0. Судили, и на этом обожглись:
     * 26.08 в 01:28:54 в немую сессию пришёл РОВНО ОДИН случайный
     * пакет, счётчик перестал быть нулём, путь остался запомненным, и
     * следующая попытка пошла в него же. Отсюда и «работает только с
     * третьего раза».
     *
     * Теперь приговор выносит сторож движка, а не счётчик здесь: он
     * ждёт первого встречного пакета muteLimit и различает «шлюз нас не
     * слышит» и «слышит, но встречного трафика нет». Условие tx > 0 &&
     * rx == 0 осталось вторым рубежом на случай, когда сессия оборвалась
     * раньше, чем сторож успел сказать своё слово.
     */
    /**
     * Системный «Приватный DNS» — в лог, а в строгом режиме ещё и человеку.
     *
     * ЗАЧЕМ. 04.09 на МТС Android выдал «Mobile network has no internet
     * access — Private DNS server cannot be accessed» при строгом режиме
     * с именем dns.google. Уведомление названо явно: беда на СОТОВОЙ
     * сети, то есть оператор не пропускает DoT на 853-й порт. Ни шлюз,
     * ни клиент к этому отношения не имеют — кот 2 замерил, что порт с
     * нашей стороны открыт, а MTU у нас 1100 при его потолке 1200.
     *
     * Но человеку видно одно: включил VPN — интернет пропал. Строгий
     * режим на обычный DNS НЕ откатывается, и разрешение имён умирает
     * целиком. Придёт это к нам, а не к оператору.
     *
     * ПОЧЕМУ ТОЛЬКО СЛОВО, А НЕ ДЕЙСТВИЕ. Настройку выставил человек,
     * она системная, и менять её за него мы не вправе — даже если бы
     * могли. Наше дело назвать причину и место, где чинится.
     *
     * Говорим ОДИН РАЗ за подъём службы: строку эту видят только те, кто
     * настройку осознанно включал, и повторять её каждое подключение
     * значило бы превратить подсказку в назойливость.
     */
    private fun notePrivateDns() {
        val mode: String?
        val host: String?
        try {
            mode = Settings.Global.getString(contentResolver, "private_dns_mode")
            host = Settings.Global.getString(contentResolver, "private_dns_specifier")
        } catch (e: Throwable) {
            // Настройка — сведение, а не необходимость. Уронить ею
            // подъём туннеля было бы обменом хорошего на плохое.
            TunnelLog.add("приватный DNS: состояние прочитать не вышло (${e.message})")
            return
        }

        when (mode) {
            "hostname" -> {
                TunnelLog.add("приватный DNS: строгий режим, сервер ${host ?: "не указан"}")
                TunnelLog.event("включён приватный DNS — в части сетей он мешает связи")
                if (!privateDnsWarned) {
                    privateDnsWarned = true
                    Notice.say(
                        "Включён приватный DNS. Если сайты не открываются, " +
                            "переключите его на «Автоматически» в настройках сети"
                    )
                }
            }

            "off" -> TunnelLog.add("приватный DNS: выключен")
            else -> TunnelLog.add("приватный DNS: автоматически")
        }
    }

    private fun forgetMutePath() {
        // ПОТОКОВАЯ СТУПЕНЬ — ОТДЕЛЬНОЙ ВЕТКОЙ, И ОНА ЗДЕСЬ ПЕРВАЯ.
        //
        // Раньше метод начинался со строки ниже — «нет запомненного
        // пути, уходим», — и на потоке выходил пустышкой: поток мы не
        // запоминаем, rememberedFor у него всегда пуст. Немой поток не
        // оставлял следа, и следующая попытка шла в ту же немоту.
        streamWonFor?.let { key ->
            streamWonFor = null
            PathMemory.noteStreamMute(this, key)
            val n = PathMemory.streamMuteStreak(this, key)
            TunnelLog.add("поток поднялся и не понёс трафика — засчитано ($n) для этой сети")
        }

        val key = rememberedFor ?: return
        rememberedFor = null
        PathMemory.forget(this, key)
        // Прямой UDP онемел — засчитываем для этой сети. forget() выше
        // снял только запомненного кандидата и счётчик гонки; этот
        // счётчик у него свой (DIRECT_MUTE_SUFFIX) и переживает forget.
        // После порога DIRECT_MUTE_SKIP_AFTER лестница пойдёт мимо
        // прямого на релей.
        PathMemory.noteDirectMute(this, key)
        val n = PathMemory.directMuteStreak(this, key)
        TunnelLog.add("прямой UDP онемел — засчитано ($n) для этой сети")
        TunnelLog.event("путь онемел — выбираю заново")
    }

    private fun networkChanged(): Boolean {
        val now = netWatch.activeUnderlying()
        if (now == null && sessionNetwork == null) return false
        return now != sessionNetwork
    }

    /**
     * Есть ли сейчас сеть, по которой вообще можно подключаться.
     *
     * Нужна, чтобы отличить «сети нет» от «подключиться не удалось».
     * Во время звонка на сетях без VoLTE данные приостанавливаются:
     * интерфейс жив, но пакеты не ходят. Android помечает это снятием
     * NET_CAPABILITY_NOT_SUSPENDED (с Android 9); до неё — по отсутствию
     * INTERNET или самой активной сети.
     *
     * Не смогли выяснить — считаем, что сеть ЕСТЬ: приписать «нет сети»
     * по своей ошибке хуже, чем оставить общий текст.
     */
    private fun hasUsableNetwork(): Boolean = try {
        val cm = getSystemService(ConnectivityManager::class.java)
        val net = cm?.activeNetwork
        val caps = net?.let { cm.getNetworkCapabilities(it) }
        when {
            caps == null -> false
            !caps.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET) -> false
            Build.VERSION.SDK_INT >= Build.VERSION_CODES.P &&
                !caps.hasCapability(NetworkCapabilities.NET_CAPABILITY_NOT_SUSPENDED) -> false
            else -> true
        }
    } catch (e: Throwable) {
        true
    }

    private fun onUnderlyingLost(lost: Network) {
        if (lost != sessionNetwork) return
        TunnelLog.add("пропала сеть, на которой стоит сессия — переподключаюсь")
        TunnelLog.event("сеть пропала")
        scheduleReconnect("сеть сессии пропала")
    }

    /**
     * Сеть сессии выжила, но сменила адрес.
     *
     * Обрабатывается так же, как пропажа сети, и по той же причине:
     * адрес-источник нашего сокета больше не существует, все sendto по
     * нему отдают ENETUNREACH. Разница только в том, что Android об
     * этом не скажет ни словом — onLost для такой сети не приходит, и
     * до 09.09 единственным свидетелем был сторож тишины в движке,
     * которому на приговор нужно полторы минуты.
     */
    private fun onUnderlyingAddrChanged(net: Network) {
        if (net != sessionNetwork) return
        TunnelLog.add("сеть сессии сменила адрес — сокет мёртв, переподключаюсь")
        TunnelLog.event("сеть сменила адрес")
        scheduleReconnect("сеть сессии сменила адрес")
    }

    /**
     * Android перестал видеть связь в сети сессии.
     *
     * СЕССИЮ НЕ ГАСИМ. Сигнал шумный, и рвать по нему туннель значило
     * бы менять полторы минуты ожидания на регулярные обрывы на ровном
     * месте. Просим движок проверить канал вне очереди: ответит шлюз —
     * всё продолжится, не ответит — сработает обычный сторож, но через
     * шесть секунд вместо девяноста.
     */
    private fun onUnderlyingSuspect(net: Network) {
        if (net != sessionNetwork) return
        val now = SystemClock.elapsedRealtime()
        val prev = lastSuspectAt.get()
        if (prev != 0L && now - prev < SUSPECT_MIN_GAP_MS) return
        if (!lastSuspectAt.compareAndSet(prev, now)) return
        if (!Engine.suspectNetwork("сеть не проходит проверку связи")) {
            TunnelLog.add("проверять нечего: сессии нет или шлюз работает без эха")
        }
    }

    /**
     * Гасит движок немедленно и назначает новую попытку через паузу.
     *
     * Движок гасим сразу, не дожидаясь паузы: канал уже мёртв, и держать
     * сокет на исчезнувшем маршруте незачем — все sendto по нему всё
     * равно отдают ENETUNREACH. Ждать сторожа тишины (90 с) тем более
     * незачем: мы уже знаем, что канала нет.
     *
     * Пауза растёт при повторных неудачах, а число попыток ограничено:
     * в мигающей сети иначе получится вечный цикл переподключений.
     */
    private fun scheduleReconnect(reason: String, engineAlreadyStopped: Boolean = false) {
        if (shuttingDown.get()) return
        if (!reconnectPending.compareAndSet(false, true)) return

        // KILL SWITCH — ВТОРОЙ РУБЕЖ, ПЕРВЫЙ ТЕПЕРЬ У StateListener.onStopping.
        //
        // До 15.09 этот вызов был единственной защитой и не закрывал
        // зазор целиком для обрывов, которые движок находит сам: TUN он
        // закрывает раньше, чем об этом узнаёт Kotlin. Теперь для этого
        // случая раньше срабатывает onStopping (движок зовёт его ДО
        // закрытия TUN) — а сюда для тех же обрывов мы попадаем уже
        // ПОСЛЕ, через onStopped. Оставлен намеренно как второй шанс:
        // establishBlackhole() идемпотентен, повторный вызов ничего не
        // портит, а если тот, первый, почему-то не удался — здесь есть
        // ещё одна попытка. Для обрывов, которые находит сам Kotlin
        // (пропала сеть, сменился адрес, ACTION_RECONNECT), этот вызов
        // по-прежнему и первый, и решающий: он стоит РАНЬШЕ своего же
        // Engine.stop() ниже по коду, зазора для этих путей нет вовсе.
        establishBlackhole(reason)

        // Как долго прожил туннель до обрыва — считаем ДО обнуления
        // метки. Ноль означает «не поднимался вовсе»: это не «поднялся и
        // упал», а неудачный подъём, у него свой счётчик.
        val wasUp = connectedAt > 0L
        val lived = if (wasUp) System.currentTimeMillis() - connectedAt else 0L
        connectedAt = 0L

        // Поколение вперёд: слушатель старой сессии, увидев своё
        // поколение текущим, погасил бы службу. При обрыве движок уже
        // остановился сам (мы в его колбэке) — второй Engine.stop() был
        // бы повторным входом в движок, поэтому его пропускаем.
        generation.incrementAndGet()
        if (!engineAlreadyStopped) {
            try {
                Engine.stop()
            } catch (e: Throwable) {
                TunnelLog.add("ошибка при остановке: ${e.message}")
            }
        }
        TunnelState.setConnected(false)
        sessionNetwork = null

        main.post {
            // НЕТ СЕТИ — ЖДЁМ ЕЁ, А НЕ СДАЁМСЯ.
            //
            // Отсутствие сети не отказ туннеля: подключать нечего.
            // Предел сдачи (пять попыток, ~47 с) заведён против мигающей
            // сети, а не против перегона метро, где сети нет минутами:
            // 11.09 из-за него клиент за 47 секунд сдался и назад сам не
            // поднялся. Поэтому здесь ни счётчик неудач не растёт, ни
            // предел не проверяется — ждём ровным шагом сколько угодно.
            // Возврат сети поднимет туннель сразу через
            // onUnderlyingAvailable; этот шаг — подстраховка на случай,
            // когда сеть уже вернулась, а колбэк промолчал.
            if (!hasUsableNetwork()) {
                quickDrops = 0
                TunnelLog.add("сети нет — жду возврата, проверю через ${NO_NET_POLL_MS / 1000} с")
                armReconnect(NO_NET_POLL_MS)
                return@post
            }

            // «Поднялся и сразу упал» — отдельный предел. Успешный
            // подъём обнулил счётчик неудач, и без этого предела цикл
            // «встал → через 8 с немота → встал» шёл бы молча и вечно.
            if (wasUp) {
                if (lived < QUICK_DROP_MS) {
                    quickDrops++
                } else {
                    quickDrops = 0
                }
            }
            if (reconnectFails >= RECONNECT_MAX_FAILS || quickDrops >= QUICK_DROP_LIMIT) {
                val why = if (quickDrops >= QUICK_DROP_LIMIT)
                    "$quickDrops раз подряд туннель падал сразу после подъёма"
                else "$reconnectFails попыток подряд не удались"
                TunnelLog.add("сдаюсь: $why")
                Notice.problem("Связь потеряна: $why")
                reconnectPending.set(false)
                quickDrops = 0
                shutdownService()
                return@post
            }
            // Первая попытка — короткая пауза; со второй растёт по
            // большему из двух счётчиков: 1, 3, 6, 12, 24 с.
            val steps = maxOf(reconnectFails, quickDrops)
            val delay = if (steps == 0) {
                RECONNECT_FIRST_MS
            } else {
                RECONNECT_BASE_MS shl minOf(steps - 1, RECONNECT_MAX_SHIFT)
            }
            TunnelLog.add("переподключение через ${delay / 1000} с ($reason)")
            armReconnect(delay)
        }
    }

    /**
     * Ставит отложенную попытку и оставляет reconnectPending поднятым
     * как ЖЕТОН ВЛАДЕНИЯ.
     *
     * Жетон снимает тот, кто попытку и запускает: либо этот таймер по
     * сроку, либо onUnderlyingAvailable, когда сеть вернулась раньше.
     * Кто первым снял true→false, тот и поднимает; второй видит false и
     * молчит. Без жетона возврат сети и сработавший таймер подняли бы
     * два туннеля разом.
     */
    private fun armReconnect(delayMs: Long) {
        main.postDelayed({
            if (reconnectPending.compareAndSet(true, false)) {
                if (!shuttingDown.get()) {
                    startTunnel(isReconnect = true)
                }
            }
        }, delayMs)
    }

    /**
     * Сеть появилась. Если мы её ЖДЁМ — поднимаемся немедленно, не
     * досиживая шаг таймера.
     *
     * Трогаем ровно один случай: туннель не поднят, а переподключение
     * уже назначено — то есть мы сидим и ждём сеть, которая только что
     * и пришла. Живой туннель не трогаем: появление ещё одной сети не
     * повод рвать рабочий путь, переезд на Wi-Fi будет отдельной
     * задачей.
     *
     * Всё на главном потоке — как и остальная работа со счётчиками и
     * службой. Жетон reconnectPending снимаем тем же compareAndSet, что
     * и таймер: кто первым, тот и поднимает.
     */
    private fun onUnderlyingAvailable(net: Network) {
        main.post {
            if (shuttingDown.get()) return@post
            if (!Access.hasKey()) return@post
            if (TunnelState.connected.value) return@post
            if (!hasUsableNetwork()) return@post
            if (!reconnectPending.compareAndSet(true, false)) return@post
            TunnelLog.add("сеть вернулась — поднимаюсь сразу, не жду таймер")
            TunnelLog.event("сеть вернулась")
            startTunnel(isReconnect = true)
        }
    }

    /**
     * Остановка по нашей воле: сначала движок, потом служба.
     *
     * Engine.stop() чаще всего приведёт сюда же через StateListener —
     * это нормально, повторный вход отсекает защёлка в shutdownService().
     * Своего вызова shutdownService() внизу не убрать: если сессии не
     * было вовсе (Connect не дошёл до конца), движку некого извещать,
     * и служба осталась бы висеть.
     */
    private fun stopTunnel() {
        try {
            Engine.stop()
        } catch (e: Throwable) {
            TunnelLog.add("ошибка при остановке: ${e.message}")
        }
        shutdownService()
    }

    /**
     * Гасит службу и НЕ трогает движок.
     *
     * Ровно этим она и отличается от stopTunnel(), и в этом весь смысл:
     * Engine.stop() зовёт session.stop, тот зовёт слушателя, а слушатель,
     * позвав Engine.stop() снова, замкнул бы круг. Слушатель зовёт только
     * эту половину — обратного пути в Go отсюда нет.
     *
     * Вызывается и с главного потока, и из goroutine движка, поэтому
     * работа со службой уходит на главный поток, а защёлка атомарна.
     */
    private fun shutdownService() {
        if (!shuttingDown.compareAndSet(false, true)) return
        // KILL SWITCH СНИМАЕТСЯ ЗДЕСЬ, И ЭТО ГРАНИЦА ЕГО ЗАЩИТЫ.
        //
        // Сюда ведут три дороги: явное «Отключить», сдача после
        // исчерпанных попыток переподключения, отзыв разрешения
        // системой. Во всех трёх человек либо попросил уйти сам, либо
        // мы признали, что подняться не можем, — держать заглушку
        // дальше значило бы прятать интернет насовсем без спроса.
        // Разбор — у объявления blackhole.
        dropBlackhole()
        // Счётчики последней сессии. По ним видно самый частый вид
        // поломки: «встали, но обратного потока не было».
        val tx = Engine.lastTx()
        val rx = Engine.lastRx()
        TunnelLog.event("отключено; отправлено $tx, принято $rx")

        // ПУТЬ, КОТОРЫЙ ПОДНЯЛСЯ И НЕ ПОНЁС НИЧЕГО, ЗАПОМИНАТЬ НЕЛЬЗЯ.
        //
        // «Встал» и «работает» — разные вещи, а память путей до сих пор
        // считала их одним. Запомненный путь пробуется БЕЗ ГОНКИ, то
        // есть остальные даже не проверяются, и выйти из этого круга
        // было нечем: забывали мы только при провале всей лестницы, а
        // здесь лестница не проваливалась — туннель вставал.
        //
        // Признак: отправляли и не получили НИ ОДНОГО пакета. Не «мало»,
        // а ровно ноль: даже эхо-keepalive не вернулось, значит обратной
        // дороги нет вовсе. Малый счёт бывает при простое и поводом не
        // является.
        // Приговор выносит СТОРОЖ ДВИЖКА, а не счётчик здесь: он ждёт
        // эха на собственную метку и лазейки со случайным пакетом не
        // оставляет. Условие tx > 0 && rx == 0 осталось вторым рубежом
        // на случай, когда сессия оборвалась раньше, чем сторож успел
        // сказать своё слово.
        if (lastStopReason == REASON_MUTE || lastStopReason == REASON_SILENCE ||
            (tx > 0L && rx == 0L)
        ) {
            forgetMutePath()
        } else if (rx > 0L) {
            // ПУТЬ ОТРАБОТАЛ И ПОНЁС ТРАФИК — счётчик немоты в ноль.
            // Сеть, где путь вчера резали, сегодня может его пускать, и
            // копить промахи вечно значило бы уходить на релей на сети,
            // где всё давно ожило. Поток — по streamWonFor, прямой — по
            // rememberedFor (он ещё не обнулён, это ниже).
            streamWonFor?.let { PathMemory.clearStreamMute(this, it) }
            // Немоту ПРЯМОГО здесь НЕ сбрасываем. Для потока «понёс
            // трафик» = здоров: он гаснет за 8 с, любой трафик значит,
            // что не режут. Прямой же немеет ПОСЛЕ того, как понёс много
            // трафика (у жены 80 КБ/212 КБ, потом смерть), так что «понёс
            // трафик» здоровьем прямого не является. Счётчик снимает
            // только свежее подключение (startTunnel) — там честная
            // повторная проба, а не «мигнул трафик — забыли».
        }
        streamWonFor = null
        lastStopReason = null
        // Служба гасится совсем — метка подъёма недействительна.
        connectedAt = 0L
        rememberedFor = null
        netWatch.stop()
        // Туннеля больше нет — значит и применённого к нему списка
        // приложений тоже. Иначе предупреждение «изменения применятся
        // при следующем подключении» показывалось бы на погашенном.
        SplitTunnel.forgetApplied()
        TunnelState.setConnected(false)
        main.post {
            stopForeground(STOP_FOREGROUND_REMOVE)
            stopSelf()
        }
    }

    /**
     * Собирает лестницу под текущий режим.
     *
     * Порядок ступеней решается ЗДЕСЬ, а не в движке: он зависит от
     * настройки и от того, что запомнено для этой сети, — движок про
     * это не знает и знать не должен, он лестницу только проходит.
     *
     * Релейная ступень в режиме AUTO добавляется ВСЕГДА, даже пока она
     * не реализована. Это защита от ловушки роутерного клиента: там
     * провал всех прямых кандидатов упирается в мгновенный отказ релея,
     * потому что креды VK не запрашивались, и лечится только ещё одним
     * перезапуском сессии. У нас провал прямых ступеней обязан вести к
     * следующей ступени внутри ТОЙ ЖЕ попытки, и её присутствие в
     * лестнице с самого начала — единственный способ это гарантировать.
     */
    private fun buildLadder(
        known: String?,
        skipDirect: Boolean = false,
        secondRoundMs: Int = 0,
        skipStreams: Boolean = false,
    ): Ladder {
        val ladder = Engine.newLadder()

        // Срок второго круга гонки из настройки сервера. Ноль движок
        // читает как «оставить зашитое умолчание».
        ladder.setSecondRoundMs(secondRoundMs)

        // ОТПЕЧАТОК ОТОБРАЖЕНИЯ NAT — ТОЛЬКО В ОТЛАДОЧНОЙ СБОРКЕ.
        //
        // Движок спросит у STUN, каким наш адрес видно снаружи: при
        // подъёме и ещё раз, когда сторож объявит туннель немым. Если
        // отображение между этими двумя мгновениями сменилось —
        // подтверждается главная гипотеза по дефекту "принято 0":
        // операторский NAT переназначил нас посреди сессии, а шлюз
        // различает клиентов по адресу источника.
        //
        // Отладка или релиз решается РАЗДЕЛЬНЫМИ ИСХОДНИКАМИ, а не
        // проверкой BuildConfig: на хешах VK мы уже видели, что
        // недостижимая ветка оставляет строки в собранном dex, и
        // находятся они обычным grep. Разбор — в Seed.kt обоих наборов.
        //
        // Пустой адрес означает для движка «пробы нет вовсе»: ни одного
        // лишнего пакета на провод. В релизе так и будет — голый пакет
        // STUN с боевого сокета отличает нас от роутерного клиента.
        ladder.setProbeStun(probeStunAddr())
        ladder.setDeepProbe(deepProbe())

        val mode = TransportSetting.mode.value

        // УЗЛЫ ОТ СЛУЖБЫ, а зашитые — ТОЛЬКО ЕСЛИ СОХРАНЁННОГО НЕТ
        // ВОВСЕ. Это правило 2, и оно не про удобство: зашитые адреса
        // заведомо старше любого ответа службы, и подставлять их поверх
        // сохранённого значило бы откатывать человека к прошлогодним
        // адресам при первой же неудаче запроса.
        //
        // Заметь: сюда мы попадаем и с ПРОСРОЧЕННЫМ ответом, и это
        // намеренно (правило 1). Истёкший ttl значит «пора обновить», а
        // не «список больше не годен».
        val nodes = Params.nodes()
        val fromService = nodes.isNotEmpty()
        TunnelLog.add(
            if (fromService) "узлы: ${nodes.size} от службы" +
                (if (Params.timeToRefresh()) ", срок вышел — обновлю при случае" else "")
            else "узлы: ответа службы нет, беру зашитые запасные"
        )

        // Соответствие буквы и устойчивого имени. Пусто для зашитых:
        // там имя узла и есть буква.
        val ids = HashMap<String, String>()

        val all: List<Node> = when {
            mode == Config.TransportMode.RELAY_ONLY -> emptyList()
            fromService -> nodes.map {
                Node(it.id, it.host, it.port, it.dtls, it.transport, it.sni)
            }
            else -> Config.DIRECT_CANDIDATES.mapIndexed { i, c ->
                Node(Paths.directName(i), "", c.port, c.useDtls)
            }
        }

        // ПРОПУСК ЗАКРЫТОГО UDP убирает ТОЛЬКО UDP-ступени, а поток
        // (TCP/TLS) оставляет: на сети, режущей UDP, поток и есть путь.
        // Раньше здесь был emptyList — он ронял и поток, когда стал
        // частью лестницы.
        // ПРОПУСК РЕЗАННОГО ПОТОКА убирает TCP/TLS и оставляет UDP: это
        // зеркало пропуска UDP, и включаются они независимо. Сеть, где
        // UDP не поднимается, а поток поднимается и немеет, выключит оба
        // — и лестница станет чисто релейной. Ровно этого мы и хотим:
        // релей на такой сети единственный, кто держит трафик.
        val directs: List<Node> = all.filter { n ->
            val stream = n.transport == "tcp" || n.transport == "tls"
            if (stream) !skipStreams else !skipDirect
        }

        // ПОРЯДОК — ПОДСКАЗКА, А НЕ РАСПИСАНИЕ, и список остаётся
        // ПОЛНЫМ. Узлы поднимаются параллельно, победитель — первый
        // готовый; выкидывать записи по своему разумению нельзя ни
        // одну: на МТС живёт только 56005, а у другого человека
        // мёртвым может оказаться именно он.
        //
        // Запомненный узел ставим первым — это и есть подсказка, а не
        // отказ от остальных: движок пробует его один и без гонки, а
        // если он не поднялся, гонка идёт по всем оставшимся.
        // БУКВА — СВОЙСТВО УЗЛА, А НЕ МЕСТА В ЛЕСТНИЦЕ.
        //
        // Раздаём её ДО перестановки, по исходному порядку списка.
        // Раньше буква бралась по месту в уже переставленном списке, и
        // запомненный узел, встав первым, получал A: в логе выходило
        // «запомнено: entry-3» и следом «ступень A запомнена». Шли при
        // этом верно — по портам видно, — но читать такой лог нельзя.
        val letters = HashMap<String, String>()
        directs.forEachIndexed { i, n -> letters[n.id] = Paths.directName(i) }

        val ordered = orderByKnown(directs, known)

        val streams = HashSet<String>()
        for (n in ordered) {
            // Имя ступени — БУКВА, а не описание. Описание вроде
            // «прямой 56005 без DTLS» попадало бы и в лог человеку, и
            // в сам пакет. Соответствие буквы и пути — в Paths.
            val code = letters[n.id] ?: Paths.directName(ordered.indexOf(n))
            ids[code] = n.id
            when (n.transport) {
                // ПОТОКОВЫЕ СТУПЕНИ (кот 2): TCP и TLS. Запомненными не
                // помечаются — движок пробует их последовательно после
                // UDP, как запасной путь, порядок задан сервером.
                "tcp" -> {
                    streams.add(code)
                    ladder.addTCP(code, n.host, n.port)
                }
                "tls" -> {
                    streams.add(code)
                    ladder.addTLS(code, n.host, n.port, n.sni)
                }
                "udp" -> if (n.id == known) {
                    // Запомненную ступень помечаем явно: движок пробует
                    // её одну и без гонки. Гонка нужна незнакомой сети.
                    ladder.addDirectRemembered(code, n.host, n.port, n.dtls)
                } else {
                    ladder.addDirect(code, n.host, n.port, n.dtls)
                }
                // НЕЗНАКОМЫЙ ТРАНСПОРТ ПРОПУСКАЕМ ВСЛУХ, А НЕ МОЛЧА.
                //
                // Раньше эта ветка была else и всё непонятное считала
                // UDP: появись на службе новый вид транспорта, мы бы
                // дозванивались до его порта датаграммами и получали
                // необъяснимо мёртвую ступень без единой строки о
                // причине. Фильтр ?transports в запросе такого ответа
                // не допускает, но полагаться на дальнюю сторону в том,
                // что она не пришлёт нам незнакомого, — как раз тот
                // род молчаливого допущения, который стоил нам недели.
                else -> TunnelLog.add(
                    "узел $code: транспорт «${n.transport}» этой сборке незнаком — пропускаю"
                )
            }
        }
        nodeIds = ids
        streamCodes = streams
        // Соответствие букв и узлов — одной строкой, чтобы читающий лог
        // не гадал, какая буква какому узлу досталась. Имена узлов
        // непрозрачны и о протоколе не говорят ничего.
        if (ordered.isNotEmpty()) {
            TunnelLog.add(
                "ступени: " + ordered.joinToString(", ") {
                    "${letters[it.id] ?: "?"}=${it.id}"
                }
            )
        }

        // Релей отключается только прямым словом службы: ответ без
        // поля relay не должен отнимать запасной путь.
        if (mode != Config.TransportMode.DIRECT_ONLY && Params.relayEnabled()) {
            ladder.addRelay(
                Paths.RELAY,
                Config.TURN_ADDR_BACKUP, Config.TURN_REALM,
                Config.RELAY_GATEWAY_PORT, Config.RELAY_USE_DTLS,
            )
            // Хеши VK. Есть — комплекты добываются цепочкой на лету, по
            // одному на пачку слотов, и статические креды не нужны.
            // Хеши берутся из ПУЛА, а не из настроек: пулом управляет
            // человек с экрана, и мёртвые с закапчёванными пул не отдаёт.
            val hashes = HashStore.usable()
            for (h in hashes) ladder.addRelayHash(h)

            if (hashes.isNotEmpty()) {
                TunnelLog.add(
                    // Считаем ПУЛ, а не список из Config.
                    //
                    // Config.VK_HASHES — засев для отладки, и в релизе
                    // его использовать нельзя: живая ссылка на него
                    // заставляла R8 сохранить сам список, и чужие
                    // ссылки на звонки уезжали в APK каждому, кто его
                    // поставит. Нашлось поиском по собранному пакету.
                    //
                    // Пул к тому же и есть правда: работаем мы с ним, а
                    // не с засевом.
                    "креды: цепочка VK, ссылок ${hashes.size}, " +
                        "потолок слотов 16 (пачки 9 + 7)"
                )
            } else {
                // Хешей нет — релею идти не с чем. Ступень останется в
                // лестнице и откажет с внятным текстом: молча пропасть
                // из списка ей нельзя, иначе отказ незаметен.
                TunnelLog.add("хешей VK нет — релейная ступень откажет, добавь их на экране хешей")
            }
        }

        // Число слотов. Ноль означает умолчание — min(4, ядер), как у
        // роутера. Движок обрежет по своему потолку и применит только к
        // релейной ступени.
        val cores = Runtime.getRuntime().availableProcessors()
        val start = if (Config.SLOTS_START > 0) {
            Config.SLOTS_START
        } else {
            minOf(4, cores)
        }
        ladder.setSlots(start, Config.SLOTS_MAX, Config.SLOTS_AUTO)
        TunnelLog.add(
            "слоты: старт $start" +
                (if (Config.SLOTS_START > 0) " (задано)" else " (умолчание, ядер $cores)") +
                ", предел ${Config.SLOTS_MAX}" +
                (if (Config.SLOTS_AUTO) ", автоподбор включён" else ", автоподбор ВЫКЛЮЧЕН")
        )

        // ИМИТАЦИЯ ОБРЕЗКИ UDP — ТОЛЬКО В ОТЛАДОЧНОЙ СБОРКЕ.
        //
        // Проверка BuildConfig.DEBUG здесь не украшение, а предохранитель
        // от МОЕЙ ошибки. Config.SIMULATE_DIRECT_BLOCKED — константа в
        // файле, которого нет в git: включил, собрал отладочную, забыл
        // выключить — и следующий релиз уехал бы к людям с наглухо
        // отключённым UDP. Ошибка на один забытый флаг, цена — все
        // пользователи разом.
        //
        // Теперь такой сборки не существует: в релизе ветка недостижима,
        // и R8 её выбрасывает целиком.
        if (Config.SIMULATE_DIRECT_BLOCKED && BuildConfig.DEBUG) {
            ladder.failDirect()
            TunnelLog.add("ИМИТАЦИЯ: UDP-ступени считаю закрытыми, потоки и релей живут")
        }

        // ИМИТАЦИЯ МЁРТВОГО ХЕША — тоже только отладочная сборка, тот же
        // предохранитель и по той же причине: константа живёт в файле,
        // которого нет в git.
        //
        // Нужна там, где сеть исправна: настоящего тайм-аута на ней не
        // добиться, а отсрочку хеша проверить надо.
        if (Config.SIMULATE_VK_TIMEOUT && BuildConfig.DEBUG) {
            ladder.simulateVKTimeout()
            TunnelLog.add("ИМИТАЦИЯ: первый хеш VK притворится не ответившим за срок")
        }
        return ladder
    }

    /** Запомненная ступень идёт первой, остальные — в обычном порядке. */
    /**
     * Один узел лестницы: либо от службы, либо из зашитых запасных.
     *
     * host пустой означает «общий адрес из Connect» — так собирается
     * лестница из настроек, где адрес шлюза один на всех.
     */
    private data class Node(
        val id: String,
        val host: String,
        val port: Int,
        val dtls: Boolean,
        val transport: String = "udp",
        val sni: String = "",
    )

    /**
     * Запомненный узел — первым. ОСТАЛЬНЫЕ ОСТАЮТСЯ ВСЕ.
     *
     * Порядок здесь — подсказка о предпочтении, а не расписание
     * попыток: движок поднимает узлы параллельно и берёт первого
     * готового. Единственное, что даёт первое место, — пометка
     * «запомненный», по которой движок пробует его один и без гонки; не
     * поднялся — гонка идёт по всем оставшимся.
     */
    private fun orderByKnown(all: List<Node>, known: String?): List<Node> {
        if (known == null) return all
        val hit = all.firstOrNull { it.id == known } ?: return all
        return listOf(hit) + all.filter { it !== hit }
    }

    /**
     * Одной строкой: какая сеть под нами и какие семейства адресов на ней есть.
     *
     * Проверяет вторую гипотезу обрыва. Сокет до шлюза открывается как
     * "udp4"; если на активной сети IPv4-адреса нет вовсе, он обречён
     * независимо от protect(), и лечить надо выбор семейства, а не protect.
     *
     * Сами адреса в лог не идут — только их наличие.
     */
    private fun describeNetwork(): String = try {
        val cm = getSystemService(ConnectivityManager::class.java)
        val net = cm?.activeNetwork
        if (net == null) {
            "сеть: активной сети нет"
        } else {
            val caps = cm.getNetworkCapabilities(net)
            val props = cm.getLinkProperties(net)

            val transport = when {
                caps == null -> "?"
                caps.hasTransport(NetworkCapabilities.TRANSPORT_WIFI) -> "WIFI"
                caps.hasTransport(NetworkCapabilities.TRANSPORT_CELLULAR) -> "CELLULAR"
                caps.hasTransport(NetworkCapabilities.TRANSPORT_ETHERNET) -> "ETHERNET"
                caps.hasTransport(NetworkCapabilities.TRANSPORT_VPN) -> "VPN"
                else -> "иной"
            }

            val addrs = props?.linkAddresses.orEmpty()
            val v4 = addrs.any { it.address is Inet4Address }
            val v6 = addrs.any { it.address is Inet6Address }
            val iface = props?.interfaceName ?: "?"

            "сеть: $transport ($iface), IPv4=${if (v4) "есть" else "НЕТ"}, " +
                "IPv6=${if (v6) "есть" else "НЕТ"}, адресов=${addrs.size}"
        }
    } catch (e: Throwable) {
        // Диагностика не имеет права ронять подключение.
        "сеть: определить не удалось (${e.message})"
    }

    override fun onRevoke() {
        // Система отобрала разрешение VPN — например, включили другой клиент.
        TunnelLog.add("разрешение VPN отозвано системой")
        stopTunnel()
        super.onRevoke()
    }

    override fun onDestroy() {
        Engine.stop()
        TunnelState.setConnected(false)
        super.onDestroy()
    }

    private fun createChannel() {
        val mgr = getSystemService(NotificationManager::class.java)
        if (mgr.getNotificationChannel(CHANNEL_ID) != null) return
        val channel = NotificationChannel(
            CHANNEL_ID,
            "Состояние туннеля",
            NotificationManager.IMPORTANCE_LOW
        )
        mgr.createNotificationChannel(channel)
    }

    private fun buildNotification(): Notification {
        val open = PendingIntent.getActivity(
            this, 0,
            Intent(this, MainActivity::class.java),
            PendingIntent.FLAG_IMMUTABLE
        )
        val b = Notification.Builder(this, CHANNEL_ID)

        // ЗАДЕРЖКА В ДЕСЯТЬ СЕКУНД — не наша медлительность, а правило
        // системы. С Android 12 уведомление службы переднего плана
        // показывается НЕ СРАЗУ: система ждёт десять секунд, чтобы
        // короткоживущие службы не мигали значком впустую.
        //
        // Для VPN это правило вредное: туннель уже работает, весь
        // трафик человека уже идёт через нас, а признака этого на
        // экране ещё нет. FOREGROUND_SERVICE_IMMEDIATE отключает
        // отсрочку — ровно для таких случаев он и заведён.
        //
        // Канал при этом остаётся IMPORTANCE_LOW: значок нужен, звук
        // и всплывающая карточка при каждом подключении — нет.
        if (Build.VERSION.SDK_INT >= 31) {
            b.setForegroundServiceBehavior(Notification.FOREGROUND_SERVICE_IMMEDIATE)
        }
        return b
            .setContentTitle("Meridian")
            .setContentText("Туннель активен")
            .setSmallIcon(R.drawable.ic_meridian_notify)
            .setContentIntent(open)
            .setOngoing(true)
            .build()
    }
