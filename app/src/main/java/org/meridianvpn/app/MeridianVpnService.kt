    /**
     * Когда последний раз просили движок проверить канал вне очереди.
     *
     * Утрата проверки связи мигает: без этого предела мигающая сеть
     * гнала бы метки и строки лога без счёта, а это ровно тот
     * неограниченный поток, что запрещён инвариантами.
     */
    private val lastSuspectAt = AtomicLong(0L)

    /**
     * Сеть, на которой стоит текущая сессия.
     *
     * Наш UDP-сокет привязан к маршруту по умолчанию, а при первой
     * отправке ядро неявно закрепляет за ним адрес-источник этого
     * интерфейса. Пропадёт интерфейс — все последующие sendto отдают
     * ENETUNREACH, и сессия мертва необратимо. Поэтому запоминаем сеть
     * и сравниваем в onLost.
     */
    @Volatile
    private var sessionNetwork: Network? = null

    /**
     * Поколение сессии.
     *
     * Слушатель движка запоминает своё поколение при создании. Если к
     * моменту вызова номер уже другой — это эхо погашенной сессии, и
     * гасить по нему службу нельзя, иначе переподключение убивало бы
     * само себя.
     */
    private val generation = AtomicInteger(0)

    /** Переподключение уже назначено — второго не планируем. */
    private val reconnectPending = AtomicBoolean(false)

    /**
     * Подъём уже идёт. ВТОРОГО ОДНОВРЕМЕННО БЫТЬ НЕ ДОЛЖНО.
     *
     * Из лога 25.08: шесть заходов в одну секунду, три из них отвалились
     * с «сессия уже поднята». Планета остаётся нажимаемой, пока идёт
     * подключение, и каждое нажатие рождало свой поток.
     *
     * Мало того что это бессмысленно — это ЛОМАЛО подключение сразу
     * двумя способами:
     *
     *   несколько AUTH с одним паролем уходили на шлюз одновременно, а
     *   адрес в туннеле он выдаёт ПО ХЕШУ ПАРОЛЯ: сессии выбивали друг
     *   друга, и AUTH оставался без ответа;
     *
     *   поток, проигравший гонку за Connect, шёл в общий catch и звал
     *   stopTunnel(), то есть гасил ЧУЖУЮ, только что поднятую сессию.
     *
     * Отсюда и «работает с четвёртого раза»: срабатывало тогда, когда
     * нажатие случайно оказывалось одиночным.
     *
     * Engine.awaitStopped() тут не помогает: он ждёт смерти ПРЕЖНЕЙ
     * сессии, а не мешает двум новым начаться разом.
     */
    private val connecting = AtomicBoolean(false)

    /** Неудач подряд. Меняется ТОЛЬКО на главном потоке. */
    private var reconnectFails = 0

    /** «Поднялся и сразу упал» подряд. ТОЛЬКО на главном потоке. */
    private var quickDrops = 0

    /**
     * Когда текущий туннель объявлен поднятым, мс. Ноль — не поднят.
     *
     * По нему отличаем самопроизвольный обрыв живого туннеля (молча
     * переподключаемся) от «поднялся и сразу упал» (считаем к пределу).
     */
    @Volatile
    private var connectedAt = 0L

    /**
     * Ключ сети, для которой запомнен путь текущей сессии.
     *
     * Нужен, чтобы забыть путь, который поднялся, но НЕ ПОНЁС ТРАФИК.
     * Разбор — в shutdownService().
     */
    @Volatile
    private var rememberedFor: String? = null

    /** Причина, с которой движок погасил последнюю сессию. */
    @Volatile
    private var lastStopReason: String? = null

    /**
     * Буква ступени → устойчивое имя узла из ответа службы.
     *
     * ПАМЯТЬ ПУТЕЙ ДЕРЖИТСЯ НА id, А НЕ НА БУКВЕ. Буква — это место в
     * списке, а место служба переставляет когда угодно; запомнив букву,
     * мы после первой же перестановки шли бы прямо к чужому узлу, и
     * без гонки — то есть самый неприятный вид ошибки, молчаливый.
     *
     * Человеку и в лог при этом по-прежнему идёт буква: id наружу не
     * показывается.
     */
    @Volatile
    private var nodeIds: Map<String, String> = emptyMap()

    /**
     * Буквы потоковых ступеней (TCP/TLS) текущей лестницы.
     *
     * По ним отличаем поток от UDP-прямой при разборе победителя: поток
     * запоминать нельзя (он запасной путь, как релей), но и к порогу
     * пропуска UDP он относится так же, как релей, — его победа значит,
     * что прямой UDP на этой сети не держится.
     */
    private var streamCodes: Set<String> = emptySet()

    /**
     * Ключ сети, если ТЕКУЩАЯ сессия поднята потоковой ступенью.
     *
     * Двойник rememberedFor для потока. Нужен, чтобы немоту туннеля
     * было кому засчитать: победу потока мы не запоминаем, и без этого
     * поля немой поток не оставлял по себе следа вовсе — разбор в
     * PathMemory.MUTE_SUFFIX.
     */
    @Volatile
    private var streamWonFor: String? = null

    /** Про приватный DNS человеку уже сказали — второй раз не говорим. */
    private var privateDnsWarned = false


    override fun onCreate() {
        super.onCreate()
        CrashLog.install(this)
        TunnelLog.attach(this)
        TunnelState.attach(this)
        TransportSetting.attach(this)
        HashStore.attach(this)
        SplitTunnel.attach(this)
        Access.attach(this)
        ApiClient.attach(this)
        Params.attach(this)
        updateAttach(this)
    }

    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
        // intent == null означает, что службу подняла СИСТЕМА: мы вернули
        // START_STICKY, процесс умер, его воскресили. Человек null не
        // присылает никогда. Раньше эта ветка молча сливалась с обычным
        // подключением, и владелец не отличал перезапуск после падения от
        // собственного нажатия.
        if (intent == null) {
            TunnelLog.separator("служба поднята системой")
            val crash = CrashLog.last(this)
            TunnelLog.add(
                if (crash != null) "причина: прошлый запуск упал — $crash"
                else "причина: процесс был выгружен (падения не записано)"
            )
            if (crash != null) CrashLog.clear(this)
            startTunnel()
            return START_STICKY
        }

        return when (intent.action) {
            // ПОСТОЯННЫЙ VPN (настройка Android «Always-on VPN»). Систему
            // поднимает нас этим действием без нажатия и без открытия
            // приложения — например, сразу после перезагрузки. Разрешение
            // VPN при always-on уже выдано (без него его не включить), а
            // всё нужное подключено в onCreate. Поднимаемся и держимся
            // (START_STICKY): если процесс выгрузят, система вернёт нас
            // тем же путём. Раньше это молча сливалось с обычным «else» —
            // работало, но в логе было неотличимо от нажатия.
            VpnService.SERVICE_INTERFACE -> {
                TunnelLog.separator("постоянный VPN")
                TunnelLog.add("служба поднята системой как always-on")
                startTunnel()
                START_STICKY
            }
            ACTION_DISCONNECT -> {
                stopTunnel()
                START_NOT_STICKY
            }
            ACTION_RECONNECT -> {
                // Гасим движок, но НЕ службу: сразу поднимаемся заново.
                // Поколение вперёд, иначе слушатель гибнущей сессии
                // увидит своё поколение текущим и погасит нас.
                generation.incrementAndGet()
                try {
                    Engine.stop()
                } catch (e: Throwable) {
                    TunnelLog.add("ошибка при остановке: ${e.message}")
                }
                TunnelState.setConnected(false)
                sessionNetwork = null
                SplitTunnel.forgetApplied()
                startTunnel(isReconnect = true)
                START_STICKY
            }
            else -> {
                startTunnel()
                START_STICKY
            }
        }
    }

    private fun startTunnel(isReconnect: Boolean = false) {
        // ПЕРВОЙ строкой, до всего остального: если подъём уже идёт,
        // второй не начинаем и службу не трогаем — она уже на переднем
        // плане стараниями первого.
        if (!connecting.compareAndSet(false, true)) {
            TunnelLog.add("подключение уже идёт — повторную команду игнорирую")
            return
        }

        // KILL SWITCH — ВТОРОЙ СТРОКОЙ, ДО ЛЕСТНИЦЫ.
        //
        // Между нажатием «Подключить» и первым установленным туннелем
        // лестница кандидатов идёт БЕЗ VPN-интерфейса вовсе (до этой
        // правки — секунды, а на плохой сети и больше), и всё это время
        // остальные приложения были на настоящей сети. Тот же путь
        // проходит и переподключение: оно тоже зовёт startTunnel(), и
        // повторный вызов здесь безвреден — establishBlackhole() просто
        // переустановит то, что уже стоит.
        establishBlackhole(
            reason = if (isReconnect) "переподключение" else "подключение",
            // announce=false ТОЛЬКО для самого первого «Подключить»:
            // здесь заглушка защищает подъём лестницы, обрыва ещё не
            // было, и рассказывать человеку «Kill Switch сработал» было
            // бы враньём по смыслу. При isReconnect=true announce
            // остаётся по умолчанию — !wasAlready внутри всё равно
            // погасит повтор, если onStopping/scheduleReconnect уже
            // объявили этот же обрыв чуть раньше.
            announce = isReconnect,
        )

        // Свежее подключение по воле человека — счётчики аварий с
        // чистого листа. У переподключения они, наоборот, копятся: по
        // ним и срабатывают пределы вечного цикла.
        if (!isReconnect) {
            reconnectFails = 0
            quickDrops = 0
        }

        createChannel()
        startForeground(NOTIFICATION_ID, buildNotification())

        // Новый CONNECT может прийти в уже гасимый экземпляр: стартовая
        // команда отменяет отложенный stopSelf(), служба остаётся жить.
        // Без сброса защёлки такая воскресшая служба больше никогда не
        // погасла бы.
        shuttingDown.set(false)

        // ДОСТУП. Проверяется здесь и только здесь — в единственном
        // месте, где туннель начинает подниматься.
        //
        // Уже поднятый туннель этой проверкой не рвётся: она не
        // выполняется, пока сессия жива. Человек, у которого сутки
        // кончились посреди работы, доработает до отключения сам.
        //
        // Переподключение при смене сети — это НОВЫЙ подъём, и оно тоже
        // сюда попадает. Так и задумано: сессия уже оборвалась, а
        // поднимать её заново без доступа не за что.
        if (!Access.allowed()) {
            TunnelLog.add(
                if (isReconnect) "пробный период кончился — переподключение отменено"
                else "пробный период кончился, ключа нет — туннель не поднимаю"
            )
            connecting.set(false)
            shutdownService()
            return
        }

        // Планета крутится всё время подъёма, включая повторные
        // попытки. Снимет отметку любой определённый исход — и успех, и
        // провал, оба идут через TunnelState.setConnected().
        TunnelState.setBusy(true)

        // Включаем ДО подключения: смена канала во время прохода
        // лестницы интересна ровно так же, как и во время работы.
        netWatch.start()

        val gen = generation.incrementAndGet()
        val startedAt = System.currentTimeMillis()
        // ВЕРСИЯ В ПЕРВОЙ ЖЕ СТРОКЕ ПОДКЛЮЧЕНИЯ.
        //
        // 27.08 по логу в 18:20 нельзя было сказать, какая сборка на
        // телефоне: строки, по которым сборки различались, печатаются
        // только при отказе, а отказа в тот раз не случилось. Разбирать
        // замер, не зная, что именно его сняло, — потерянный круг.
        //
        // Берём у системы, а не из BuildConfig: показывается ровно то,
        // что установлено, см. appVersion.
        TunnelLog.event(
            (if (isReconnect) "переподключение, попытка ${reconnectFails + 1} из $RECONNECT_MAX_FAILS"
            else "подключение начато") + ", сборка " + appVersion(this)
        )

        thread(name = "meridian-connect") {
            // УДЕРЖАНИЕ ПРОЦЕССОРА НА ВРЕМЯ ПОДЪЁМА.
            //
            // 27.08 пульс движка показал, что нас останавливают ЦЕЛИКОМ
            // на 2,7-7,1 секунды подряд, стоит свернуть приложение сразу
            // после нажатия. Лестница при этом судит ступени по срокам,
            // которых не было: пауза в полторы секунды растягивается до
            // восьми, окно ожидания эха съедается целиком, и исправная
            // ступень бракуется — подключение из одной секунды
            // становится десятью, через релей.
            //
            // Служба переднего плана от этого не спасает: она не даёт
            // нас убить, но не обязывает систему давать нам процессор.
            //
            // Держим ТОЛЬКО пока идёт подъём. Срок — на случай, если мы
            // где-то не снимем сами: держать процессор бесконечно из-за
            // своей же ошибки нельзя.
            val wake = try {
                val pm = getSystemService(PowerManager::class.java)
                pm?.newWakeLock(PowerManager.PARTIAL_WAKE_LOCK, "meridian:connect")
                    ?.apply { acquire(WAKE_LIMIT_MS) }
            } catch (e: Throwable) {
                TunnelLog.add("удержание процессора не вышло: ${e.message}")
                null
            }
            try {
                // Одно значение на всё приложение, см. Access.deviceId().
                // Раньше здесь стоял свой вызов ANDROID_ID с подстановкой
                // "unknown" — и на телефонах, где он пуст, все устройства
                // выглядели для шлюза одним и тем же.
                val deviceId = Access.deviceId(this)

                val protector = object : Protector {
                    override fun protect(fd: Int): Boolean {
                        // protect() — обязателен, без него сокет уйдёт в
                        // наш же туннель. Он и решает.
                        val ok = this@MeridianVpnService.protect(fd)
                        if (ok) bindToUnderlying(fd)
                        return ok
                    }
                }
                val logger = object : Logger {
                    override fun log(line: String) = TunnelLog.add(line)
                }

                // Движку неоткуда узнать про ConnectivityManager, а знать
                // он обязан: между подъёмом транспорта и отправкой AUTH
                // проходит до полутора секунд форы, и в это окно человек
                // успевает войти в зону Wi-Fi.
                val guard = object : NetworkGuard {
                    override fun sameNetwork(): Boolean = !networkChanged()
                }

                // Приходит из goroutine движка, не с главного потока.
                // Engine.stop() отсюда звать НЕЛЬЗЯ: движок сам нас и
                // позвал, см. shutdownService().
                val listener = object : StateListener {
                    /**
                     * KILL SWITCH — САМАЯ РАННЯЯ ТОЧКА, ДОБАВЛЕНА 15.09.
                     *
                     * Движок ещё не закрыл TUN (закроет сразу после
                     * этого вызова, engine/session.go stop()) — если
                     * прямо здесь поднять заглушку, Android заменит
                     * интерфейс АТОМАРНО, и окна без защиты не
                     * останется вовсе. До этой правки заглушка вставала
                     * только в scheduleReconnect/onStopped — то есть
                     * после того, как движок уже закрыл настоящий TUN
                     * для обрывов, которые он находит сам (немота,
                     * тишина канала), и зазор между закрытием и тем
                     * вызовом был реальным, хоть и небольшим.
                     *
                     * ПРОВЕРКА ПОКОЛЕНИЯ ЗДЕСЬ НУЖНА, И ВОТ ПОЧЕМУ.
                     * Engine.stop() ВСЕГДА шлёт одну и ту же строку
                     * ("по команде приложения"), кто бы его ни позвал —
                     * и настоящее «Отключить» (stopTunnel), и наш
                     * собственный вынужденный перезапуск при смене сети
                     * (scheduleReconnect, который сам зовёт Engine.stop()
                     * ниже по своему коду). Различить их по reason
                     * нельзя — только по generation: scheduleReconnect
                     * сдвигает его РАНЬШЕ своего Engine.stop(), поэтому
                     * к моменту этого колбэка для вынужденного
                     * перезапуска generation уже чужой. Ровно этот же
                     * разбор смотри в onStopped ниже — там та же пара
                     * проверок и с той же целью.
                     *
                     * Заглушку поднимаем и в «чужом поколении» тоже —
                     * scheduleReconnect обычно успевает поднять её сам
                     * ДО своего Engine.stop() (что даёт настоящий
                     * нулевой зазор для этого пути), но если та попытка
                     * почему-то не удалась — здесь второй шанс, а
                     * повторный establish() того же самого безвреден.
                     */
                    override fun onStopping(reason: String) {
                        if (generation.get() != gen) {
                            // Kotlin уже решил перезапуститься САМ
                            // (пропала сеть, сменился адрес,
                            // ACTION_RECONNECT) — scheduleReconnect
                            // обычно поднимает заглушку раньше своего же
                            // Engine.stop(), это здесь второй шанс.
                            establishBlackhole("свой перезапуск: $reason")
                            return
                        }
                        if (reason == REASON_STOP_COMMAND) {
                            // Настоящее «Отключить»: человек попросил
                            // уйти, заглушка тут же снялась бы в
                            // shutdownService() — поднимать её на долю
                            // секунды незачем, только шум в логе.
                            return
                        }
                        // ДВИЖОК НАШЁЛ ОБРЫВ САМ — самый частый случай в
                        // жизни (метро, роуминг, тишина канала). Ровно
                        // ради этой ветки и делалась вся правка 15.09:
                        // до неё заглушка сюда не успевала вовсе, TUN
                        // уже был закрыт движком раньше, чем Kotlin об
                        // этом узнавал.
                        establishBlackhole("движок нашёл обрыв: $reason")
                    }

                    override fun onStopped(reason: String) {
                        TunnelLog.add("движок остановил сессию: $reason")
                        lastStopReason = reason
                        if (generation.get() != gen) {
                            // Эхо уже погашенной сессии: идёт
                            // переподключение, службу трогать нельзя.
                            return
                        }

                        // ОСТАНОВКА ПО КОМАНДЕ — ГАСИМ, ОБРЫВ — МОЛЧА
                        // ПЕРЕПОДКЛЮЧАЕМСЯ.
                        //
                        // Различаем по причине. "по команде приложения"
                        // приходит от Engine.stop(), который зовём мы
                        // сами на «Отключить»: тут переподключаться
                        // нельзя, человек попросил уйти.
                        //
                        // Всё остальное на этом месте — самопроизвольный
                        // обрыв ЖИВОГО туннеля: сторож немоты, молчание
                        // канала, ошибка сокета на исчезнувшем маршруте.
                        // Лестница тут ни при чём — она отработала ДО
                        // подъёма и туннель уже стоял. Раньше мы просто
                        // гасили службу, и человек жал кнопку заново;
                        // теперь поднимаемся сами.
                        //
                        // Два предохранителя от вечного цикла — в
                        // scheduleReconnect: предел неудачных попыток и
                        // предел «поднялся и сразу упал».
                        if (reason == REASON_STOP_COMMAND) {
                            shutdownService()
                            return
                        }

                        // Немой путь забываем ДО переподъёма, иначе
                        // запомненная ступень снова уведёт в ту же
                        // немоту без гонки. Тот же разбор, что в
                        // shutdownService().
                        if (reason == REASON_MUTE || reason == REASON_SILENCE) forgetMutePath()

                        // Движок уже остановился сам — мы в его колбэке,
                        // Engine.stop() отсюда звать нельзя.
                        scheduleReconnect("обрыв: $reason", engineAlreadyStopped = true)
                    }
                }

                // Пока прежняя сессия не мертва окончательно, новую
                // начинать нельзя: её сокет ещё может слать пакеты, а
                // адрес в туннеле шлюз выдаёт по хешу пароля — второй
                // AUTH на том же адресе выбьет первый. Таймер в три
                // секунды перед переподключением такой гарантии не даёт,
                // он всего лишь пауза; гарантию даёт вот это ожидание.
                //
                // Зовём с фонового потока — функция блокирующая.
                if (!Engine.awaitStopped(AWAIT_STOP_MS)) {
                    throw IllegalStateException(
                        "прежняя сессия не остановилась за $AWAIT_STOP_MS мс"
                    )
                }

                TunnelLog.add(describeNetwork())
                TunnelLog.event("сеть: " + shortNetworkType())

                // Сеть запоминаем ДО establish(): после него активной
                // станет сам туннель, и запомнили бы мы его, а не канал
                // оператора.
                val net = netWatch.activeUnderlying()
                sessionNetwork = net
                TunnelLog.add(
                    if (net != null) "сессия встаёт на ${netWatch.ifaceOf(net)}"
                    else "сеть сессии определить не удалось — обрыв поймает только сторож тишины"
                )

                // Ключ сети и запомненная для неё ступень. Ключ считаем
                // ДО подключения: после установления туннеля активной
                // сетью станет сам туннель, и ключ получился бы не тот.
                val netKey = PathMemory.networkKey(this)
                val knownId = PathMemory.remembered(this, netKey)

                // СВЕЖЕЕ ПОДКЛЮЧЕНИЕ ПРОБУЕТ ПРЯМОЙ ЗАНОВО.
                //
                // Счётчик немоты прямого сбрасываем ТОЛЬКО здесь и
                // только на свежем старте (не переподключении): человек
                // открыл приложение сам — самое время проверить, не ожил
                // ли прямой на этой сети. Внутри одной сессии счётчик
                // держится, и после немоты лестница идёт мимо прямого на
                // релей до следующего свежего старта. Это и есть честная
                // повторная проба вместо сломанного пробного захода по
                // модулю (тот не срабатывал: счётчик немоты не растёт,
                // пока прямой пропущен).
                if (!isReconnect) {
                    PathMemory.clearDirectMute(this, netKey)
                }

                // ПАРАМЕТРЫ СПРАШИВАЕМ ДО ПОСТРОЕНИЯ ЛЕСТНИЦЫ — повод 1,
                // вышел срок. Мы на фоновом потоке, звать можно прямо
                // здесь. Не дозвонились — не беда: по правилу 1 работаем
                // по последнему удачному ответу, сколько бы ни прошло.
                try {
                    Params.refreshIfDue()
                } catch (e: Throwable) {
                    TunnelLog.add("параметры: запрос сорвался (${e.message})")
                }

                TunnelLog.add(
                    "ключ сети: $netKey, запомнено: ${knownId ?: "ничего"}"
                )

                // Без пароля подключаться не с чем. В отладке сюда не
                // попасть — там есть тестовый; в релизе это человек на
                // триале, у которого ключа ещё нет. Молчать нельзя:
                // иначе он увидит неудачу лестницы и решит, что дело в
                // сети.
                if (Access.password().isEmpty()) {
                    throw IllegalStateException(
                        "нет ключа доступа: пробный период пока работает " +
                            "только в отладочной сборке"
                    )
                }

                // ПРОПУСК ПРЯМОГО ПУТИ НА ЗАВЕДОМО ЗАКРЫТОЙ СЕТИ.
                //
                // Если прямой путь тут подряд не держится, каждый подъём
                // впустую тратит ~5 с на его перебор перед уходом на
                // релей. Считаем по счётчику (PathMemory) и на такой
                // сети идём сразу на релей — но не после первой неудачи
                // и не навсегда: раз в несколько попыток прямой всё-таки
                // щупаем, чтобы заметить ожившую сеть.
                //
                // Пропуск возможен ТОЛЬКО в режиме AUTO и только когда
                // релею есть на чём подняться: без кредов пропуск
                // прямого оставил бы человека вообще без пути.
                // Пороги — из настройки сервера (умолчания = прежние 5 и
                // 4, см. Params). Пишем применённые значения в лог: без
                // этого «настройка приехала» и «настройка применилась» не
                // отличить.
                val skipAfter = Params.directSkipAfterFails()
                val probeEvery = Params.directProbeEveryAttempts()
                val secondRoundMs = Params.secondRoundMs()
                TunnelLog.add(
                    "настройка лестницы: второй круг $secondRoundMs мс, " +
                        "пропуск после $skipAfter, проба каждые $probeEvery"
                )

                val relayReady = TransportSetting.mode.value == Config.TransportMode.AUTO &&
                    Params.relayEnabled() && HashStore.usable().isNotEmpty()
                // Две причины идти мимо прямого, и они РАЗНЫЕ. Гонку
                // прямой проигрывает, когда не может ПОДНЯТЬСЯ (skipDirectRace).
                // Немоту он зарабатывает, когда поднялся и умер посреди
                // сессии (skipDirectMute) — это и есть беда жены 12.09.
                // До сегодня учитывалась только первая.
                val skipDirectRace = relayReady &&
                    PathMemory.skipDirect(this, netKey, skipAfter, probeEvery)
                val skipDirectMute = relayReady &&
                    PathMemory.skipDirectMute(this, netKey, DIRECT_MUTE_SKIP_AFTER, probeEvery)
                val skipDirect = skipDirectRace || skipDirectMute
                if (skipDirectMute) {
                    TunnelLog.add(
                        "прямой UDP на этой сети немеет " +
                            "(${PathMemory.directMuteStreak(this, netKey)}) — мимо UDP, на релей"
                    )
                    TunnelLog.event("прямой на этой сети немеет — иду на релей")
                } else if (skipDirectRace) {
                    TunnelLog.add(
                        "прямой UDP на этой сети подряд не держится " +
                            "(${PathMemory.relayStreak(this, netKey)}) — мимо UDP, на поток и релей"
                    )
                } else if (relayReady &&
                    PathMemory.probingDirect(this, netKey, skipAfter, probeEvery)
                ) {
                    // Проба относится к ПРОИГРЫШУ ГОНКИ (relayStreak): тот
                    // счётчик растёт на каждом релейном заходе и по модулю
                    // сам щупает прямой. У немоты повторная проба другая —
                    // свежее подключение (clearDirectMute выше), потому
                    // что счётчик немоты в пропуске не растёт и модуль бы
                    // не сработал.
                    TunnelLog.add("проверяю, не открылся ли прямой путь на этой сети")
                }

                // ПРОПУСК ПОТОКА НА СЕТИ, ГДЕ ЕГО РЕЖУТ ПОСЛЕ ПОДЪЁМА.
                //
                // Отдельно от пропуска UDP, потому что беда другая. UDP
                // на такой сети не поднимается вовсе — его видно сразу.
                // Поток поднимается и проходит проверку целиком, а режут
                // его через несколько секунд, когда пошёл настоящий
                // трафик: сторож объявляет туннель немым, сессия падает,
                // переподключение строит ту же лестницу — и круг.
                // Разбор — в PathMemory.MUTE_SUFFIX.
                val skipStreams = relayReady &&
                    PathMemory.skipStreams(this, netKey, STREAM_MUTE_SKIP_AFTER, probeEvery)
                if (skipStreams) {
                    TunnelLog.add(
                        "поток на этой сети поднимается и немеет " +
                            "(${PathMemory.streamMuteStreak(this, netKey)}) — мимо потока, на релей"
                    )
                } else if (relayReady &&
                    PathMemory.probingStreams(this, netKey, STREAM_MUTE_SKIP_AFTER, probeEvery)
                ) {
                    TunnelLog.add("проверяю, не перестали ли резать поток на этой сети")
                }

                val ladder = buildLadder(knownId, skipDirect, secondRoundMs, skipStreams)
                TunnelLog.add(
                    "лестница: ${ladder.len()} ступеней, режим ${TransportSetting.mode.value}" +
                        if (Config.SIMULATE_DIRECT_BLOCKED) ", ИМИТАЦИЯ закрытого прямого пути" else ""
                )

                // Фаза 1: лестница транспорта и AUTH. Туннель ещё не
                // построен — адрес для него мы узнаём только из ответа
                // шлюза, а какой ступенью — только пройдя лестницу.
                val assigned = try {
                    // РЕЗЕРВНЫЙ АДРЕС — ТОЛЬКО ЕСЛИ РЕЗОЛВ ИМЕНИ НЕ ДАЛ
                    // НИЧЕГО, а не при любом отказе лестницы. Отличаем по
                    // подстроке сообщения из engine/resolve.go: если
                    // движок вообще не смог узнать адрес по имени (DoH,
                    // системный DNS и кэш молчат), сессия внутри Connect()
                    // ещё не заводилась — второй заход тем же вызовом
                    // безопасен и ничего не задваивает. Если же адрес
                    // получили, а не поднялась уже сама лестница на нём —
                    // это обычный отказ, ниже его разбирает существующий
                    // catch, как и раньше.
                    try {
                        Engine.connect(
                            Config.EDGE_HOST, EdgeCache.get(this) ?: "", ladder,
                            Access.password(), deviceId,
                            protector, guard, CaptchaGate.solver(this), logger, listener
                        )
                    } catch (eResolve: Throwable) {
                        if (eResolve.message?.contains("узнать адрес шлюза") != true) throw eResolve
                        TunnelLog.add(
                            "имя ${Config.EDGE_HOST} не резолвится (${eResolve.message}) " +
                                "— иду на резервный адрес"
                        )
                        Engine.connect(
                            Config.GATEWAY, "", ladder, Access.password(), deviceId,
                            protector, guard, CaptchaGate.solver(this), logger, listener
                        )
                    }
                } catch (e: Throwable) {
                    // Лестница не поднялась целиком. Запомненная ступень
                    // больше не годится — забываем молча, в следующий раз
                    // пойдём обычным порядком.
                    //
                    // НО не тогда, когда виновата смена сети: ступень при
                    // этом ни при чём, и забыть её значило бы наказать
                    // рабочий путь за то, что человек вошёл в зону Wi-Fi.
                    if (knownId != null) {
                        if (networkChanged()) {
                            TunnelLog.add("сеть сменилась — запомненную ступень НЕ забываю")
                        } else {
                            PathMemory.forget(this, netKey)
                            TunnelLog.add("запомненная ступень не сработала, забыта")
                        }
                    }

                    // Пропускали прямой, а релей тоже не встал — снимаем
                    // пропуск: стратегия «сразу на релей» не сработала,
                    // в следующий раз пробуем всё заново. Смену сети
                    // сюда не считаем: виноват канал, а не выбор пути.
                    if (skipDirect && !networkChanged()) {
                        // Снимаем ровно ту метку, что и завела пропуск:
                        // иначе одна причина стёрла бы улику другой.
                        if (skipDirectRace) PathMemory.clearRelayStreak(this, netKey)
                        if (skipDirectMute) PathMemory.clearDirectMute(this, netKey)
                        TunnelLog.add("релей тоже не поднялся — пропуск прямого снят")
                    }

                    // То же и для пропуска потока: шли мимо него сразу
                    // на релей, а релей не встал — стратегия не
                    // сработала, в следующий раз пробуем поток заново.
                    if (skipStreams && !networkChanged()) {
                        PathMemory.clearStreamMute(this, netKey)
                        TunnelLog.add("релей тоже не поднялся — пропуск потока снят")
                    }

                    // ПОВОД 2: НЕ СРАБОТАЛ НИ ОДИН УЗЕЛ.
                    //
                    // Самый ценный повод спросить параметры: он значит,
                    // что сохранённый список перестал работать целиком, и
                    // другого способа узнать новый у нас нет. Пол в
                    // десять минут внутри — чтобы мигающая сеть не
                    // превратила это в поток запросов.
                    //
                    // Смена сети таким поводом НЕ является: узлы при этом
                    // ни при чём, виноват канал.
                    if (!networkChanged()) {
                        try {
                            Params.refreshAfterAllFailed()
                        } catch (t: Throwable) {
                            TunnelLog.add("параметры: запрос сорвался (${t.message})")
                        }
                    }
                    throw e
                }
                TunnelLog.add("выдан адрес $assigned")
                if (Engine.captchaCount() > 0) {
                    TunnelLog.add("капча встречалась ${Engine.captchaCount()} раз(а) за работу приложения")
                }

                // Запоминаем ТОЛЬКО прямые ступени.
                //
                // Память нужна ровно для одного: пропустить гонку, когда
                // для этой сети уже известна хорошая прямая ступень.
                // Релей и так всегда последний в лестнице, и запись про
                // него на порядок не влияет вообще никак — зато затирает
                // полезную память о прямой ступени, и в следующий раз
                // короткого пути «запомнена → без гонки» уже нет.
                //
                // Прямой путь при этом пробуется КАЖДЫЙ раз, даже когда в
                // прошлый раз выиграл релей: он мог с тех пор открыться.
                // ПРЯМАЯ — ЭТО UDP-ПРЯМАЯ. Поток (TCP/TLS) и релей —
                // запасные пути: их не запоминаем, а их победа значит,
                // что UDP-прямой на этой сети не держится, и считается к
                // порогу пропуска ровно как релей. На сети, режущей UDP,
                // это и уведёт лестницу сразу на поток+релей, минуя
                // заведомо мёртвый UDP-перебор.
                val winner = Engine.winner()
                val winnerIsUdpDirect = winner.isNotEmpty() &&
                    winner != Paths.RELAY && winner !in streamCodes
                if (winner.isNotEmpty() && !winnerIsUdpDirect) {
                    // Поток или релей — счётчик вверх: UDP-прямой не
                    // держится, сеть набирает вес в сторону «мимо UDP».
                    PathMemory.noteRelayWon(this, netKey)
                    TunnelLog.add("поднялись через $winner — не запоминаю, память держим для UDP-прямых")
                }

                // ПОДНЯЛИСЬ ПОТОКОМ — ЗАПОМИНАЕМ, ЧЕЙ ЭТО БУДЕТ ПРОМАХ,
                // если туннель окажется немым. Победу потока не
                // запоминаем и запоминать не будем, но немоту нужно
                // кому-то засчитать: разбор в PathMemory.MUTE_SUFFIX.
                streamWonFor = if (winner.isNotEmpty() && winner in streamCodes) netKey else null
                if (winner.isNotEmpty() && winnerIsUdpDirect) {
                    // Запоминаем УСТОЙЧИВОЕ имя узла, а показываем букву.
                    PathMemory.remember(this, netKey, nodeIds[winner] ?: winner)
                    // Прямой ожил — счётчик пропуска в ноль. Если сеть
                    // сменила конфигурацию обратно, пробный заход это
                    // поймал, и дальше снова идём прямым.
                    PathMemory.clearRelayStreak(this, netKey)
                    rememberedFor = netKey
                    TunnelLog.add("запомнил для этой сети: $winner")
                }

                val slash = assigned.indexOf('/')
                val address = assigned.substring(0, slash)
                val prefix = assigned.substring(slash + 1).toInt()

                // Фаза 2: строим туннель и отдаём дескриптор движку.
                //
                // MTU спрашиваем ИМЕННО ЗДЕСЬ, после Connect: до прохода
                // лестницы неизвестно, какая ступень выиграет, а MTU у
                // них разное. Ступень без DTLS требует меньшего, потому
                // что над obfs там нет никого, кто резал бы пакеты.
                val mtu = Engine.mtu()
                TunnelLog.add("MTU туннеля: $mtu")

                val builder = Builder()
                    .setSession("Meridian")
                    .addAddress(address, prefix)
                    .addRoute("0.0.0.0", 0)
                    // ДВА РЕЗОЛВЕРА, А НЕ ОДИН.
                    //
                    // Оба публичные и оба спрашиваются ВНУТРИ туннеля:
                    // их адреса попадают под маршрут по умолчанию выше,
                    // наружу запрос выходит уже на шлюзе. Резолвер
                    // оператора при этом не спрашивается вовсе — а он,
                    // по замеру кота 1 от 04.09, отдаёт заблокированным
                    // доменам заглушку 87.228.47.204, одну на все.
                    //
                    // Второй нужен как запас: один резолвер — единичная
                    // точка отказа, и на роутере это уже стоило дня
                    // работы 04.09. Своего резолвера у нас нет — кот 2
                    // проверил на VPS, 53-й порт не слушает никто.
                    .setMtu(mtu)
                for (s in DNS_SERVERS) builder.addDnsServer(s)

                // ОБЪЯВЛЕННЫЕ РЕЗОЛВЕРЫ — В ЛОГ, ИЗ ТОГО ЖЕ СПИСКА.
                //
                // Список один и тот же и для объявления, и для строки:
                // разъехаться им нечем. Писать в лог литералы отдельно
                // значило бы завести прибор, который со временем начнёт
                // врать — а именно на таких приборах мы обожглись 05.09,
                // когда счётчик показывал ноль на исправном потоке.
                //
                // Строка НЕ доказывает, что система послушалась: Android
                // волен подставить свой резолвер поверх нашего, и
                // проверяется это только со стороны шлюза, по потокам на
                // 53-й порт от нашего туннельного адреса. Но без неё
                // разбор любой жалобы на DNS начинается с догадок о том,
                // что вообще было объявлено на этом телефоне.
                TunnelLog.add("резолверы туннеля: ${DNS_SERVERS.joinToString(", ")}")

                // IPv6 ЗАБИРАЕМ В ТУННЕЛЬ, ЧТОБЫ ОН НЕ ШЁЛ МИМО НЕГО.
                //
                // Шлюз v6 не несёт совсем — кот 2 замерил: ни адреса, ни
                // маршрута по умолчанию, forwarding=0, WG клиентам v6 не
                // выдаёт. Рабочим маршрутом ::/0 сделать нельзя, на том
                // конце его никто не примет.
                //
                // Но и оставить его ВНЕ туннеля нельзя, и это не
                // предпочтение. Мобильные операторы v6 раздают (в наших
                // логах "IPv6=есть", адресов 2), DNS у нас теперь чистый
                // и честно вернёт AAAA — и весь трафик к сайтам с AAAA
                // пошёл бы мимо туннеля открытым каналом. Человек этого
                // не заметит: приложение показывает «подключено».
                //
                // Забираем маршрут на себя. Пакеты упрутся в отсутствие
                // v6 и будут отброшены движком, приложения по Happy
                // Eyeballs уйдут на IPv4. НАСТРОЙКИ ТЕЛЕФОНА НЕ ТРОГАЕМ:
                // перехват маршрута — не выключение IPv6 в системе.
                //
                // Под try: примет ли Android маршрут v6 без адреса v6,
                // на устройстве я проверить не могу. Отказ обязан быть
                // ГРОМКИМ — он означает, что утечка на этом телефоне
                // живая.
                try {
                    builder.addRoute("::", 0)
                    TunnelLog.add("IPv6 забран в туннель и глушится — шлюз его не несёт")
                } catch (e: Throwable) {
                    TunnelLog.add(
                        "IPv6 В ТУННЕЛЬ ЗАБРАТЬ НЕ ВЫШЛО (${e.message}) — " +
                            "трафик v6 идёт МИМО туннеля, это утечка"
                    )
                }

                // РАЗДЕЛЬНОЕ ТУННЕЛИРОВАНИЕ. Единственное место, где оно
                // применяется: Builder читается системой в establish(),
                // и у поднятого туннеля список уже не изменить.
                //
                // Здесь же наше собственное приложение выводится из
                // туннеля — разбор в SplitTunnel.apply().
                SplitTunnel.apply(builder, this)

                notePrivateDns()

                val pfd = builder.establish()
                    ?: throw IllegalStateException("establish() вернул null — разрешение отозвано?")

                // KILL SWITCH: заглушку этот establish() уже сменил сам
                // (Android заменяет интерфейс службы атомарно при
                // повторном вызове) — здесь только освобождаем свою
                // ссылку на неё, чтобы не держать мёртвый дескриптор.
                dropBlackhole()

                // detachFd: дескриптор переходит во владение Go.
                // Закрывать его здесь нельзя — будет двойное закрытие.
                Engine.start(pfd.detachFd())
                TunnelLog.add("туннель поднят")
                // ЗАПОМИНАЕМ АДРЕС ТОЛЬКО ТЕПЕРЬ, после подтверждённого
                // Start() — до этого момента известно лишь, что резолв
                // что-то нашёл, а не что это «что-то» реально работает.
                val via = Engine.resolvedVia()
                if (via.isNotEmpty()) EdgeCache.set(this, Engine.resolvedAddr())
                TunnelLog.event(
                    "подключено, путь ${Paths.letterOf(Engine.winner())}" +
                        (if (via.isEmpty()) "" else " ($via)") + ", " +
                        "за ${(System.currentTimeMillis() - startedAt) / 1000} с"
                )
                // Всё получилось — прежней жалобе на экране больше не
                // место. Планета сама покажет, что туннель работает.
                Notice.clear()
                // Туннель встал — значит, введённый ключ подошёл шлюзу.
                // Отдельной проверки на сервере нет и не нужно: адрес в
                // туннеле выдаётся по хешу пароля, и с неверным ключом мы
                // до этой строки просто не дошли бы.
                Access.confirmPending()
                TunnelState.setConnected(true)
                connectedAt = System.currentTimeMillis()
                // Поднялись — счётчик неудач обнуляется.
                main.post { reconnectFails = 0 }
            } catch (e: Throwable) {
                TunnelLog.add("ошибка: ${e.message}")
                // НЕТ СЕТИ — ЭТО «СЕТИ НЕТ», а не «подключиться не
                // удалось». Баг тестировщика 29.08: во время звонка на
                // сетях без VoLTE данные приостанавливаются — интерфейс
                // есть, но пакеты не ходят, туннель не встаёт. Общий
                // текст врал про причину; проверяем сеть и называем прямо.
                val noNet = !hasUsableNetwork()
                val reason = if (noNet) "сети нет" else humanReason(e)
                TunnelLog.event("не удалось: $reason")
                // Проверяли ключ — он не подтвердился. Сохранённый ключ
                // при этом не трогаем: непроверенный живёт только в памяти.
                Access.dropPending(e.message ?: "подключение не удалось")

                // ПОВОД 3: туннель не встал, а ключ у нас числится
                // годным. Расхождение между нашей записью и отказом
                // шлюза — самый вероятный признак того, что ключ больше
                // не тот: истёк, отозван, удалён.
                //
                // Только когда сеть НЕ менялась: при смене сети виноват
                // канал, а не ключ, и спрашивать про него незачем.
                // Мы уже на фоновом потоке, звать можно прямо здесь.
                if (Access.hasKey() && !networkChanged()) {
                    try {
                        Access.refreshKey(force = true)
                    } catch (t: Throwable) {
                        TunnelLog.add("перепроверка ключа сорвалась: ${t.message}")
                    }
                }

                if (e.message.orEmpty().contains("уже поднята")) {
                    // ТУННЕЛЬ УЖЕ РАБОТАЕТ. Это не отказ, а "делать
                    // нечего", и трогать нельзя вообще ничего.
                    //
                    // Висело с 22-й задачи: ошибка шла в общий catch,
                    // тот звал stopTunnel(), и лишняя попытка
                    // подключения гасила РАБОТАЮЩИЙ туннель.
                    //
                    // ВЕТКА ПЕРВАЯ В ЦЕПОЧКЕ, и это не вкусовщина.
                    // Ниже стоят ветки, которые зовут scheduleReconnect,
                    // а он начинает с Engine.stop() — то есть убил бы
                    // живую сессию тем же способом, только окольным.
                    // Достаточно, чтобы в этот момент сменилась сеть
                    // или это была попытка переподключения.
                    //
                    // Защёлка connecting делает такой заход редким, но
                    // не невозможным: Engine.awaitStopped мог истечь по
                    // сроку, а сессия дожить.
                    TunnelLog.add("сессия уже поднята — службу и движок не трогаю")
                } else if (noNet) {
                    // НЕТ СЕТИ — НЕ ОТКАЗ, А ОТСУТСТВИЕ. Счётчик неудач
                    // НЕ трогаем: перегон метро длиннее, чем те 47
                    // секунд, за которые копится предел сдачи, и
                    // считать отсутствие сети провалом — значит не
                    // подняться самим, когда сеть вернётся. Сам
                    // scheduleReconnect увидит отсутствие сети и уйдёт в
                    // ровное ожидание вместо роста паузы.
                    scheduleReconnect("сети нет")
                } else if (networkChanged()) {
                    // Сеть ушла из-под ног. Это не отказ пути и не повод
                    // гасить службу даже на первой попытке: сеть уже
                    // другая, надо просто начать на ней заново.
                    //
                    // Счётчик неудач при этом растёт наравне с обычными:
                    // мигающая сеть иначе крутила бы нас вечно.
                    main.post { reconnectFails++ }
                    scheduleReconnect("сеть сменилась во время подъёма")
                } else if (isReconnect) {
                    // Это была попытка переподключения. Гасить службу
                    // рано: сеть могла ещё не устояться. Пробуем снова,
                    // с растущей паузой и с пределом на число попыток.
                    main.post { reconnectFails++ }
                    scheduleReconnect("предыдущая попытка не удалась")
                } else if (generation.get() != gen) {
                    // НАША ПОПЫТКА УЖЕ УСТАРЕЛА. Гасить службу нельзя:
                    // сессией владеет кто-то другой, и stopTunnel()
                    // убил бы ЧУЖОЙ работающий туннель.
                    //
                    // Ровно это и происходило до защёлки connecting:
                    // проигравший поток валился с «сессия уже поднята» и
                    // тут же гасил только что поднятую сессию соседа.
                    // Защёлка эту гонку закрывает, а проверка ниже
                    // остаётся вторым рубежом — цена ошибки здесь
                    // слишком велика для одного рубежа.
                    TunnelLog.add("попытка устарела (поколение $gen) — службу не трогаю")
                } else if (Access.hasKey() && !Access.keyProven()) {
                    // КЛЮЧ ВЫДАН, НО ПОДКЛЮЧЕНИЕМ ЕЩЁ НЕ ПРОВЕРЕН —
                    // сдаваться с первой попытки рано.
                    //
                    // Шлюз перечитывает список паролей раз в минуту.
                    // Всё это время свежий ключ для него не существует,
                    // и он молчит: разобрать пакет он не может, а
                    // отказать — тем более, до разбора пароля дело не
                    // доходит. 26.08 это дало шесть "подключиться не
                    // удалось" за сорок секунд, а через три минуты тот
                    // же ключ подключился с первого раза.
                    //
                    // Отдельного таймера тут нет и не нужно: обычная
                    // лестница переподключений с растущей паузой
                    // (3+6+12+24+48 секунд, предел RECONNECT_MAX_FAILS)
                    // сама укладывается примерно в полторы минуты — как
                    // раз с запасом на минуту синхронизации.
                    main.post { reconnectFails++ }
                    Notice.say("Ключ выдан только что — серверу нужно до минуты")
                    scheduleReconnect("ключ ещё не подтверждён подключением")
                } else {
                    // Сдаёмся с первой попытки: не смена сети и не
                    // повтор. Это и есть тот случай, ради которого
                    // строка состояния существует, — иначе человек
                    // видит неподвижную планету и не знает почему.
                    Notice.problem(
                        when {
                            noNet -> "Нет сети"
                            standsAlone(e) -> reason
                            else -> "Не удалось подключиться: $reason"
                        }
                    )
                    stopTunnel()
                }
            } finally {
                // ЗАЩЁЛКА СНИМАЕТСЯ ВСЕГДА — и после успеха, и
                // после любой ошибки. Незакрытая защёлка означала
                // бы приложение, которое больше никогда не
                // подключится, и лечилось бы только перезапуском.
                connecting.set(false)
                // Удержание процессора снимается здесь же и по той же
                // причине: подъём кончился в любом исходе.
                try {
                    if (wake != null && wake.isHeld) wake.release()
                } catch (e: Throwable) {
                    // Уже снято системой по сроку — это не беда.
                }
            }
        }
    }

