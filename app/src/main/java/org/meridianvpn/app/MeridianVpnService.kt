    /**
     * KILL SWITCH.
     *
     * АВАРИЙНЫЙ ВЫКЛЮЧАТЕЛЬ, А НЕ ПРОСТО ЛОГ. Без него между падением
     * туннеля и новым подъёмом Android возвращает трафик всех
     * приложений на настоящую сеть — интерфейс VPN снят, значит
     * маршрут 0.0.0.0/0 больше никуда не ведёт, и система откатывается
     * на обычный. Раньше это окно было ЦЕЛОЙ ПАУЗОЙ ПЕРЕПОДКЛЮЧЕНИЯ
     * (1-24 с, а при смене сети и правда сколько угодно) — то самое
     * «светит IP», от которого просил защититься владелец.
     *
     * ЧТО ДЕРЖИТ blackhole. Свой интерфейс VpnService — тот же захват
     * трафика (0.0.0.0/0, ::/0, DNS, раздельное туннелирование), что и
     * у боевого, но БЕЗ движка позади: пакеты, которые в него попадут,
     * никто не читает и никуда не пересылает. Устройство молчит вместо
     * того, чтобы заговорить настоящим адресом — обмен, ради которого
     * Kill Switch и существует.
     *
     * ГДЕ ГРАНИЦА ЗАЩИТЫ, ЧЕСТНО. ПРАВКА 15.09 ЗАКРЫЛА ОСТАВАВШИЙСЯ
     * ЗАЗОР — было иначе, история важна, чтобы не переоткрыть его
     * заново по забывчивости.
     *
     * Первая версия (14.09) ставила заглушку в scheduleReconnect() —
     * то есть в onStopped, который engine/session.go зовёт ПОСЛЕДНИМ,
     * когда TUN уже закрыт и насосы уже вышли. Для обрыва, который
     * находит сам движок (немота, тишина канала — самый частый случай в
     * жизни), это означало реальный, хоть и небольшой зазор: TUN закрыт
     * раньше, чем Kotlin вообще узнаёт об обрыве.
     *
     * Правка 15.09 добавила движку второй колбэк — StateListener.onStopping,
     * который session.stop() (engine/session.go) зовёт ПЕРВОЙ строкой,
     * ДО закрытия TUN. Заглушка встаёт там, пока прежний туннель ещё
     * формально жив — и Android заменяет интерфейс АТОМАРНО (establish()
     * второй раз сам гасит прежний, чем бы он ни был), так что окна без
     * защиты не остаётся вовсе. Это верно для ОБОИХ источников обрыва
     * теперь: и для того, что находит движок сам, и для того, что
     * распознаёт сам Kotlin (пропала сеть, сменился адрес,
     * ACTION_RECONNECT) — для вторых, впрочем, зазора не было и раньше.
     *
     * Единственное, что защитить в принципе нельзя: те несколько
     * миллисекунд, за которые обрыв УЖЕ произошёл на проводе, но ни
     * движок, ни Kotlin о нём ещё не знают, — раньше ЭТОГО момента
     * защиты не бывает никогда, ни в одной реализации.
     *
     * ГДЕ ЗАЩИТЫ НЕТ СОЗНАТЕЛЬНО. Сдача (RECONNECT_MAX_FAILS,
     * QUICK_DROP_LIMIT) и явное «Отключить» по-прежнему гасят службу
     * целиком через shutdownService() — Kill Switch снимается вместе с
     * ней, и человек возвращается на открытую сеть, как было до этой
     * правки. Владелец просил защиту на КАЖДОЕ переподключение, а не
     * бессрочную блокировку после отказа от попыток — это разные
     * решения, второе я не принимал сам.
     *
     * ВИДИМОСТЬ В ЛОГЕ. TunnelLog.add() внутри — дебаг-онли по
     * BuildConfig.DEBUG (15.09 обнаружено при разборе релизного dex:
     * оказалось, что и десятки других строк в этом файле — тоже, это
     * старый и осознанный порядок, не поломка). Само срабатывание при
     * этом ОБЪЯВЛЕНО ОТДЕЛЬНО через TunnelLog.event() — тот виден и в
     * релизе, и разбор через него человеку не мешает: одна строка на
     * обрыв, без слова о механизме (announce/wasAlready внутри
     * establishBlackhole решают, когда её показывать).
     *
     * Мутации — только под killSwitchLock: establishBlackhole()
     * зовётся и с потока подъёма, и из колбэка движка (произвольный
     * поток gomobile), а dropBlackhole() — оттуда же и с главного.
     */
    private val killSwitchLock = Any()

    @Volatile
    private var blackhole: ParcelFileDescriptor? = null

    /**
     * Поднимает заглушку — или переустанавливает её, если уже стояла.
     *
     * ВЫЗЫВАТЬ КАК МОЖНО РАНЬШЕ. Каждая лишняя миллисекунда до этого
     * вызова — окно настоящей утечки, см. разбор у blackhole.
     *
     * Провал НЕ бросает исключение и не гасит службу: Kill Switch —
     * подстраховка, а не главный путь, и её собственная ошибка не
     * должна ронять то, что она защищает. Строка в лог обязана быть
     * достаточно громкой, чтобы её не пропустили при разборе утечки.
     */
    /**
     * @param announce Сказать об этом человеку через TunnelLog.event() —
     * то есть видимо и в РЕЛИЗЕ, не только в дебаге (TunnelLog.add() —
     * дебаг-онли по BuildConfig.DEBUG, TunnelLog.event() — всегда).
     * ВАЖНО ДЕРЖАТЬ ОДНУ СТРОКУ НА ОБРЫВ, А НЕ НА КАЖДЫЙ ВЫЗОВ:
     * establishBlackhole() зовётся дважды на один и тот же обрыв
     * (onStopping и следом scheduleReconnect/onStopped) — вторая
     * попытка видит already-поднятую заглушку (см. wasAlready ниже) и
     * молчит сама, без участия этого флага. Флаг решает другое: НУЖНО
     * ли вообще announce для этого ВЫЗЫВАЮЩЕГО — startTunnel() шлёт
     * false для самого первого «Подключить», где заглушка защищает
     * подъём лестницы, а не чинит обрыв, и рассказывать человеку
     * «включилась защита» на обычном подключении было бы враньём по
     * смыслу, не по факту.
     */
    private fun establishBlackhole(reason: String, announce: Boolean = true) = synchronized(killSwitchLock) {
        val wasAlready = blackhole != null
        try {
            val builder = Builder()
                .setSession("Meridian")
                .addAddress(BLACKHOLE_ADDRESS, BLACKHOLE_PREFIX)
                .addRoute("0.0.0.0", 0)
            for (s in DNS_SERVERS) builder.addDnsServer(s)
            // Тот же best-effort, что у боевого интерфейса (комментарий
            // там же): отказ означает утечку по v6, и молчать о нём
            // нельзя, но и ронять заглушку из-за него нельзя тоже.
            try {
                builder.addRoute("::", 0)
            } catch (e: Throwable) {
                TunnelLog.add(
                    "Kill Switch: IPv6 в заглушку забрать не вышло (${e.message})"
                )
            }
            // Раздельное туннелирование действует и здесь: приложения,
            // выведенные человеком из-под VPN, не обязаны терять
            // интернет из-за того, что VPN сейчас в разрыве, — это ИХ
            // осознанный выбор, а не то, что защищает Kill Switch.
            SplitTunnel.apply(builder, this)
            val pfd = builder.establish()
            if (pfd == null) {
                TunnelLog.add(
                    "Kill Switch: establish() заглушки вернул null ($reason) — " +
                        "разрешение VPN отозвано, защиты сейчас нет"
                )
                // Отказ защиты видно и в релизе — это настоящее окно
                // утечки, а не рутинная деталь устройства.
                TunnelLog.event("Kill Switch не встал: разрешение VPN отозвано")
                return@synchronized
            }
            // Прежняя заглушка (если была) этим же вызовом уже заменена
            // Android'ом — закрываем свою ссылку на неё вслед, чтобы не
            // держать мёртвый дескриптор.
            blackhole?.let { runCatching { it.close() } }
            blackhole = pfd
            TunnelLog.add("Kill Switch: держу интерфейс без движка ($reason)")
            // ВИДНО И В РЕЛИЗЕ. Одна строка на обрыв — !wasAlready
            // отсекает повторный вызов на тот же обрыв (см. announce
            // выше), а announce отсекает routine-подключение, где
            // заглушка защищает подъём лестницы, а не чинит обрыв.
            if (announce && !wasAlready) {
                TunnelLog.event("Kill Switch сработал: интернет заблокирован, пока туннель не восстановится")
            }
        } catch (e: Throwable) {
            TunnelLog.add(
                "Kill Switch: заглушка не встала (${e.message}) — защиты сейчас нет"
            )
            TunnelLog.event("Kill Switch не встал: защиты сейчас нет")
        }
    }

    /**
     * Снимает заглушку.
     *
     * Зовётся, когда её сменил настоящий туннель (established() тем же
     * вызовом уже подменил интерфейс — здесь только освобождаем свою
     * ссылку), и при полной остановке службы (shutdownService()), где
     * заменять заглушку уже нечем: человек либо отключился сам, либо мы
     * сдались.
     */
    private fun dropBlackhole() = synchronized(killSwitchLock) {
        blackhole?.let { runCatching { it.close() } }
        blackhole = null
    }

    /** Наблюдение за сетями под туннелем. */
    private val netWatch = NetworkWatch(
        this,
        onUnderlyingLost = { net -> onUnderlyingLost(net) },
        onUnderlyingAddrChanged = { net -> onUnderlyingAddrChanged(net) },
        onUnderlyingSuspect = { net -> onUnderlyingSuspect(net) },
        onUnderlyingAvailable = { net -> onUnderlyingAvailable(net) },
