package org.meridianvpn.app

/**
 * Засев пула ссылок VK — ТОЛЬКО В ОТЛАДОЧНОЙ СБОРКЕ.
 *
 * Файл собирается лишь в debug. В релизе на его месте одноимённый файл
 * из app/src/release, возвращающий пустой список, и ссылки на Config
 * там нет вовсе.
 *
 * ПОЧЕМУ НЕ ПРОСТО if (BuildConfig.DEBUG). Так и было, и не сработало:
 * поиск по собранному релизному APK нашёл ссылки на звонки внутри dex.
 *
 * Причина в том, что Config — объект Kotlin, и весь его инициализатор
 * попадает в класс целиком. Config нужен в релизе ради адреса шлюза и
 * портов, значит остаётся и список ссылок рядом, даже если ни одна
 * ветка его не читает. Выбросить его R8 не может: это не мёртвый код, а
 * живое поле живого класса.
 *
 * Разные наборы исходников снимают вопрос: в релизе ссылки на
 * Config.VK_HASHES нет ни одной, и класс со списком выбрасывается
 * целиком — не по догадке об оптимизаторе, а потому что на него никто
 * не смотрит.
 */
fun seedHashes(): List<String> = DebugHashes.VK_HASHES

/**
 * Адрес STUN для проверки отображения NAT — ТОЛЬКО В ОТЛАДКЕ.
 *
 * Движок спросит, каким наш адрес видно снаружи: при подъёме и ещё раз
 * когда сторож объявит туннель немым. Разошлись — подтверждается
 * главная гипотеза по дефекту «принято 0»: операторский NAT
 * переназначил нас посреди сессии, а шлюз различает клиентов по адресу
 * источника.
 *
 * Адрес берём тот, что уже есть в настройках, — запасной TURN. Сервер
 * TURN отвечает на обычный запрос STUN без всякой проверки прав, и
 * заводить ради пробы новый чужой узел, о котором в приложении раньше
 * не было ни слова, незачем.
 */
fun probeStunAddr(): String = Config.TURN_ADDR_BACKUP

/**
 * Глубокая диагностика — В ОТЛАДКЕ ВКЛЮЧЕНА.
 *
 * Контрольный AUTH со второго сокета в момент немоты. Ответ пришёл —
 * путь и сеть живы, ломается именно прежнее соединение. Ответа нет — до
 * шлюза не доходит ничего, каким бы сокетом ни идти.
 *
 * Это последняя развилка дефекта «принято 0», и разделить её больше
 * нечем: адрес источника, внешнее отображение и эхо уже измерены.
 */
fun deepProbe(): Boolean = true

/**
 * Откуда брать обновления — ОТЛАДКА: закрытый репозиторий владельца.
 *
 * Отдельный от раздачи, и закрытый намеренно: отладочная сборка несёт
 * личные ссылки на звонки VK из Config.kt, подробный лог и глубокую
 * диагностику. Выложить её открыто значило бы раздать всё это всем.
 */
fun updateRepo(): String = "OWNER/private-debug-repo"

/**
 * Нужен ли токен — ОТЛАДКА: ДА, но В СБОРКЕ ЕГО НЕТ.
 *
 * Токен владелец вставляет руками, один раз, на экране настроек. Он
 * ложится в настройки приложения — туда же, где живёт ключ доступа, — и
 * переживает установку поверх.
 *
 * ПОЧЕМУ НЕ ЗАШИТЬ ЕГО В СБОРКУ, хотя так было бы проще: APK лежит на
 * телефоне, и зашитый токен уезжает вместе с телефоном. Введённый
 * руками живёт в закрытом хранилище приложения и отзывается одной
 * кнопкой на GitHub. Разница невелика, но она в нашу пользу, а стоит
 * одно текстовое поле.
 */
fun updatePrivate(): Boolean = true
