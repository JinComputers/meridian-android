package org.meridianvpn.app

/**
 * Засев пула ссылок VK — В РЕЛИЗЕ ЕГО НЕТ.
 *
 * Ссылки на звонки человек заводит свои: чужие в его сборке — это чужой
 * расход и чужая капча. А в раздаваемом APK они означали бы, что личные
 * ссылки владельца получил каждый, кто его поставил.
 *
 * Разбор, почему это отдельный файл, а не проверка BuildConfig.DEBUG, —
 * в app/src/debug/.../Seed.kt.
 */
fun seedHashes(): List<String> = emptyList()

/**
 * Адрес STUN для отладочной проверки отображения NAT — В РЕЛИЗЕ ПУСТО.
 *
 * Пустой адрес означает для движка «пробы нет вовсе»: ни одного лишнего
 * пакета на провод. Это важно не для трафика, а для профиля: голый
 * пакет STUN с боевого сокета отличает нас от роутерного клиента, а
 * вся наша необнаружимость держится ровно на неотличимости.
 *
 * ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРОВЕРКА BuildConfig.DEBUG, и это не
 * перестраховка. На хешах VK мы уже обожглись: недостижимая ветка
 * оставила строки в собранном dex, и нашлись они обычным grep. Здесь
 * цена ошибки та же — проверяемость. Разделение по наборам исходников
 * проверяется по собранному пакету, а вера в оптимизатор — ничем.
 */
fun probeStunAddr(): String = ""

/**
 * Глубокая диагностика — В РЕЛИЗЕ ВЫКЛЮЧЕНА.
 *
 * Сегодня это контрольный AUTH со второго сокета в момент, когда сторож
 * объявил туннель немым. Он разделяет две оставшиеся ветки дефекта
 * «принято 0», и другого способа их разделить со стороны клиента нет.
 *
 * Выключена в релизе не из осторожности, а по той же причине, что и
 * проба NAT: лишний AUTH на проводе — лишний отпечаток, а вся наша
 * необнаружимость держится на неотличимости от роутерного клиента.
 *
 * ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРОВЕРКА BuildConfig — разбор там же, где у
 * probeStunAddr: недостижимая ветка оставляет строки в собранном dex, и
 * находятся они обычным grep.
 */
fun deepProbe(): Boolean = false

/**
 * Откуда брать обновления — РЕЛИЗ: открытый репозиторий с раздачей.
 */
fun updateRepo(): String = "JinComputers/meridian-android"

/**
 * Нужен ли токен для скачивания — РЕЛИЗ: НЕТ.
 *
 * Репозиторий раздачи открыт, и обращаться к нему надо обычным адресом
 * без всякой авторизации. Заголовок с токеном в релизной сборке
 * означал бы, что в ней токен есть, — а его там нет и быть не должно.
 */
fun updatePrivate(): Boolean = false
