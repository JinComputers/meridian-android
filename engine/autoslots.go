// Автоподбор числа слотов на релее.
//
// За основу взят autoSlots роутерного клиента (спецификация-2, C.5), но
// ПРИЗНАК РОСТА заменён, и это главное отличие. Роутер меряет простой
// ядер через /proc/stat и растёт, пока процессор не загружен. У нас так
// нельзя по двум причинам сразу:
//
//  1. Доступ к /proc для обычного приложения на Android урезан и
//     урезается дальше от версии к версии. Читается ли он на конкретном
//     устройстве, заранее не известно — поэтому мы один раз пробуем и
//     пишем результат в лог, но решений по нему НЕ принимаем.
//
//  2. Даже если бы читался, признак не тот. Роутер упирался в
//     процессор: 7.33 Мбит при 203% из 400%. Телефон с аппаратным AES в
//     процессор не упрётся — он упрётся в канал. Значит и мерить надо
//     канал.
//
// Что осталось от роутера дословно, потому что от платформы не зависит:
// асимметрия «расти медленно, снимать быстро», окупаемость по МЕДИАНЕ
// нескольких окон, заморозка с таймером и досрочным снятием по скачку
// полосы, запрет роста после снятия.
const (
	// slotWindow — длина окна наблюдения.
	//
	// У роутера 60 секунд (C.5). Взято 20: сессия на телефоне живёт
	// минуты, а не сутки, и с минутными окнами третий слот появлялся бы
	// на третьей минуте — то есть почти никогда.
	//
	// Это ПОЛНОЕ окно, действующее после разгона. На разгоне работает
	// вдвое более короткое, см. slotWindowRamp: с полным окном на всём
	// пути дорога от одного слота до девяти занимала двенадцать минут,
	// то есть дольше почти любого сеанса.
	//
	// [ПОРОГ НЕ ПОДТВЕРЖДЁН ЗАМЕРОМ]
	slotWindow = 20 * time.Second

	// minWindowBytes — ниже этого объёма за окно роста нет.
	//
	// Смысл тот же, что у роутера (200 КБ/окно при 60 с): нет трафика —
	// нечего и разгонять. Пересчитано на наше окно и округлено вверх:
	// 256 КБ за 20 секунд это около 100 кбит/с.
	//
	// ЗАМЕР ПОДТВЕРДИЛ ПРИГОДНОСТЬ. Рабочая полоса на релее — от 1.9
	// Мбит на одном слоте до 13.46 на восьми, то есть от 4.75 до 33.6
	// МБ за двадцатисекундное окно. Порог лежит в двадцать раз ниже
	// самого тихого рабочего окна: настоящую нагрузку он не отсечёт, а
	// простой отличит.
	minWindowBytes = 256 * 1024

	// idleShrinkBytes — окно тише этого считается простоем, и слот
	// снимается НЕМЕДЛЕННО, без подтверждения вторым окном.
	//
	// Заменяет роутерное «простой меньше 0.25 ядра». У нас лишние слоты
	// стоят не процессора, а keepalive-ов, соединений на шлюзе и износа
	// аллокаций на релее — значит и снимать их надо, когда возить нечего.
	//
	// ЗАМЕР ПОДТВЕРДИЛ ПРИГОДНОСТЬ: порог в семьдесят с лишним раз ниже
	// самого тихого рабочего окна (4.75 МБ), спутать нагрузку с простоем
	// он не может.
	idleShrinkBytes = 64 * 1024

	// growWindows — столько подряд «здоровых» окон нужно для роста.
	// Перенесено из C.5 как есть: асимметрия с одним окном на снятие и
	// есть то самое «расти медленно, снимать быстро».
	growWindows = 2

	// gainWindows — сколько окон до и после добавления слота собирается
	// для оценки окупаемости. Из C.5 как есть.
	gainWindows = 3

	// minGainFraction — прирост полосы по МЕДИАНЕ меньше этого означает
	// «потолок канала», рост замораживается.
	//
	// У роутера 5%. Поднято до 10%, потому что наше окно втрое короче
	// и потому шумнее: на 5% при 20-секундных окнах мы ловили бы шум.
	//
	// ЗАМЕР ПОДТВЕРДИЛ. Насыщения на релее нет вовсе: отдача на слот
	// 1.45-1.68 Мбит и не падает (1 слот 1.9, 2 — 2.9, 4 — 6.0,
	// 8 — 13.46). При линейной отдаче предельный прирост от N к N+1
	// равен ровно 1/N, то есть:
	//
	//	8 → 9 слотов: +12.5%   выше порога
	//	9 → 10:       +11.1%   выше порога
	//	10 → 11:      +10.0%   вот здесь порог наконец связал бы
	//
	// Наш потолок девять, до одиннадцати дело не дойдёт никогда. Значит
	// контроллер останавливается О ПОТОЛОК, а не о порог, — как и
	// задумано. Замеренная кривая вдобавок чуть ЛУЧШЕ линейной (отдача
	// на слот растёт с 1.45 до 1.68), так что запас ещё больше.
	//
	// Порог при этом не бесполезен: он сторожит случай, когда канал
	// насытится раньше — тогда прирост упадёт резко, а не по 1/N.
	minGainFraction = 0.10

	// frozenRetry — через сколько заморозка снимается сама.
	//
	// У роутера 15 минут, у нас было 5 — и замер показал, что это чистая
	// потеря времени: дважды подряд ждали по пять минут, и оба раза
	// сразу после снятия рост удавался.
	//
	// Минута. Окно у нас вчетверо короче роутерного, сессия живёт
	// минутами, а не сутками. Цена ошибки мала: при настоящем потолке
	// следующая попытка просто снова заморозится, потеряв одно окно.
	frozenRetry = time.Minute

	// slotWindowRamp — короткое окно НА РАЗГОНЕ.
	//
	// Пока не случилось ни одной заморозки и ни одного снятия, мы
	// заведомо далеко от насыщения, а перерасти не даёт потолок в девять
	// слотов. Значит и осторожничать не перед чем — можно вдвое быстрее.
	//
	// После первого же признака насыщения окно становится полным: там,
	// где решение близко к порогу, короткое окно только шумит.
	slotWindowRamp = 10 * time.Second

	// fastGainFraction — «очевидный успех», принимаемый без медианы.
	//
	// Три окна и медиана нужны, чтобы отличить настоящий прирост от шума
	// У ПОРОГА. Когда первое же окно после роста показало вдвое больше
	// порога, сомневаться не в чем: шум такого размаха не даёт.
	//
	// Ровно 2×minGainFraction, и это не совпадение — множитель и есть
	// смысл величины. Считается, а не пишется числом, чтобы при правке
	// порога не разъехалось.
	fastGainFraction = 2 * minGainFraction

	// minLoadedWindows — сколько НАГРУЖЕННЫХ окон нужно, чтобы вообще
	// выносить вердикт об окупаемости.
	//
	// Меньше двух — свидетельства нет: одно окно на мобильной сети
	// ничего не значит, а ноль тем более.
	minLoadedWindows = 2

	// maxPostpone — сколько раз подряд можно отложить вердикт, добирая
	// ещё окно.
	//
	// Не бесконечно: если источник так и не даёт нагрузки, судить не о
	// чем и ждать больше нечего. По исчерпании вердикт НЕ выносится
	// вовсе — рост просто продолжается, и его ограничивает потолок.
	maxPostpone = 3

	// frozenBandJump — во сколько раз должна вырасти полоса, чтобы
	// заморозка снялась ДОСРОЧНО.
	//
	// У роутера полтора раза, и столько же стояло у нас. Замер показал,
	// что при таком пороге досрочное снятие не срабатывает НИКОГДА: оба
	// раза заморозка снималась по таймеру. Полуторакратный скачок — это
	// про рывок канала, а канал растёт постепенно.
	//
	// 1.15: пятнадцати процентов роста достаточно, чтобы усомниться в
	// собственном вердикте о потолке. Проверка идёт на КАЖДОМ окне, а не
	// по таймеру, — так было и раньше, просто порог был недостижим.
	frozenBandJump = 1.15

	// maxUnprofitable — сколько неокупившихся ростов ПОДРЯД терпим,
	// прежде чем прекратить рост до конца сессии.
	//
	// Три вердикта «ниже порога» подряд — это не шум, это колено кривой.
	// Дальше можно только качаться: заморозка, разморозка, рост на
	// шесть процентов, снова заморозка. До сих пор способа сказать
	// «приехали» не было вовсе — заморозка всегда временная.
	//
	// Счётчик обнуляется ЛЮБЫМ окупившимся ростом: колено сдвигается,
	// если канал изменился, и вчерашний потолок сегодня может быть не
	// потолком.
	maxUnprofitable = 3

	// shrinkLock — после снятия слота рост запрещён это время.
	// Защита от маятника. У роутера 5 минут, у нас 2 — пропорционально
	// укороченному окну.
	//
	// [ПОРОГ НЕ ПОДТВЕРЖДЁН ЗАМЕРОМ]
	shrinkLock = 2 * time.Minute

	// idleNoLoadGrace — сколько терпим МОЛЧАЩИЙ туннель, прежде чем
	// начать снимать лишние слоты, так и не увидев нагрузки.
	//
	// Зачем предел вообще. sawLoad — вето без срока: пока не было
	// настоящей нагрузки, слоты не снимаются никогда. 08.09 в логе
	// владельца это дало четыре релейных слота, живущих две минуты при
	// полном молчании: из 61 отправленного пакета 28 были эхо. Каждый
	// слот держит TURN-аллокацию на релее VK — то есть мы занимали
	// четыре чужих аллокации ни за что.
	//
	// Полторы минуты, а не двадцать секунд. Замер, ради которого вето
	// заводилось, был именно про двадцать: подключились в 15:41:40, в
	// 15:42:00 сняли слот по окну в девять килобайт и запретили рост на
	// две минуты — трафик просто не успел пойти. Полторы минуты дают
	// медленному старту вчетверо больший запас и всё же кончаются.
	idleNoLoadGrace = 90 * time.Second
)

// probeProcStat — один раз пробует прочитать /proc/stat и пишет
// результат в лог.
//
// Решений по нему НЕ принимается. Нужно только затем, чтобы ответить
// фактом на вопрос «читается ли он у нас вообще»: с устройства это
// видно, а из моей памяти — нет.
func (s *session) probeProcStat() {
	b, err := os.ReadFile("/proc/stat")
	if err != nil {
		s.logf("/proc/stat не читается (%v) — решения по нему и не принимаются", err)
		return
	}
	line := string(b)
	if len(line) > 60 {
		line = line[:60]
	}
	s.logf("/proc/stat читается, начало: %q — но решения принимаются по каналу", line)
}

// autoSlots — контроллер числа слотов.
//
// Живёт внутри сессии, а не между ними, как у роутера: у нас сессия
// пересоздаётся при каждой смене сети, и переносить в новую сеть выводы,
// сделанные в старой, было бы прямой ошибкой — полоса там другая.
type autoSlots struct {
	s *session

	// history — объём за последние окна, новые в конце.
	history []uint64

	healthy   int       // подряд здоровых окон
	frozen    bool      // рост заморожен: уперлись в потолок канала
	frozenAt  time.Time //
	frozenAvg float64   // полоса на момент заморозки, для frozenBandJump
	lockUntil time.Time // рост запрещён до этого момента (после снятия)

	// frozenSlots — сколько слотов было на момент заморозки.
	//
	// Вместе с frozenAvg отвечает на вопрос «изменилось ли хоть что-то
	// с тех пор». Если нет — поднимать слот, чтобы заново выяснить то
	// же самое, значит тратить аллокацию впустую.
	frozenSlots int

	// unprofitable — неокупившихся ростов подряд.
	unprofitable int

	// growthOver — рост прекращён до конца сессии.
	//
	// Не то же самое, что заморозка: та временная и снимается сама,
	// эта окончательна. Снятие слотов по простою при этом продолжает
	// работать — лишние слоты остаются лишними.
	growthOver bool

	// beforeGrow — окна ДО последнего добавления слота, afterGrow —
	// после. Оценка окупаемости идёт по медиане и того, и другого.
	beforeGrow []uint64
	afterGrow  []uint64
	awaiting   int // сколько окон после роста ещё собираем

	// postponed — сколько раз подряд вердикт отложен из-за нехватки
	// нагруженных окон.
	postponed int

	// cur — длина окна СЕЙЧАС. На разгоне короткая, дальше полная.
	cur time.Duration

	// ramp — идёт разгон: ни заморозки, ни снятия ещё не случилось.
	ramp bool

	// sawLoad — было ли хоть одно окно с НАСТОЯЩЕЙ нагрузкой.
	//
	// До этого момента тихое окно означает «ещё не началось», а не «уже
	// не нужно», и снимать по нему слоты нельзя. Замер показал, во что
	// это обходится: подключились в 15:41:40, в 15:42:00 сняли слот по
	// окну в девять килобайт и запретили рост на две минуты — трафик
	// просто не успел пойти.
	sawLoad bool

	ticker *time.Ticker
}

// scaled пересчитывает порог, заданный «за полное окно», на текущее.
//
// Без этого пересчёта короткое окно врало бы дважды: вдвое меньше байт
// не дотягивало бы до minWindowBytes и рост не начинался бы никогда, а
// idleShrinkBytes, наоборот, принимал бы рабочую нагрузку за простой и
// снимал слоты под трафиком.
func (a *autoSlots) scaled(base uint64) uint64 {
	return base * uint64(a.cur) / uint64(slotWindow)
}

// leaveRamp переводит контроллер из разгона в осторожный режим.
// Зовётся по первому признаку насыщения — заморозке или снятию.
func (a *autoSlots) leaveRamp(why string) {
	if !a.ramp {
		return
	}
	// Выход из разгона — только по признаку насыщения, а признак
	// осмыслен лишь после настоящей нагрузки. Снятие слота до первого
	// байта таким признаком не является и сюда больше не доходит (см.
	// sawLoad), но условие оставлено вторым заслоном: цена ошибки —
	// вдвое подорожавший каждый следующий слот.
	if !a.sawLoad {
		a.s.logf("автослоты: %s, но нагрузки ещё не было — разгон продолжается", why)
		return
	}
	a.ramp = false
	a.cur = slotWindow
	a.ticker.Reset(slotWindow)
	a.s.logf("автослоты: разгон окончен (%s), окно %s → %s", why, slotWindowRamp, slotWindow)
}

func (s *session) runAutoSlots() {
	s.probeProcStat()

	a := &autoSlots{s: s, cur: slotWindowRamp, ramp: true}
	t := time.NewTicker(slotWindowRamp)
	defer t.Stop()
	a.ticker = t

	s.logf("автоподбор слотов включён: окно %s (разгон, дальше %s), предел %d",
		slotWindowRamp, slotWindow, s.slotsMax)

	var lastTx, lastRx uint64
	for {
		select {
		case <-s.ctx.Done():
			return
		case <-t.C:
		}

		tx, rx := s.txBytes.Load(), s.rxBytes.Load()
		bytes := (tx - lastTx) + (rx - lastRx)
		lastTx, lastRx = tx, rx
		a.window(bytes)
	}
}

// window — одно окно наблюдения: сюда стекается всё решение.
func (a *autoSlots) window(bytes uint64) {
	s := a.s
	a.history = append(a.history, bytes)
	if len(a.history) > gainWindows*2 {
		a.history = a.history[1:]
	}
	now := time.Now()
	slots := len(s.slotList())
	kbit := float64(bytes) * 8 / 1000 / a.cur.Seconds()

	// Взводим ДО всех решений, в том числе во время оценки окупаемости:
	// нагрузка есть нагрузка, в каком бы состоянии контроллер ни был.
	if !a.sawLoad && bytes >= a.scaled(minWindowBytes) {
		a.sawLoad = true
		s.logf("автослоты: пошла нагрузка (%d КБ за окно), снятие слотов разрешено",
			bytes/1024)
	}

	// Сбор окон после роста — оценка окупаемости.
	if a.awaiting > 0 {
		a.afterGrow = append(a.afterGrow, bytes)
		a.awaiting--

		// ОЧЕВИДНЫЙ УСПЕХ. Первое же окно после роста дало вдвое больше
		// порога — досиживать медиану незачем, растём дальше.
		if len(a.afterGrow) == 1 {
			// Основа сравнения та же, что в judgeGain: максимум
			// нагруженных окон. Иначе быстрый путь и медленный судили бы
			// по разным величинам и расходились бы в выводах.
			if before := maxOf(a.loaded(a.beforeGrow)); before > 0 {
				gain := (float64(bytes) - float64(before)) / float64(before)
				if gain >= fastGainFraction {
					a.awaiting = 0
					// Окупился — счёт неокупившихся начинаем заново.
					a.unprofitable = 0
					s.logf("автослоты: слот окупился СРАЗУ (по одному окну), полоса %d → %d КБ/окно (+%.0f%% при быстром пороге %.0f%%), слотов %d",
						before/1024, bytes/1024, gain*100, fastGainFraction*100, slots)
					return
				}
			}
		}

		if a.awaiting == 0 {
			a.judgeGain(now)
		}
		return
	}

	// Снятие — БЕЗ подтверждения вторым окном, намеренно. Но ТОЛЬКО
	// после того, как нагрузка вообще появлялась: тишина до первого
	// байта означает «ещё не началось».
	if bytes < a.scaled(idleShrinkBytes) && slots > 1 && !a.sawLoad {
		upFor := now.Sub(a.s.upAt)
		if !idleShrinkAllowed(a.sawLoad, slots, upFor) {
			s.logf("автослоты: окно тихое (%d КБ), но нагрузки ещё не было — слот не снимаю",
				bytes/1024)
			return
		}
		// РОСТ ПОСЛЕ ЭТОГО СНЯТИЯ НЕ ЗАПРЕЩАЕМ, и это не оплошность.
		//
		// shrinkLock существует против качелей: снятие по спорному
		// замеру и немедленный рост обратно. Здесь спорить не о чем —
		// за полторы минуты не прошло НИ ОДНОГО байта нагрузки. А цена
		// запрета была бы настоящей: человек, открывший приложение и
		// начавший пользоваться им через две минуты, получил бы урезанную
		// полосу ещё на две минуты сверху.
		if victim := s.dropSlot(); victim != nil {
			victim.close()
			a.healthy = 0
			s.logf("автослоты: %s без единого байта нагрузки — снимаю лишний слот "+
				"(осталось %d), рост НЕ запрещаю",
				upFor.Round(time.Second), len(s.slotList()))
		}
		return
	}
	if bytes < a.scaled(idleShrinkBytes) && slots > 1 {
		if victim := s.dropSlot(); victim != nil {
			victim.close()
			a.lockUntil = now.Add(shrinkLock)
			a.healthy = 0
			s.logf("автослоты: снимаю слот, за окно %d КБ (%.0f кбит/с) при пороге простоя %d КБ; слотов %d, рост запрещён %s",
				bytes/1024, kbit, a.scaled(idleShrinkBytes)/1024, len(s.slotList()), shrinkLock)
			// Снятие — признак насыщения: разгон окончен.
			a.leaveRamp("снят слот")
		}
		return
	}

	// Рост окончен насовсем — дальше только снятие по простою, оно выше.
	if a.growthOver {
		return
	}

	// Досрочное снятие заморозки по скачку полосы.
	if a.frozen {
		// Тоже максимум нагруженных: frozenAvg записан максимумом, и
		// сравнивать его с медианой значило бы сравнивать разное.
		avg := maxOf(a.loaded(a.history))
		switch {
		case a.frozenAvg > 0 && float64(avg) > a.frozenAvg*frozenBandJump:
			a.frozen = false
			s.logf("автослоты: заморозка снята досрочно, полоса выросла с %.0f до %.0f КБ/окно",
				a.frozenAvg/1024, float64(avg)/1024)

		case now.Sub(a.frozenAt) >= frozenRetry:
			// Срок вышел — но поднимать слот имеет смысл, только если с
			// момента заморозки что-то изменилось. Иначе мы честно
			// потратим аллокацию, чтобы заново выяснить ровно то же
			// самое, что выяснили минуту назад.
			if slots == a.frozenSlots && float64(avg) <= a.frozenAvg {
				a.frozenAt = now
				s.logf("автослоты: срок заморозки вышел, но полоса не выросла (%.0f из %.0f КБ/окно) "+
					"и слотов те же %d — замораживаюсь снова, попытку роста не трачу",
					float64(avg)/1024, a.frozenAvg/1024, slots)
				return
			}
			a.frozen = false
			s.logf("автослоты: заморозка снята по времени, прошло %s", frozenRetry)

		default:
			// Показываем, НАСКОЛЬКО не хватило до досрочного снятия.
			// Без этой строки непонятно, близко ли порог: раньше он был
			// недостижим, и молчание выглядело как «ничего не
			// происходит». Строк тут немного — заморозка живёт минуту.
			s.logf("автослоты: заморожен, полоса %.0f из %.0f КБ/окно, нужных для досрочного снятия",
				float64(avg)/1024, a.frozenAvg*frozenBandJump/1024)
			return
		}
	}

	if now.Before(a.lockUntil) {
		return
	}
	if slots >= s.slotsMax {
		return
	}
	if bytes < a.scaled(minWindowBytes) {
		a.healthy = 0
		return
	}

	a.healthy++
	if a.healthy < growWindows {
		s.logf("автослоты: окно здоровое (%d КБ, %.0f кбит/с), подтверждений %d из %d",
			bytes/1024, kbit, a.healthy, growWindows)
		return
	}

	// Решение о росте.
	a.healthy = 0
	a.beforeGrow = a.tail(a.history, gainWindows)
	a.afterGrow = nil
	a.postponed = 0
	s.logf("автослоты: расту до %d слотов, %d окон подряд по %d КБ и больше",
		slots+1, growWindows, a.scaled(minWindowBytes)/1024)
	go s.growOneSlot()
	a.awaiting = gainWindows
}

// judgeGain — окупился ли добавленный слот.
//
// По МЕДИАНЕ окон до и после, а не по одному окну: одно окно на мобильной
// сети ничего не значит.
// judgeGain — окупился ли добавленный слот.
//
// СУДИМ ПО МАКСИМУМУ НАГРУЖЕННЫХ ОКОН, и это главное здесь.
//
// Медиана отвечала на вопрос «сколько в среднем возили», а спросить
// надо «сколько смогли бы». Источник качает рывками: между рывками
// канал простаивает не потому, что не может, а потому что буфер полон.
// Максимум такие провалы игнорирует, медиана на них попадалась — в
// замере это дало «потолок канала, +0%» с заморозкой, а через минуту
// полоса выросла вдвое, с 12302 до 23287. Канал в момент «потолка» рос.
//
// Окна без нагрузки выбрасываются из обоих наборов: они свидетельство
// о паузе источника, а не о ёмкости канала.
//
// Порог 10% при этом не тронут намеренно: менялась измеряемая
// величина, а не граница, и менять оба разом значит потом не знать,
// что подействовало.
func (a *autoSlots) judgeGain(now time.Time) {
	s := a.s
	bef := a.loaded(a.beforeGrow)
	aft := a.loaded(a.afterGrow)

	// Свидетельства не хватает — ОТКЛАДЫВАЕМ, а не замораживаем.
	// Молчаливая пятиминутная заморозка по несуществующему
	// свидетельству — худший из возможных исходов.
	if len(bef) == 0 || len(aft) < minLoadedWindows {
		if a.postponed < maxPostpone {
			a.postponed++
			a.awaiting = 1
			s.logf("автослоты: вердикт отложен (%d из %d), нагруженных окон до %d, после %d из %d — добираю ещё одно",
				a.postponed, maxPostpone, len(bef), len(aft), len(a.afterGrow))
			return
		}
		// Ждать больше нечего: источник так и не дал нагрузки. Вердикт
		// не выносим вовсе — рост продолжается, его держит потолок.
		a.postponed = 0
		s.logf("автослоты: судить не о чем, нагрузки так и не было — вердикт не выношу, рост продолжается")
		return
	}
	a.postponed = 0

	before := maxOf(bef)
	after := maxOf(aft)
	if before == 0 {
		return
	}
	slots := len(s.slotList())
	gain := (float64(after) - float64(before)) / float64(before)
	if gain >= minGainFraction {
		// Окупился — колено кривой отодвинулось, счёт начинаем заново.
		a.unprofitable = 0
		s.logf("автослоты: слот окупился ПО МАКСИМУМУ %d нагруженных окон из %d, полоса %d → %d КБ/окно (+%.0f%% при пороге %.0f%%), слотов %d",
			len(aft), len(a.afterGrow), before/1024, after/1024,
			gain*100, minGainFraction*100, slots)
		return
	}

	a.unprofitable++
	if a.unprofitable >= maxUnprofitable {
		// ПРИЕХАЛИ. Не заморозка: та временная и снимется сама, эта до
		// конца сессии. Три вердикта «ниже порога» подряд — колено
		// кривой, и дальше можно только качаться.
		a.growthOver = true
		a.frozen = false
		s.logf("автослоты: РОСТ ОКОНЧЕН до конца сессии — %d неокупившихся подряд, "+
			"остаёмся на %d слотах, полоса %d КБ/окно (последний прирост %+.0f%% при пороге %.0f%%)",
			a.unprofitable, slots, after/1024, gain*100, minGainFraction*100)
		a.leaveRamp("рост окончен")
		return
	}

	a.frozen = true
	a.frozenAt = now
	a.frozenAvg = float64(after)
	a.frozenSlots = slots
	s.logf("автослоты: потолок канала ПО МАКСИМУМУ %d нагруженных окон из %d, полоса %d → %d КБ/окно (%+.0f%% при пороге %.0f%%) — рост заморожен на %s, неокупившихся подряд %d из %d",
		len(aft), len(a.afterGrow), before/1024, after/1024,
		gain*100, minGainFraction*100, frozenRetry, a.unprofitable, maxUnprofitable)
	// Заморозка — признак насыщения: разгон окончен.
	a.leaveRamp("уперлись в потолок канала")
}

// loaded оставляет только окна с НАСТОЯЩЕЙ нагрузкой.
//
// Окно ниже порога нагрузки не говорит о ёмкости канала ничего: оно
// говорит, что источник в этот момент не просил. Считать его наравне с
// рабочим — значит мерить аппетит вместо возможностей.
func (a *autoSlots) loaded(v []uint64) []uint64 {
	min := a.scaled(minWindowBytes)
	out := make([]uint64, 0, len(v))
	for _, x := range v {
		if x >= min {
			out = append(out, x)
		}
	}
	return out
}

func maxOf(v []uint64) uint64 {
	var m uint64
	for _, x := range v {
		if x > m {
			m = x
		}
	}
	return m
}

func (a *autoSlots) tail(v []uint64, n int) []uint64 {
	if len(v) <= n {
		out := make([]uint64, len(v))
		copy(out, v)
		return out
	}
	out := make([]uint64, n)
	copy(out, v[len(v)-n:])
	return out
}

// idleShrinkAllowed — пора ли снимать слоты на туннеле, где нагрузки не
// было вовсе.
//
// Вынесено отдельно РАДИ ПРОВЕРЯЕМОСТИ: решение здесь стоит четырёх
// чужих TURN-аллокаций, а остальной автоподбор завязан на состояние и
// таймеры и тестом не накрыт. Эту развилку накрыть можно, и она накрыта.
func idleShrinkAllowed(sawLoad bool, slots int, upFor time.Duration) bool {
	if sawLoad {
		// Нагрузка была — решение принимает обычная ветка снятия,
		// с подтверждением и с запретом роста.
		return false
	}
	return slots > 1 && upFor >= idleNoLoadGrace
}
