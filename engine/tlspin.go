// tlsGatewaySNI — ЗАПАСНОЙ SNI для 443, если приложение своего не дало.
//
// БУКВАЛЬНО ВАЖНО: на 443 стоит nginx, он разбирает поток по SNI
// (ssl_preread) и уводит ЭТО имя на шлюз, а всё прочее — на вебхук
// платежей. Неверный SNI — и поток уедет к вебхуку, упрётся в чужой
// сертификат, сверка отпечатка отвергнет его, ступень не поднимется.
//
// ОСНОВНОЙ SNI ЕДЕТ ИЗ /v1/params (решение кота 2, вариант б): он
// содержит IP в имени (GATEWAY-IP) и переезжает вместе с host. Тут —
// только запаска на случай «ответа службы нет», к тому же адресу, что и
// зашитый запасной host в приложении.
const tlsGatewaySNI = "gw.GATEWAY-IP.sslip.io"

// ТРАНСПОРТ TLS 443 — СВЕРКА ОТПЕЧАТКА СЕРТИФИКАТА ШЛЮЗА.
//
// На TLS-ступени (порт 443, SNI gw.GATEWAY-IP.sslip.io) шлюз
// предъявляет САМОПОДПИСАННЫЙ сертификат. Доверие к цепочке проверять не
// нужно и вредно: доверенного удостоверяющего центра тут нет вовсе, а
// стандартная проверка отвергла бы самоподписанный сертификат.
//
// Вся защита этого транспорта — сверка ОТПЕЧАТКА, посимвольно. Значение
// снято котом 2 31.08 с боевого шлюза. Меняется — только вместе со
// сменой сертификата на шлюзе и только по его слову.
//
// ЧТО ИМЕННО ХЕШИРУЕТСЯ. Отпечаток — SHA-256 от DER-байтов ЛИСТОВОГО
// сертификата целиком (rawCerts[0]), то есть ровно то, что печатает
// `openssl x509 -fingerprint -sha256` без двоеточий. НЕ SPKI-пин (тот у
// нас для API, base64, см. ApiPins.kt) — здесь голый хекс SHA-256, и
// формат значения кота 2 (64 хекс-знака) это подтверждает.
//
// ГДЕ СНЯТО — ЧАСТЬ ЗНАЧЕНИЯ, БЕЗ НЕЁ ОНО НЕПРОВЕРЯЕМО. Отпечаток снят
// с GATEWAY_IP:443 И ОБЯЗАТЕЛЬНО С SNI:
//
//	openssl s_client -connect GATEWAY_IP:443 \
//	  -servername gw.GATEWAY-IP.sslip.io </dev/null 2>/dev/null \
//	  | openssl x509 -fingerprint -sha256 -noout
//
// БЕЗ -servername ТОТ ЖЕ АДРЕС И ПОРТ ОТДАЁТ ДРУГОЙ СЕРТИФИКАТ —
// CN = GATEWAY-IP.sslip.io вместо gw.… Проверяющий без SNI получит
// несовпадение на полностью исправном шлюзе и решит, что подмена.
// Замер кота 2 от 05.09.
//
// Та же беда уже случилась на API: кот 2 померил jinelectronics.ru:443
// вместо :21947, получил чужой ключ и едва не объявил аварию. Дважды за
// один заход, и оба раза адрес совпадал, а мерилось не то. Поэтому
// условия замера пишутся рядом со значением, а не помнятся.
//
// СПИСОК, А НЕ ОДНО ЗНАЧЕНИЕ — поправка кота 2, и она обязательна.
// Ротация сертификата тогда идёт в два спокойных шага: сначала выкатываем
// приложение, знающее И текущий, И следующий отпечаток, потом меняем
// сертификат на шлюзе. Одномоментная смена оставила бы без пути любого,
// кто не успел обновиться. Сегодня в списке один.
var gwCertFingerprints = []string{
	"804897c03285a14294d9fa6cfd62df6554bd175ed84ea2e6d0777821f67c35a0",
	// Следующий отпечаток при ротации — СЮДА, и выкатить релиз ДО смены
	// сертификата на шлюзе.
}

// errNoGatewayCert — шлюз не прислал ни одного сертификата.
var errNoGatewayCert = errors.New("TLS: шлюз не прислал сертификат")

// pinnedGatewayVerify — проверка для tls.Config.VerifyPeerCertificate.
//
// Принимает соединение ТОЛЬКО если отпечаток листового сертификата
// совпал с want. Иначе — ошибка, и рукопожатие обрывается.
//
// ВАЖНО про tls.Config: InsecureSkipVerify обязан быть true. Иначе
// стандартная проверка цепочки отвергнет самоподписанный сертификат ДО
// того, как позовут эту функцию, — и до отпечатка дело не дойдёт. То
// есть InsecureSkipVerify тут не «выключить проверку», а «выключить
// ЧУЖУЮ проверку, чтобы включить свою».
//
// Две ошибки, каждая проверяется отдельно (см. tlspin_test.go):
//   - чужой отпечаток отвергается;
//   - совпадающий принимается.
//
// Без второй «отвергает чужой» неотличимо от «отвергает всё».
func pinnedGatewayVerify(want []string) func([][]byte, [][]*x509.Certificate) error {
	return func(rawCerts [][]byte, _ [][]*x509.Certificate) error {
		if len(rawCerts) == 0 {
			return errNoGatewayCert
		}
		got := certFingerprint(rawCerts[0])
		for _, w := range want {
			if got == w {
				return nil
			}
		}
		// В ошибку кладём пришедший отпечаток: без него нельзя понять,
		// сменился ли сертификат на шлюзе (тогда правим список) или нас
		// подменяют (тогда всё работает как надо).
		return fmt.Errorf("TLS: отпечаток сертификата шлюза не совпал ни с одним из %d известных — пришёл %s", len(want), got)
	}
}

// certFingerprint — SHA-256 DER-сертификата в том же виде, что в
// константе. Вынесено, чтобы тест считал отпечаток тем же способом, что
// и проверка, а не своим.
func certFingerprint(der []byte) string {
	sum := sha256.Sum256(der)
	return hex.EncodeToString(sum[:])
}

// gatewayTLSConfig — tls.Config для TLS-ступени, ОДНО место, откуда его
// берёт боевой дозвон.
//
// Вынесено функцией НАРОЧНО: так тест проверяет ровно тот конфиг, что
// уходит в бой (см. TestGatewayTLSConfigPins). Снятие сверки отсюда
// компилируется, туннель поднимается, и снаружи это неотличимо от
// исправной работы — только доверять будете кому угодно. Тест это ловит.
func gatewayTLSConfig(sni string) *tls.Config {
	return &tls.Config{
		ServerName:            sni,
		MinVersion:            tls.VersionTLS12,
		InsecureSkipVerify:    true, // выключаем ЧУЖУЮ проверку, чтобы включить свою
		VerifyPeerCertificate: pinnedGatewayVerify(gwCertFingerprints),
	}
}
