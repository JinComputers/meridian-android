package engine

import (
	"fmt"
	"io"
	"sync"
	"sync/atomic"
)

// PacketFlow — поток пакетов туннеля там, где дескриптора TUN нет (iOS).
//
// На Android туннель — это файловый дескриптор, и движок читает из него
// обычным Read. У NEPacketTunnelProvider дескриптора нет вовсе: пакеты
// приходят и уходят через readPackets/writePackets, массивами.
//
// Реализуется СТОРОНОЙ ПЛАТФОРМЫ, как Logger, Protector и остальные
// четыре интерфейса. Форма предложена котом 4 по итогам замера
// сгенерированной привязки, разбор — ios/docs/second-entry-proposal.md.
//
// Кадр: [2 байта длины, big-endian][пакет]. Тот же вид, что у кадра в
// streamlink.go, но ДРУГОЙ СЛОЙ — см. комментарий у flowFrameMax.
type PacketFlow interface {
	// ReadBatch блокирует до появления пакетов и отдаёт их одним куском:
	// один или несколько кадров подряд.
	//
	// НАПРАВЛЕНИЕ ДОРОГОЕ, ОТСЮДА ПАЧКИ. Замер кота 4 по сгенерированной
	// привязке: на каждый вызов приходится две копии и аллокация в куче
	// Go (malloc+memcpy на стороне C, затем C.GoBytes). Пачки сокращают
	// ЧИСЛО переходов границы; на объём мусора они почти не влияют —
	// байт копируется столько же.
	//
	// Пустая пачка и nil — ОДНО И ТО ЖЕ и означают ЗАКРЫТИЕ потока.
	// Различить их через границу gomobile невозможно: пустой NSData
	// приезжает в Go как nil-срез. Возвращать пустое в смысле «сейчас
	// нечего» нельзя — переходник примет это за конец.
	//
	// Зовётся ОДНОЙ горутиной (tunToNet). Перед возвратом nil сторона
	// платформы обязана сказать через Logger, почему поток кончился:
	// возврата ошибки здесь нет намеренно, и без этой строки в логе
	// останется только «чтение TUN прекращено: EOF».
	ReadBatch() []byte

	// WriteBatch принимает РОВНО ОДИН кадр — один пакет, как он пришёл
	// из сети. false — поток закрыт.
	//
	// ПОПАКЕТНО, А НЕ ПАЧКАМИ, и это не упущение. Насос вниз зовёт
	// запись, как только пакет пришёл; собирать пачку значит ждать
	// следующего, то есть добавлять задержку каждому пакету, а сигнала
	// «больше сейчас не будет» через io.Writer не выразить. Направление
	// к тому же дешёвое: на стороне Go копий нет вовсе.
	//
	// ЗОВЁТСЯ ПАРАЛЛЕЛЬНО, до slotsMax горутин: netToTun свой на каждый
	// слот. Реализация обязана быть потокобезопасной САМА. Замок в
	// flowConn ниже — это реализация, а не договор: снимут его ради
	// скорости, и молчаливое «вызывающий сериализует» превратится в
	// порчу, которая проявится только под нагрузкой на релее.
	//
	// Байты действительны ТОЛЬКО до возврата из метода: это окно в
	// память Go, а не копия (dataWithBytesNoCopy, freeWhenDone:NO).
	// Нужны после — копировать. Удержание не даст ни ошибки, ни
	// исключения: чтение уехавшей памяти Go выглядит как испорченный
	// пакет.
	//
	// Перед возвратом false — тоже сказать через Logger, почему.
	WriteBatch(b []byte) bool

	// Close — поток больше не нужен.
	//
	// ЗОВЁТ ЕГО ДВИЖОК, из stop(), там же, где сегодня закрывается TUN.
	// Сторона платформы обязана выдержать повторный вызов и НЕ закрывать
	// поток вторым разом сама. Это перенос инварианта Android
	// («дескриптор переходит во владение движку») на платформу, где
	// дескриптора нет.
	//
	// ОБЯЗАН РАЗБУДИТЬ ВИСЯЩИЙ ReadBatch: тот возвращается немедленно и
	// отдаёт nil. Без этого AwaitStopped не дождётся насоса tunToNet и
	// подвиснет, а движок будет считать место занятым.
	Close()
}

// flowFrameMax — потолок кадра между движком и платформой.
//
// ВНИМАНИЕ: кадр здесь выглядит ТОЧНО ТАК ЖЕ, как кадр потокового
// транспорта в streamlink.go — [2 байта длины BE][полезное]. Это РАЗНЫЕ
// СЛОИ, и перепутать их значит искать долго:
//
//	streamlink.go — то, что уходит НА ПРОВОД, и внутри кадра лежит
//	                obfsWrapPacket: RTP-подобная шапка, ChaCha20-Poly1305,
//	                набивка. Потолок tcpFrameMax = 2048;
//	flowconn.go   — то, что ходит между движком и платформой ВНУТРИ
//	                телефона. Внутри кадра голый IP-пакет из туннеля. На
//	                провод этот кадр не уходит никогда, DPI его не видит.
//
// Совпадение формы случайно и сохранено намеренно: заводить в одном
// движке два разных способа записать длину незачем.
//
// Число не новое: ровно с таким буфером tunToNet читает сегодня.
const flowFrameMax = tunMTU + 80

// flowConn — переходник между PacketFlow и io.ReadWriteCloser.
//
// ЕДИНСТВЕННОЕ новое место в движке. Насосы tunToNet и netToTun не
// знают, откуда пришли пакеты, и не меняются ни строкой — но верно это
// только благодаря переходнику, и все будущие ошибки будут здесь.
type flowConn struct {
	flow PacketFlow
	logf func(string, ...interface{})

	// Дозаправка. buf — пачка, отданная ReadBatch; off — сколько из неё
	// уже роздано. Read зовётся ОДНОЙ горутиной (tunToNet), поэтому
	// замок здесь не нужен — записано, чтобы не завели «на всякий
	// случай».
	buf []byte
	off int

	// oversize — сколько пакетов крупнее потолка отброшено за соединение.
	// Пишет только Read, то есть одна горутина, как и buf/off.
	oversize int

	// Запись зовут до slotsMax горутин разом.
	wmu  sync.Mutex
	wbuf []byte

	closed atomic.Bool
}

func newFlowConn(flow PacketFlow, logf func(string, ...interface{})) *flowConn {
	return &flowConn{flow: flow, logf: logf}
}

// Read отдаёт ОДИН пакет, как того ждёт tunToNet.
func (c *flowConn) Read(p []byte) (int, error) {
	for {
		if c.off < len(c.buf) {
			// Разбор длины — с той же строгостью, что у streamLink.
			if len(c.buf)-c.off < 2 {
				return 0, c.structural("хвост пачки короче поля длины")
			}
			n := int(c.buf[c.off])<<8 | int(c.buf[c.off+1])
			if n == 0 {
				return 0, c.structural("нулевая длина кадра")
			}
			if c.off+2+n > len(c.buf) {
				return 0, c.structural("кадр не помещается в пачку")
			}
			// КРУПНЫЙ ПАКЕТ ОТ ПЛАТФОРМЫ — НЕ ПОВОД РВАТЬ ПОТОК. Длина честная,
			// кадр целиком в пачке, разметка цела: пакет больше tunMTU+80 просто
			// не пройдёт туннелем (чужое приложение с MSS от физического
			// интерфейса; первый живой прогон Windows: 1360 байт при потолке
			// 1280). Роняем один пакет и читаем дальше: для TCP это потеря,
			// которая лечится повтором. Рвать по-прежнему надо, когда разметка
			// сама негодна (нулевая длина, кадр за пределами пачки): там мусор,
			// а не большой пакет.
			if n > flowFrameMax {
				c.off += 2 + n
				c.oversize++
				if c.logf != nil && (c.oversize == 1 || c.oversize%100 == 0) {
					c.logf("пакет от платформы %d байт больше потолка %d — отброшен (всего %d); "+
						"MTU интерфейса туннеля не должен превышать MTU движка", n, flowFrameMax, c.oversize)
				}
				continue
			}
			if n > len(p) {
				return 0, c.structural(fmt.Sprintf("кадр %d байт не влезает в буфер %d", n, len(p)))
			}
			copy(p, c.buf[c.off+2:c.off+2+n])
			c.off += 2 + n
			return n, nil
		}
		// Пачка израсходована — дозаправка.
		c.buf, c.off = nil, 0
		b := c.flow.ReadBatch()
		// len(b) == 0, а не b == nil: пустое и nil через границу
		// неразличимы, и код обязан говорить то же, что договор.
		if len(b) == 0 {
			return 0, io.EOF
		}
		c.buf = b
	}
}

// Write отдаёт платформе ровно один кадр.
func (c *flowConn) Write(p []byte) (int, error) {
	if len(p) == 0 || len(p) > flowFrameMax {
		return 0, fmt.Errorf("пакет %d байт вне 1..%d", len(p), flowFrameMax)
	}
	c.wmu.Lock()
	defer c.wmu.Unlock()
	if c.closed.Load() {
		return 0, io.ErrClosedPipe
	}
	// Один буфер на соединение: Write под замком, значит переиспользовать
	// можно. Аллокации на пакет здесь нет — в отличие от направления вверх.
	c.wbuf = append(c.wbuf[:0], byte(len(p)>>8), byte(len(p)))
	c.wbuf = append(c.wbuf, p...)
	if !c.flow.WriteBatch(c.wbuf) {
		return 0, io.ErrClosedPipe
	}
	return len(p), nil
}

// Close идемпотентен: движок зовёт его из stop(), а stop() зовут откуда
// угодно и не по одному разу.
func (c *flowConn) Close() error {
	if c.closed.Swap(true) {
		return nil
	}
	c.flow.Close()
	return nil
}

// structural — негодная пачка. Поток рвётся целиком.
//
// Склеивать хвост со следующей пачкой НЕЛЬЗЯ: если длины поехали,
// дальше пойдёт мусор, а мусор, пропущенный в туннель, — это
// испорченные пакеты вместо потерянных. Второе чинится повтором,
// первое не чинится ничем.
func (c *flowConn) structural(why string) error {
	c.buf, c.off = nil, 0
	if c.logf != nil {
		c.logf("пачка от платформы негодна: %s — поток рву", why)
	}
	return fmt.Errorf("негодная пачка: %s", why)
}
