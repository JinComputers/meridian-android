package engine

import (
	"sync/atomic"
	"time"
)

// Капча: ПОКАЗЫВАЕМ ЧЕЛОВЕКУ, не решаем сами.
//
// В апстримном клиенте капча разобрана на трёх уровнях: решение прямо
// на Go с proof-of-work и распознаванием пазла, невидимый WebView с
// эмуляцией клика, и ручной показ. Мы делаем только третий.
//
// Почему только его: капча у нас не появлялась НИ РАЗУ, а
// автоматическое решение завязано на текущий вид картинки и сломается
// при первой же смене оформления. Писать полторы тысячи строк под
// событие, которого мы не видели, — не та цена.
//
// Отсюда и счётчик ниже: сначала надо узнать, как часто она вообще
// случается, а уже потом решать, нужна ли автоматика.

// captchaTokenParam — под каким именем решённая капча уходит обратно.
//
// НЕ ПОДТВЕРЖДЕНО. В разведке имени нет, живой капчи мы не видели.
// Взято по виду ответа: раз VK отдаёт success_token, вероятнее всего
// его же и ждёт обратно.
//
// Меняется одной строкой — ради этого и вынесено. Первый живой случай
// покажет верное имя: и запрос, и ответ повтора логируются целиком.
const captchaTokenParam = "success_token"

// captchaWait — сколько ждём человека.
//
// Три минуты: экран может открыться не сразу — при подключении из
// фоновой службы человек сначала увидит уведомление и должен по нему
// нажать. Меньше — и мы бросим попытку, пока он тянется к телефону.
const captchaWait = 3 * time.Minute

// captchaSeen — сколько раз капча встретилась за время работы процесса.
//
// Глобальный, а не на сессию: капча считается на источник обращений, и
// нам интересна её частота вообще, а не в пределах одного подключения.
var captchaSeen atomic.Uint64

// CaptchaSolver — показ капчи человеку.
//
// Реализуется на стороне Kotlin: открыть WebView по redirect_uri,
// дождаться, пока человек решит, и вернуть success_token.
//
// Вызов БЛОКИРУЮЩИЙ и приходит из goroutine движка, не с главного
// потока Android. Пустая строка означает «человек не решил»: закрыл
// экран, не дождался или не захотел.
type CaptchaSolver interface {
	Solve(redirectURI string) string

	// Reason — ПОЧЕМУ Solve вернул пусто.
	//
	// Второй метод, а не расширенный ответ первого: через gomobile
	// сторона Java умеет возвращать только простые типы, и уложить в
	// одну строку и токен, и причину значило бы снова завести
	// строковую типизацию — ровно то, от чего мы здесь уходим.
	//
	// Спрашивается СРАЗУ после Solve и только когда тот вернул пусто.
	// Гонки нет: капча показывается по одной, вызовы идут подряд из
	// одной goroutine.
	//
	// Значения — закрытый список, см. константы captchaReason* ниже.
	// Незнакомое слово не ломает ничего: оно попадёт в лог как есть.
	Reason() string
}

// Причины отказа со стороны Kotlin. Закрытый список.
const (
	// Человек закрыл экран, не решив.
	captchaReasonClosed = "closed"

	// Человек не успел за отведённое время.
	captchaReasonTimeout = "timeout"

	// Другая капча уже показывается.
	captchaReasonBusy = "busy"
)

// captchaOutcome — чем кончился показ капчи.
//
// ЗАМЕНА ПУСТОЙ СТРОКЕ (задача 57.3, третий пункт). Раньше все шесть
// путей — решателя нет, адреса нет, человек закрыл, вышел срок, экран
// занят, поток прерван — возвращали одно и то же пустое значение, и
// вызывающий не отличал «человек отказался» от «показать было нечем».
//
// Поведение сегодня у всех одно: попытка неудачна, хеш не помечается.
// Разводим их не ради ветвления, а чтобы ветвление СТАЛО ВОЗМОЖНЫМ без
// переделки: например, «экран занят» разумнее повторить позже, а
// «человек закрыл» повторять незачем.
type captchaOutcome int

const (
	// Капча решена, токен получен.
	captchaSolved captchaOutcome = iota

	// Решателя нет: некому показать. Наша сборка без экрана капчи.
	captchaNoSolver

	// В ответе VK нет redirect_uri: показывать нечего.
	captchaNoURI

	// Человек закрыл экран, не решив.
	captchaClosed

	// Человек не успел.
	captchaTimedOut

	// Экран уже занят другой капчей.
	captchaBusy

	// Сторона Kotlin назвала причину, которой мы не знаем.
	captchaUnknown
)

func (o captchaOutcome) String() string {
	switch o {
	case captchaSolved:
		return "решена"
	case captchaNoSolver:
		return "показать некому"
	case captchaNoURI:
		return "нет адреса капчи"
	case captchaClosed:
		return "человек закрыл экран"
	case captchaTimedOut:
		return "человек не успел"
	case captchaBusy:
		return "экран занят другой капчей"
	}
	return "причина неизвестна"
}

// captchaRedirect достаёт redirect_uri из ответа.
//
// Ищем в нескольких местах: точного пути в разведке нет, а ответы VK
// кладут его то в корень, то внутрь error. Порядок от частного к
// общему.
func captchaRedirect(m map[string]any) string {
	for _, path := range [][]string{
		{"error", "redirect_uri"},
		{"redirect_uri"},
		{"response", "redirect_uri"},
		{"error", "captcha_img"},
	} {
		if v := digStr(m, path...); v != "" {
			return v
		}
	}
	return ""
}

// solveCaptcha показывает капчу и возвращает success_token.
//
// Пусто — не решили. Хеш при этом НЕ помечается: капча это свойство
// источника обращений, а не ссылки. Пометить ссылку мёртвой из-за
// капчи значило бы выбросить рабочий хеш за чужую осторожность.
func (c *vkChain) solveCaptcha(m map[string]any) (string, captchaOutcome) {
	n := captchaSeen.Add(1)
	c.s.logf("VK: КАПЧА, встретилась %d-й раз за работу приложения", n)

	if c.solver == nil {
		c.s.logf("VK: показать капчу некому (решатель не задан) — попытка неудачна, " +
			"хеш НЕ помечаю: капча не свойство ссылки")
		return "", captchaNoSolver
	}

	uri := captchaRedirect(m)
	if uri == "" {
		// Без адреса показать нечего. Это не тупик, а недостающее
		// знание: в разведке точного пути к redirect_uri нет, и первый
		// живой ответ покажет, где он лежит на самом деле.
		c.s.logf("VK: в ответе НЕТ redirect_uri — показать капчу не по чему. " +
			"Поля ответа ниже, по ним и найдём, где он лежит")
		c.logFields(0, m)
		return "", captchaNoURI
	}

	c.s.logf("VK: открываю капчу человеку, жду до %s", captchaWait)
	started := time.Now()
	token := c.solver.Solve(uri)
	spent := time.Since(started).Round(time.Second)

	if token == "" {
		// Причину спрашиваем ОТДЕЛЬНЫМ вызовом: см. CaptchaSolver.Reason.
		out := captchaUnknown
		switch r := c.solver.Reason(); r {
		case captchaReasonClosed:
			out = captchaClosed
		case captchaReasonTimeout:
			out = captchaTimedOut
		case captchaReasonBusy:
			out = captchaBusy
		default:
			// Незнакомое слово не хороним молча: оно попадёт в лог как
			// есть, и добавить его сюда — одна строка.
			c.s.logf("VK: капча вернула причину %q, которой я не знаю", r)
		}
		c.s.logf("VK: капча не решена за %s — %s. Попытка неудачна, хеш НЕ помечаю",
			spent, out)
		return "", out
	}
	c.s.logf("VK: капча решена за %s, повторяю запрос", spent)
	return token, captchaSolved
}

// CaptchaCount — сколько раз капча встретилась за время работы.
// Приложение показывает это число человеку.
func CaptchaCount() int32 {
	return int32(captchaSeen.Load())
}
