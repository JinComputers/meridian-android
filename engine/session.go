const (
	tunMTU            = 1200
	dtlsMTU           = 1100
	keepaliveInterval = 20 * time.Second

	// keepaliveFirst — КОГДА уходит ПЕРВАЯ метка. Не через двадцать
	// секунд, а почти сразу, и это единственный наш прибор.
	//
	// Шлюз отражает метку обратно (эхо-keepalive). Пока первая метка
	// уходила через двадцать секунд, короткая сломанная сессия — а они
	// живут пять-тринадцать секунд — не успевала отправить НИ ОДНОЙ, и
	// отличить "шлюз нас не слышит" от "шлюз слышит, но не отвечает"
	// было нечем. Теперь ответ есть на четвёртой секунде.
	//
	// Цена — один лишний пакет за сессию. Роутерный клиент шлёт метки
	// раз в двадцать секунд, и наш профиль на проводе от одной метки в
	// начале отличается несильно; дальше кадр тот же самый.
	keepaliveFirst = 3 * time.Second

	// rungProofGap — пауза между двумя метками проверки ступени.
	//
	// ДВЕ МЕТКИ, А НЕ ОДНА, И РАЗНЕСЁННЫЕ ВО ВРЕМЕНИ. Одной мало:
	// 26.08 в 10:52:08 ступень ответила на AUTH, пропустила один
	// встречный пакет и оглохла только после этого. Проверка вплотную
	// к AUTH такую ступень признала бы годной.
	//
	// Полторы секунды — это то же окно, что фора без DTLS, и оно уже
	// доказало, что успевает застать поломку: рабочая ступень отвечала
	// на метку на третьей секунде, сломанная не отвечала никогда.
	rungProofGap = 1500 * time.Millisecond

	// rungProofWait — сколько ждать ответа на КАЖДУЮ метку.
	rungProofWait = 1200 * time.Millisecond

	// muteLimit — сколько ждать ПЕРВОГО встречного пакета.
	//
	// rxSilenceLimit в полторы минуты сторожит другое: смерть живого
	// канала. Здесь случай грубее — канал не ожил ни разу. Сидеть в нём
	// полторы минуты незачем: ни одного ответа за восемь секунд при
	// уходящем трафике означает, что дороги назад нет вовсе.
	muteLimit = 8 * time.Second

	// probeAuthBudget — срок контрольного AUTH со второго сокета.
	//
	// Короче боевого (4 с) намеренно: сессия уже приговорена сторожем,
	// и растягивать её агонию ради измерения незачем. Трёх секунд
	// хватает с запасом — боевой AUTH отвечает за десятки миллисекунд.
	probeAuthBudget = 3 * time.Second

	// timingSlack — насколько операция вправе опоздать, прежде чем мы
	// об этом скажем.
	//
	// Заведено 27.08 под разбор плавающей задержки: фора в 1,5 секунды
	// заняла 6,2, а проверка метки в той же сессии — ровно свои три.
	// Постоянной добавки нет, значит что-то залипает время от времени,
	// и найти это можно только замером.
	//
	// Полсекунды: обычный разброс планировщика меряется миллисекундами,
	// а нас интересуют секунды.
	timingSlack = 500 * time.Millisecond

	// stunAnswerWait — сколько ждать ответа STUN перед остановкой.
	// Ответ приходит в насос чтения, а тот умрёт вместе с сессией:
	// без этой паузы измерение пропало бы ровно в тот миг, ради
	// которого делалось.
	stunAnswerWait = 700 * time.Millisecond

	// rawTunMTU — MTU туннеля на ступени БЕЗ DTLS.
	//
	// Точный расчёт: 1200 - (12 заголовка + 16 тега + 24 набивки) = 1148.
	// Взято 1100 — с запасом на путь, о котором мы ничего не знаем.
	// Наблюдение, из-за которого это появилось: на одном пакетном канале
	// оператора ступень 56005 давала "отправлено 534, принято 3", на
	// другом та же сборка работала. Разница — MTU канала.
	rawTunMTU = 1100

	// rxSilenceLimit — сколько молчания в туннеле считать смертью канала.
	//
	// Роутерный клиент держит 5 минут (спецификация 1.7), но там и
	// обстановка другая. У нас keepalive раз в 20 секунд, и при
	// подтверждённом echo молчание дольше 90 секунд означает мёртвый
	// канал (спецификация 1.5). Это четыре с лишним пропущенных эха
	// подряд — случайной потерей такое не объяснить.
	rxSilenceLimit = 90 * time.Second

	// suspectSilenceLimit — укороченный срок молчания, когда канал уже
	// ПОД ПОДОЗРЕНИЕМ.
	//
	// Ставится не сам по себе, а только по внешнему сигналу от Android:
	// нижняя сеть потеряла проверку связи (NET_CAPABILITY_VALIDATED).
	// Обычные 90 секунд заведены под другое — под простаивающий, но
	// исправный туннель, где молчание ничего не значит. Здесь система
	// уже сказала, что связи под нами нет, и ждать четыре пропущенных
	// эха незачем.
	//
	// Шесть секунд: эхо на живом релее возвращается за 100–130 мс
	// (замер 09.09), то есть запас пятидесятикратный. Цена ошибки
	// несимметрична и потому мала — ложный приговор стоит трёх секунд
	// переподключения, пропущенная смерть канала стоила полутора минут
	// без связи.
	suspectSilenceLimit = 6 * time.Second

	// probeRepeatGap — пауза перед ПОВТОРНОЙ внеочередной меткой.
	//
	// Метка уходит по UDP и может потеряться в одиночку. Без повтора
	// одна случайная потеря на единственном слоте означала бы приговор
	// исправному каналу. Повтор через полсекунды снимает именно этот
	// случай, оставляя весь укороченный срок в силе.
	probeRepeatGap = 500 * time.Millisecond

	// ladderBudget — общий срок на ВСЮ лестницу.
	//
	// В роутерном клиенте общего срока нет вовсе, и худший случай там
	// уходит далеко за минуту. На роутере это терпимо, там никто не
	// смотрит; на телефоне человек смотрит на кнопку.
	//
	// 25, а не 20: худший случай лестницы теперь 12+5+5=22 с. Человек
	// видит эти 25 секунд только на первом подключении в незнакомой
	// сети — дальше работает память пути, и обычный случай это одна
	// ступень за три секунды.
	ladderBudget = 25 * time.Second

	// ladderFreezeCap — на сколько САМОЕ БОЛЬШЕЕ срок лестницы продлевается
	// за время, когда нас останавливали целиком.
	//
	// 02.09 10:17:47 пульс пропал на 33,4 с посреди проверки ступени C.
	// Срок лестницы был абсолютным: очнувшись, она увидела, что 25 с
	// прошли, и НЕ ПОПРОБОВАЛА ни потоковую ступень, ни релей — вышла с
	// ошибкой при живой сети (контрольный AUTH тут же прошёл). Время, в
	// котором нас не было, ступеням не в вину, и в срок оно не идёт.
	//
	// Предел нужен: заморозка на Xiaomi бывает и минутной, а человек
	// смотрит на кнопку. Минута сверх 25 с — потолок, дальше честнее
	// сдаться и дать нажать снова.
	ladderFreezeCap = 60 * time.Second

	// Сроки ступеней — свойство МЕСТА в лестнице, а не порта.
	//
	// Первой достаётся много: при работающей памяти пути она и есть
	// рабочая ступень. Восемь секунд накрывают три ретрансмита pion
	// (1, 3, 7 с — initialTickerInterval с удвоением, conn.go:32).
	// Прежние 3 секунды обрывали нас ровно на втором повторе: шлюз
	// принимал подключение на третьей секунде, когда мы уже сдались.
	firstRungHandshake = 8 * time.Second

	// rememberedHeadStart — фора запомненной ступени в первом круге гонки
	// (шаг 1 в climb). Рабочая запомненная DTLS встаёт за ~0,35 с (лог
	// 24.09, MTS 5G); первый повтор рукопожатия у pion — на 1 с. 1,2 с
	// накрывают рукопожатие, прошедшее с первого раза, и не больше: если
	// первый пакет потерян, дальше ждать её одну незачем.
	rememberedHeadStart = 1200 * time.Millisecond
	firstRungAuth      = 4 * time.Second

	// raceHandshakeBudget — срок на ГОНКУ транспорта целиком.
	//
	// Ступени поднимаются одновременно, поэтому это не сумма их
	// сроков, а максимум: восемь секунд на всю гонку, а не по восемь
	// на каждую. Отсюда и выигрыш — незнакомая сеть больше не стоит
	// десяти секунд на заведомо мёртвых 443 и 56004.
	raceHandshakeBudget = 8 * time.Second

	// rerunHandshakeBudget — срок гонки на ВТОРОМ круге и дальше.
	//
	// Второй круг случается, когда победитель первого поднял транспорт
	// первым, но провалил метку или AUTH: его выбрасывают, а гонку дают
	// проигравшим. Полные восемь секунд им уже ни к чему.
	//
	// Замер дважды, 27.08 17:57 и 19:09: на этой сети (rmnet, MTS) A и B
	// (DTLS на 443 и 56004) во втором круге ВЫБИРАЮТ весь срок и падают
	// по "handshake error: context deadline exceeded". Восемь секунд
	// ожидания того, что не встаёт, — и подъём растянулся до 15 и 19
	// секунд вместо ухода на релей за четыре.
	//
	// Три секунды — не наугад: рукопожатие DTLS, которое проходит,
	// проходит за первый-второй ретрансмит pion (1 и 3 секунды,
	// удвоение). Не встало за три — не встанет и за восемь. Цена
	// промаха на медленной сети — уход на релей на секунду-другую
	// раньше, чем мог бы подняться честный, но очень медленный DTLS;
	// релей поднимется всё равно.
	rerunHandshakeBudget = 3 * time.Second

	// streamHandshakeBudget — срок подъёма потоковой ступени: TCP-дозвон
	// и, для TLS, рукопожатие. TCP connect быстрый, TLS — один-два RTT;
	// восьми секунд с запасом, тот же порядок, что у гонки.
	streamHandshakeBudget = 8 * time.Second

	// relayHandshakeBudget — срок рукопожатия DTLS на релейном плече.
	//
	// Больше прямого: пакет идёт через третью сторону, и лишний крюк
	// стоит времени. Роутерный клиент даёт релею 50 секунд
	// (спецификация-2, C.2), но там нет общего срока на лестницу.
	relayHandshakeBudget = 10 * time.Second

	// minCandidateBudget — меньше этого остатка новую ступень не
	// начинаем: успеть всё равно нельзя, а строку в лог напишем ложную.
	minCandidateBudget = 1500 * time.Millisecond

	// pumpDrainLimit — сколько ждать завершения насосов при остановке.
	//
	// В норме они выходят мгновенно: закрытый сокет и закрытый TUN
	// поднимают ошибку на первом же чтении. Срок нужен на случай, когда
	// дескриптор TUN не попал в поллер Go и закрытие не разбудило
	// чтение, — иначе место сессии не освободилось бы никогда.
	pumpDrainLimit = 3 * time.Second

	// deadlineSlack — запас, на который дедлайн сокета переживает
	// собственный срок операции. Нужен, чтобы в норме первым срабатывал
	// контекст (у него внятный текст ошибки), а дедлайн сокета оставался
	// вторым, независимым предохранителем.
	deadlineSlack = 2 * time.Second
)

// keepaliveMarker — четыре нулевых байта. Специально невалиден как
// IPv4-заголовок, чтобы шлюз надёжно отличал его от настоящего пакета.
var keepaliveMarker = []byte{0, 0, 0, 0}

// errFatalAuth — шлюз отверг пароль.
//
// ТЕКСТ ПРИСЛАН КОТОМ 1 И ПЕРЕНЕСЁН ДОСЛОВНО. Он же уточнил, что
// raw-gateway сегодня сверяет ТОЛЬКО пароль и device_id не проверяет
// вовсе — поэтому прежняя формулировка «отклонил пароль/device_id»
// была неточна дважды: и про пул адресов, и про устройство.
var errFatalAuth = errors.New("FATAL_AUTH: пароль неверный или истёк")

// errPoolFull — на шлюзе кончились адреса.
//
// Отдельная причина, а не оттенок предыдущей. Раньше шлюз слал
// FATAL_AUTH в обоих случаях, и человек с рабочим ключом читал «дело в
// ключе» и шёл в поддержку — хотя мест на шлюзе просто не было. Кот 1
// разделил ответы на своей стороне; текст перенесён дословно.
var errPoolFull = errors.New(
	"FATAL_POOL_FULL: на шлюзе сейчас нет свободных адресов — " +
		"пароль ни при чём, повторите позже")

// errDeactivated — ключ отключён на стороне службы.
//
// ТЕКСТ ПРИСЛАН КОТОМ 1 И ПЕРЕНЕСЁН ДОСЛОВНО.
//
// Третья причина, а не оттенок FATAL_AUTH. До правки кота 1 шлюз не
// смотрел на is_deactivated вовсе, и отключённый ключ пускало как
// обычный — пробный период был фактически бессрочным.
//
// Хвост "не про ваш ввод" важен: человек, набравший ключ руками,
// иначе решит, что опечатался, и будет вводить снова.
var errDeactivated = errors.New(
	"FATAL_DEACTIVATED: ключ отключён " +
		"(пробный период закончился или подписка неактивна) — не про ваш ввод")

// authRefusals — известные причины отказа шлюза.
//
// ДОБАВИТЬ ПРИЧИНУ — ДОПИСАТЬ СЮДА ОДНУ СТРОКУ. Ни разбор ниже, ни
// места обрыва лестницы при этом не меняются: fatalForLadder() ходит по
// этой же таблице.
//
// Маркеры сравниваются по вхождению, а не по равенству: шлюз может
// добавить к строке подробности, и привязка к точной форме ответа
// сломалась бы от первой же его правки.
var authRefusals = []struct {
	marker string
	err    error
}{
	{"FATAL_POOL_FULL", errPoolFull},
	{"FATAL_DEACTIVATED", errDeactivated},
}

// classifyAuthRefusal — какая из известных причин пришла.
//
// Ни одна не подошла — общий отказ по паролю: это исходное значение
// FATAL_AUTH, каким шлюз слал его всегда.
func classifyAuthRefusal(resp string) error {
	for _, r := range authRefusals {
		if strings.Contains(resp, r.marker) {
			return r.err
		}
	}
	return errFatalAuth
}

// fatalForLadder — отказ, который бессмысленно повторять на других
// ступенях.
//
// Все отказы шлюза таковы по своей природе: ступени ведут к ОДНОМУ
// шлюзу, и неверный пароль останется неверным, а свободный адрес не
// появится от смены порта (спецификация-2, C.2).
//
// Поэтому проверка ходит по той же таблице, а не перечисляет ошибки
// заново. Новая причина начинает обрывать лестницу сама, без правок
// здесь, — иначе список причин и список обрывающих ошибок разошлись бы
// при первом же добавлении.
func fatalForLadder(err error) bool {
	if errors.Is(err, errFatalAuth) {
		return true
	}
	for _, r := range authRefusals {
		if errors.Is(err, r.err) {
			return true
		}
	}
	return false
}

// errDirectSimulatedBlock — прямой путь провален нарочно, режим отладки.
var errDirectSimulatedBlock = errors.New("прямой путь закрыт искусственно (режим отладки)")

// errSessionStopped — сессию остановили, пока ступень поднималась.
var errSessionStopped = errors.New("сессия остановлена во время подъёма ступени")

// errNetworkGone — сеть сменилась под ногами.
//
// Это НЕ отказ ступени, и обходить по ней лестницу дальше бессмысленно:
// все ступени идут через один и тот же маршрут по умолчанию, и если он
// исчез, следующая упрётся ровно в то же самое. Правильный исход —
// прекратить попытку целиком и начать заново уже на новой сети.
var errNetworkGone = errors.New("сеть сменилась во время подъёма")

type session struct {
	mu sync.Mutex

	// slots — все слоты сессии. Снимок неизменяемый: добавление слота
	// заменяет срез целиком, поэтому читателю на горячем пути не нужен
	// ни один замок.
	//
	// Слот номер ноль — основной, он же единственный при slots == 1.
	slots  atomic.Pointer[[]*rung]
	slotRR atomic.Uint64

	// sessionGen — поколение сессии, 16 hex-символов. Одно на всю
	// сессию, уходит в caps КАЖДОГО слота, включая первый.
	sessionGen string

	// credsBatch — номер пачки, для которой уже взят комплект кредов.
	// credsTaken — сколько комплектов взято за сессию, то есть износ
	// ссылки. Две пачки вместо одной удваивают расход.
	credsBatch int
	credsTaken int

	// vk — кэш комплектов и разметка хешей на эту сессию.
	//
	// Устройства для VK здесь НЕТ намеренно. Цепочка генерирует себе
	// два своих uuid4 сама (vkcreds.go, newVKChain), и ANDROID_ID
	// телефона в VK не уходит вовсе. Раньше тут лежало поле vkDeviceID,
	// которому присваивался ANDROID_ID и которое не читал никто, — и
	// выглядело это ровно наоборот.
	vk *vkCache

	// wantSlots — сколько слотов просили. Реально поднятых может быть
	// меньше: первая же неудача обрывает цикл открытия.
	wantSlots int

	// simVKTimeout — отладка, см. Ladder.SimulateVKTimeout.
	simVKTimeout bool

	// dialer — чем поднимать дополнительные слоты. Заполняется, только
	// если победила релейная ступень и слотов просили больше одного.
	dialer *slotDialer

	// tun — туннель. НЕ *os.File намеренно: на iOS дескриптора нет
	// вовсе, и туда подставляется flowConn (см. flowconn.go). Насосы
	// работают с обоими одинаково — им нужны только Read/Write/Close.
	tun io.ReadWriteCloser

	ctx    context.Context
	cancel context.CancelFunc

	log      Logger
	stopped  bool
	echoConf bool

	// winner — имя ступени, которой сессия поднялась. Приложение
	// запоминает его, чтобы в следующий раз начать с неё.
	winner string

	// Улики для причины отказа (failure.go). reached — хоть одна прямая
	// ступень прошла рукопожатие, которое подделать нельзя (DTLS или
	// пиновленный TLS): сервер из этой сети виден. hadRelay/relayErr — был
	// ли релей в лестнице и чем кончился.
	reached  atomic.Bool
	hadRelay bool
	relayErr error

	// mtu — MTU выигравшей ступени. Приложение спрашивает его ПОСЛЕ
	// Connect и уже с ним строит VpnService.Builder.
	mtu int32

	// obfs — упаковщик выигравшей ступени. Держим ради счётчика
	// максимального размера на проводе.
	obfs *obfsPacketConn

	// onStop вызывается в конце stop(), уже после закрытия всех ресурсов
	// сессии. Engine использует его, чтобы обнулить current при внутренней
	// остановке (обрыв, ошибка чтения) — без этого current не сбрасывается
	// и повторный Connect упирается в "сессия уже поднята".
	onStop func()

	// listener — извещение приложения о погасшей сессии. Назначается
	// только для успешно поднятой сессии, см. Connect.
	listener StateListener

	// guard — проверка, что сеть под нами не сменилась.
	guard NetworkGuard

	// captcha — показ капчи человеку. nil — показать некому.
	captcha CaptchaSolver

	// Счётчики атомарные: насосов чтения теперь по одному на слот,
	// то есть пишут в них несколько горутин сразу.
	txCount atomic.Uint64
	rxCount atomic.Uint64

	// v6Dropped — пакеты IPv6, отброшенные на входе из TUN.
	//
	// Kotlin забирает маршрут ::/0 в туннель, чтобы v6 не шёл мимо него
	// открытым каналом. Нести его нам некуда: шлюз v6 не поддерживает
	// вовсе (замер кота 2 от 04.09). Поэтому пакет гасим ЗДЕСЬ, а не
	// отправляем на тот конец: на проводе он был бы чистой тратой, а
	// шлюз всё равно его выбросит.
	//
	// Счётчик не украшение: по нему видно, что маршрут перехвачен и
	// работает. Ноль на сети с живым v6 означает, что addRoute("::", 0)
	// не применился и утечка жива.
	v6Dropped atomic.Uint64

	// echoArmed — наша метка после подъёма УЖЕ УШЛА.
	//
	// До этого мгновения короткий встречный пакет ничего не доказывает:
	// он мог остаться в буфере от проверки ступени. См. netToTun.
	echoArmed atomic.Bool

	// echoEarly — короткие пакеты, пришедшие ДО первой метки.
	//
	// Отдельно от echoCount и только для разбора: именно они объясняют,
	// почему эхо стало возвращаться за десятки миллисекунд вместо трёх
	// секунд. На вопрос "слышит ли нас шлюз сейчас" они не отвечают.
	echoEarly atomic.Uint64

	// echoCount — сколько меток keepalive шлюз отразил обратно.
	// Считается ОТДЕЛЬНО от rxCount: это не полезный трафик, а признак
	// того, что шлюз нас слышит и отвечает.
	echoCount atomic.Uint64

	// upAt — когда встали насосы. От него отсчитываются прибор и сторож.
	upAt time.Time

	// frozeAt — когда в последний раз нас останавливали целиком.
	//
	// Ставит пульс. Нужен, чтобы НЕ СУДИТЬ СТУПЕНЬ ПО ОКНУ, В КОТОРОМ
	// НАС НЕ БЫЛО: срок чтения задан абсолютным временем, и если
	// процесс замер до срока и очнулся после, чтение вернёт "истёк" —
	// даже когда ответ уже лежит в буфере сокета.
	frozeAt atomic.Int64

	// frozenNs — сколько всего наносекунд нас останавливали целиком.
	//
	// Копит пульс. Лестница вычитает это из потраченного: срок у неё
	// на подъём, а не на то, чтобы лежать замороженной. См.
	// ladderFreezeCap.
	frozenNs atomic.Int64

	// slowLogs, slowLogMax — сколько записей в лог заняли дольше
	// timingSlack и какая была самой долгой.
	//
	// Копим, а не пишем сразу: строка о медленной строке пошла бы через
	// тот же путь и удвоила бы беду. Показываем один раз, в итоге.
	slowLogs   atomic.Uint64
	slowLogMax atomic.Int64

	// probeStun — адрес STUN для отладочной проверки отображения NAT.
	// Пусто — проверки нет, см. Ladder.SetProbeStun.
	probeStun string

	// Всё, что нужно контрольному AUTH в момент немоты. Сессия эти
	// значения получает параметрами climb и сама не хранила — а
	// сторож срабатывает много позже, когда параметров уже нет.
	//
	// ПАРОЛЬ ЗДЕСЬ ЛЕЖИТ, И В ЛОГ ОН НЕ ПОПАДАЕТ НИКОГДА. Он и так
	// живёт в памяти процесса всю сессию, внутри obfsState; отдельного
	// риска это поле не добавляет, а вот написать его в лог нельзя ни
	// при каких обстоятельствах.
	deepProbe bool

	// secondRound — срок гонки на втором круге. Ноль до копирования из
	// ladder; в climb ноль читается как зашитое rerunHandshakeBudget.
	secondRound time.Duration

	gateway  string
	password string
	deviceID string
	prot     Protector
	winCand  candidate

	// stunSeen — отражённый адрес, увиденный при подъёме. С ним
	// сравнивается тот, что придёт в момент немоты.
	stunSeen atomic.Value // string
	txBytes  atomic.Uint64
	rxBytes  atomic.Uint64

	// slotsMax — верхний предел автоподбора. slotsAuto — включён ли он.
	slotsMax  int
	slotsAuto bool

	// wg — три насоса перекачки. Пока хоть один жив, сессия не считается
	// остановленной: закрытый сокет ещё не значит завершённую горутину.
	wg sync.WaitGroup

	// done закрывается, когда сессия остановлена ПОЛНОСТЬЮ: ресурсы
	// закрыты, насосы вышли, current обнулён. Ровно этого и ждёт
	// AwaitStopped, прежде чем пускать новую сессию.
	done chan struct{}
}

func newSession(log Logger) *session {
	return &session{log: log, done: make(chan struct{}), vk: newVKCache()}
}

// Приём ресурсов поднявшейся ступени в собственность сессии — в
// adoptFirst (slots.go). Возвращает false, если сессию успели
// остановить, пока ступень поднималась. Это не теория: Stop() во время
// прохода лестницы отменяет s.ctx и закрывает слоты, а первого слота в
// этот момент ещё нет — он живёт в локальной переменной. Без этой
// проверки такая ступень доходила бы до конца, проходила AUTH,
// поднимала сессию на шлюзе и оставалась навсегда.

// networkChanged — сменилась ли сеть с начала попытки.
//
// Без guard всегда false: проверять нечем, и лучше попробовать, чем
// отказаться без причины.
func (s *session) networkChanged() bool {
	if s.guard == nil {
		return false
	}
	return !s.guard.SameNetwork()
}

// logf пишет строку в лог приложения ЧЕРЕЗ JNI.
//
// ЗАМЕР ЗДЕСЬ НЕ УКРАШЕНИЕ. 27.08 обычный сон в Go на полторы секунды
// занял 4,4 — при том что эхо в той же сессии возвращалось за 80 мс.
// То есть время теряет не сеть, а среда исполнения движка, и первый
// подозреваемый — вот этот вызов: он уходит из Go в Kotlin, и если там
// путь записи окажется медленным, блокируются потоки Go целиком, а с
// ними и таймеры.
//
// СЮДА НЕЛЬЗЯ ПИСАТЬ О НАЙДЕННОМ СРАЗУ: строка о медленной строке
// пошла бы через тот же logf и удвоила бы беду. Поэтому копим числа и
// показываем их один раз, в строке итога.
func (s *session) logf(format string, args ...interface{}) {
	if s.log == nil {
		return
	}
	line := fmt.Sprintf(format, args...)
	at := time.Now()
	s.log.Log(line)
	took := time.Since(at)
	if took > timingSlack {
		s.slowLogs.Add(1)
		for {
			was := s.slowLogMax.Load()
			if int64(took) <= was || s.slowLogMax.CompareAndSwap(was, int64(took)) {
				break
			}
		}
	}
}

// climb поднимает сессию по лестнице.
//
// Порядок такой:
//
//  1. Если для этой сети ЗАПОМНЕНА ступень — идём прямо к ней, без
//     гонки. Память пути остаётся главным механизмом: в знакомой сети
//     обычный случай это одна ступень за пару секунд.
//  2. Иначе прямые ступени поднимают транспорт ОДНОВРЕМЕННО, и AUTH
//     отправляет только победитель. Так незнакомая сеть перестала
//     стоить десяти секунд на заведомо мёртвых 443 и 56004.
//  3. Релейные ступени — по очереди, в конце.
//
// Параллельная ПРОБА невозможна и больше не рассматривается: QWDTT-PROBE
// отвечает только на 443, на 56005 её роняет AcceptFilter, на 56004
// соединение молча висит. Проверено котом 1 по коду шлюза.
//
// Параллельный ПОДЪЁМ возможен потому, что слот по паролю занимает
// AUTH, а не рукопожатие: путь к register() и assignClientIP() на шлюзе
// открывается только после завершённого AUTH.
func (s *session) climb(gateway string, ladder *Ladder, password, deviceID string, prot Protector) (string, error) {
	s.ctx, s.cancel = context.WithCancel(context.Background())

	// Устройство для запросов VK — одно на сессию, берём то же, что
	// уходит в AUTH: заводить второй идентификатор незачем.

	s.probeStun = ladder.probeStun
	s.deepProbe = ladder.deepProbe
	// Срок второго круга из настройки сервера. Ноль (не задано) — оставим
	// зашитое умолчание там, где его читаем.
	if ladder.secondRoundMs > 0 {
		s.secondRound = time.Duration(ladder.secondRoundMs) * time.Millisecond
	}
	s.gateway = gateway
	s.password = password
	s.deviceID = deviceID
	s.prot = prot
	s.simVKTimeout = ladder.simVKTimeout
	s.wantSlots = ladder.slots
	if s.wantSlots < 1 {
		s.wantSlots = 1
	}
	s.slotsMax = ladder.slotsMax
	if s.slotsMax < s.wantSlots {
		s.slotsMax = s.wantSlots
	}
	s.slotsAuto = ladder.slotsAuto
	if s.wantSlots > 1 {
		// Поколение — ОДНО на всю сессию, и родиться оно обязано до
		// первого AUTH: в caps каждого слота, включая первый, уходит
		// один и тот же токен (спецификация 3.2).
		gen, err := newSessionGeneration()
		if err != nil {
			return "", fmt.Errorf("поколение сессии: %w", err)
		}
		s.sessionGen = gen

		// ГОВОРИМ РОВНО ТО, ЧТО ДЕЛАЕМ.
		//
		// Прежняя строка звучала "многослот: просим 4 слотов" и
		// печаталась всегда, при любой ступени. А просим мы их только на
		// релейной: на прямом пути многослот неприменим, наращивать
		// нечего, и AUTH прямой ступени не несёт ни multi, ни gen (см.
		// Ladder.SetSlots, спецификация-2 C.5).
		//
		// Цена этой неточности оказалась не нулевой. 27.08 кот 1 замерил
		// у себя "многослот=false поколение=нет" на всех наших прямых
		// AUTH и справедливо указал на расхождение с нашим логом. Круг
		// разбора ушёл на то, чего в коде никогда и не было.
		s.logf("многослот: наготове %d слотов, поколение %s "+
			"(просим только на релейной ступени; прямые идут одним слотом)",
			s.wantSlots, gen)
	}

	// Пульс живёт ровно столько, сколько идёт подъём: он отвечает на
	// вопрос про задержки в лестнице, и держать его дольше незачем.
	hbCtx, hbStop := context.WithCancel(s.ctx)
	defer hbStop()
	go s.heartbeat(hbCtx)

	// Срок лестницы — БЕЗ времени, в котором нас не было.
	//
	// Считаем не по абсолютному моменту, а по потраченному минус
	// заморозка: замер процесса на полминуты (02.09, Xiaomi) иначе
	// съедает срок целиком, и до потоков с релеем лестница не доходит.
	// Продление ограничено ladderFreezeCap, о нём пишем один раз.
	climbStart := time.Now()
	frozenAtStart := s.frozenNs.Load()
	frozenNoted := false
	ladderLeft := func() time.Duration {
		frozen := time.Duration(s.frozenNs.Load() - frozenAtStart)
		if frozen > ladderFreezeCap {
			frozen = ladderFreezeCap
		}
		if frozen > 0 && !frozenNoted {
			frozenNoted = true
			s.logf("лестница: %s заморозки в срок не считаю — срок продлён на столько же",
				frozen.Round(time.Millisecond))
		}
		return ladderBudget + frozen - time.Since(climbStart)
	}
	var directs, streams, relays []candidate
	for _, c := range ladder.items {
		switch {
		case c.isRelay:
			relays = append(relays, c)
		case c.transport == transTCP || c.transport == transTLS:
			// ПОТОКОВЫЕ СТУПЕНИ (TCP/TLS) — ОТДЕЛЬНО ОТ UDP. В гонку их
			// не берём (слово кота 2: несколько TCP не лечат head-of-line,
			// а размножают его и конкурируют за одну полосу). Пробуем по
			// очереди после UDP и до релея, как запасной прямой путь.
			streams = append(streams, c)
		default:
			directs = append(directs, c)
		}
	}

	var lastErr error

	// Молчание шлюза запоминается ОТДЕЛЬНО и в итоге перебивает
	// остальное. Иначе наверх уезжает ошибка последней ступени — а
	// последняя у нас релейная, и в релизной сборке она падает на
	// отсутствии засева хешей VK. Человек шесть раз подряд получал
	// "подключиться не удалось" вместо "сервер не ответил", хотя
	// движок знал правду с первой попытки.
	var silent error
	note := func(err error) {
		if silent == nil && errors.Is(err, errAuthSilent) {
			silent = err
		}
	}

	// 1. Запомненная ступень — ФОРОЙ В ГОНКЕ, а не в одиночку.
	//
	// Было: запомненная шла одна, со сроком рукопожатия 8 с, и только после
	// её провала начиналась гонка. Лог владельца 24.09 20:33:42 (MTS 5G):
	// D, запомненная, на рукопожатие DTLS не получила ответа все 8 с, после
	// чего гонка за 1,5 с подняла F — подключение 11 с вместо ~4. Прошлое
	// подключение, 14 с, судя по второму кругу гонки, было таким же.
	//
	// Стало: запомненная стартует первой, остальные — через
	// rememberedHeadStart. Рабочая запомненная к этому мигу уже готова (D
	// в той же сети — за 355 мс), и гонка завершается без чужих сокетов.
	// Молчащая не держит лестницу: остальные идут следом, а она
	// продолжает своё рукопожатие наравне с ними. Откажет раньше срока —
	// остальные стартуют сразу. Фору без DTLS запомненная не отдаёт:
	// выбор уже сделан памятью пути.
	if len(directs) > 0 && directs[0].remembered {
		s.logf("ступень %s запомнена для этой сети — иду к ней первой, остальные через %s",
			directs[0].name, rememberedHeadStart)
		for i := 1; i < len(directs); i++ {
			directs[i].delay = rememberedHeadStart
		}
	}

	// 2. Гонка среди оставшихся прямых ступеней.
	//
	// ЦИКЛ, А НЕ ОДИН ЗАХОД. Победитель гонки — это ступень, у которой
	// раньше всех встал транспорт; годной она себя ещё не показала. Если
	// AUTH или проверка меткой у неё провалятся, проигравшие гонку
	// ступени остаются непробованными — а лестница обязана дойти до них
	// прежде, чем уходить на релей.
	//
	// Замер 27.08, 17:36:47. C проваливается дважды подряд: сперва как
	// запомненная, потом как победитель гонки. A и B при этом успели
	// прожить 7 миллисекунд и погасли по отмене — их никто не пробовал.
	// Лестница ушла на релей: подъём 8 секунд, чужие креды VK, четыре
	// TURN-аллокации и трафик через посредника — вместо того, чтобы
	// потратить ещё пару секунд на две прямые ступени.
	//
	// Раньше это пряталось за форой: C отдавала 1,5 секунды, и A с B
	// хотя бы пытались завершить рукопожатие. Фору с уже пробованной C я
	// снял (candidate.spent) — и дыра проступила. Она была и до этого,
	// просто реже.
	//
	// ПОТОКИ СТАРТУЮТ, НЕ ДОЖИДАЯСЬ КОНЦА ГОНКИ UDP (решение владельца
	// 24.09). Раньше потоковая гонка начиналась только после того, как UDP
	// выбрал весь свой срок (до 8 с), и на сети, режущей UDP, эти секунды
	// уходили впустую. Теперь через streamEarlyStart после начала гонки UDP
	// потоки поднимают транспорт параллельно; результат ждёт своей очереди
	// в шаге 3. AUTH по-прежнему один и по очереди: race поднимает только
	// транспорт, и живой поток без AUTH слота на шлюзе не занимает (разбор
	// в шаге 3). UDP успел — поток гасится, не дойдя до AUTH.
	early := s.startEarlyStreams(gateway, streams, directs, password, prot,
		ladder.failDirect, ladderLeft)
	defer early.discard()

	// tryEarly — забрать уже поднятый поток и провести его AUTH. done —
	// лестница на этом кончена (успехом, отказом шлюза или уходом сети);
	// иначе поток выбыл, и круг UDP продолжается как ни в чём не бывало:
	// оставшиеся UDP-ступени не теряются.
	tryEarly := func() (addr string, done bool, err error) {
		if !early.ready() {
			return "", false, nil
		}
		sr, serr := early.take()
		if serr != nil {
			return "", false, nil
		}
		s.logf("поток %s уже поднят — пробую его раньше нового круга UDP", sr.cand.name)
		saddr, saerr := s.authRung(sr, password, deviceID,
			minDuration(firstRungAuth, ladderLeft()))
		if saerr == nil {
			s.winner = sr.cand.name
			s.winCand = sr.cand
			return saddr, true, nil
		}
		if fatalForLadder(saerr) {
			return "", true, saerr
		}
		if isNetworkGone(saerr) || errors.Is(saerr, errNetworkGone) {
			s.logf("сеть сменилась во время потоковой ступени — прекращаю попытку целиком")
			return "", true, errNetworkGone
		}
		s.logf("потоковая ступень %s: AUTH не прошёл: %v", sr.cand.name, saerr)
		lastErr = saerr
		note(saerr)
		streams = dropCandidate(streams, sr.cand.name)
		return "", false, nil
	}

	raceRound := 0
	for len(directs) > 0 {
		raceRound++
		left := ladderLeft()
		if left < minCandidateBudget {
			s.logf("лестница: общий срок %s исчерпан до гонки", ladderBudget)
			break
		}
		{
			// Первый круг — полный срок; второй и дальше — короткий.
			// Короткий берём из настройки сервера, если задана; иначе
			// зашитое rerunHandshakeBudget. См. ladder.second_round_ms.
			roundBudget := raceHandshakeBudget
			if raceRound > 1 {
				roundBudget = rerunHandshakeBudget
				if s.secondRound > 0 {
					roundBudget = s.secondRound
				}
			}
			hsBudget := minDuration(roundBudget, left-firstRungAuth)
			if hsBudget < minCandidateBudget {
				hsBudget = minCandidateBudget
			}
			// ГОТОВЫЙ ПОТОК ПРЕРЫВАЕТ КРУГ UDP, в котором победителя ещё нет.
			// Лог 24.09 20:46:10: G встал за 0,1 с, а круг UDP ещё 1,5 с
			// держал фору без DTLS ради ступеней, которые на этой сети не
			// отвечают, потом F прошла AUTH и оглохла — G взяли только в
			// :13. Следим, только пока поток не забран: забранный больше
			// не прервёт ни один круг.
			raceCtx, stopRace := context.WithCancel(s.ctx)
			if early.started() {
				go func() {
					select {
					case <-early.readyC():
						stopRace()
					case <-raceCtx.Done():
					}
				}()
			}
			won, err := s.race(raceCtx, gateway, directs, password, prot, ladder.failDirect, hsBudget)
			preempted := err != nil && s.ctx.Err() == nil && early.ready()
			stopRace()
			// Фора запомненной — только в первом круге. Дальше она
			// пробованная (spent): ни форы, ни облегчённой проверки.
			for i := range directs {
				directs[i].delay = 0
				if directs[i].remembered {
					directs[i].spent = true
				}
			}
			if preempted {
				s.logf("поток поднялся раньше UDP — круг UDP прерван")
				if addr, done, ferr := tryEarly(); done {
					return addr, ferr
				}
				// Поток не довёз — круг UDP заново, ступени те же.
				continue
			}
			if err != nil {
				// Уход сети — не отказ ступеней. Все они идут через один
				// маршрут по умолчанию, и если он исчез, дальше по
				// лестнице упрёмся ровно в то же самое.
				if isNetworkGone(err) || errors.Is(err, errNetworkGone) {
					s.logf("сеть сменилась во время гонки — прекращаю попытку целиком")
					return "", errNetworkGone
				}
				s.logf("гонка транспорта не дала победителя: %v", err)
				lastErr = err
				note(err)

				// Второго круга тут не будет: победителя нет — значит
				// транспорт не встал НИ У ОДНОЙ оставшейся ступени.
				// Гонять их заново нечем и незачем.
				break
			} else {
				// AUTH — только здесь и только один: к этому моменту
				// race уже дождался гибели всех проигравших.
				//
				// Пока идут AUTH и метки победителя, потоки заранее не
				// стартуют: транспорт UDP уже есть, скорее всего он и
				// станет туннелем.
				//
				// Только за запомненную в её первом заходе: за неё говорит
				// память пути. Случайный победитель гонки такого доверия не
				// заслужил — лог 24.09 20:40: C прошла AUTH и оглохла на
				// метке, а потоки, придержанные ради неё, встали позже.
				if won.cand.remembered && !won.cand.spent {
					early.hold()
				}
				addr, aerr := s.authRung(won, password, deviceID,
					minDuration(firstRungAuth, ladderLeft()))
				if aerr != nil {
					// UDP-победитель не довёз — потоки сразу, без срока.
					early.now()
				}
				if aerr == nil {
					s.winner = won.cand.name
					s.winCand = won.cand
					return addr, nil
				}
				if fatalForLadder(aerr) {
					return "", aerr
				}
				if isNetworkGone(aerr) || errors.Is(aerr, errNetworkGone) {
					s.logf("сеть сменилась перед AUTH — прекращаю попытку целиком")
					return "", errNetworkGone
				}
				s.logf("ступень %s: AUTH не прошёл: %v", won.cand.name, aerr)
				lastErr = aerr
				note(aerr)

				// Победитель отпал — отдаём круг проигравшим.
				before := len(directs)
				directs = dropCandidate(directs, won.cand.name)
				if len(directs) == before {
					// Победителя нет в списке. Такого быть не должно:
					// гонка выбирает из него же. Но молча крутиться
					// вечно — хуже любой ошибки, см. правило про ветку
					// ошибки без предела.
					s.logf("лестница: победитель %s не найден в списке — "+
						"второй круг не делаю", won.cand.name)
					break
				}

				// ГОТОВЫЙ ПОТОК — ВПЕРЁД НОВОГО КРУГА UDP. Поток уже поднят
				// и ждёт; новый круг UDP — это ещё до трёх секунд
				// рукопожатий на сети, где UDP только что не довёз. Лог
				// 24.09 20:40:34: G был готов с :32, а лестница потратила
				// ещё круг на A, B, D, E и взяла G только в :37.
				// Поток не довёз — возвращаемся к кругу UDP как ни в чём не
				// бывало: оставшиеся UDP-ступени не теряются.
				if addr, done, ferr := tryEarly(); done {
					return addr, ferr
				}

				if len(directs) > 0 {
					names := make([]string, 0, len(directs))
					for _, c := range directs {
						names = append(names, c.name)
					}
					s.logf("остались непробованные прямые ступени: %s — "+
						"даю им круг, релей только когда откажут все",
						strings.Join(names, ", "))
				}
			}
		}
	}

	// 3. Потоковые ступени (TCP/TLS) — ГОНКОЙ, как и прямые. Для сетей,
	// режущих UDP.
	//
	// БЫЛО ПОСЛЕДОВАТЕЛЬНО, И ЭТО СТОИЛО ДО ВОСЬМИ СЕКУНД НА ПУСТОМ
	// МЕСТЕ. Дозвон до закрытого порта не отвечает ничем — ждём полный
	// срок, потом ровно столько же ждём вторую ступень. На сети, где
	// TCP режут молча, две ступени съедали шестнадцать секунд, и только
	// потом начинался релей.
	//
	// Гонка НИ ОДНОГО ОКНА ОБНАРУЖЕНИЯ НЕ СОКРАЩАЕТ: каждая ступень
	// по-прежнему получает свой полный срок на дозвон, просто сроки
	// текут одновременно. Меняются часы на стене, а не строгость.
	//
	// ПОЧЕМУ ЭТО БЕЗОПАСНО, хотя в race.go записано, что живой сокет
	// проигравшего, дойдя до AUTH, займёт слот по хешу пароля и выбьет
	// победителя. Гонка соревнует ТОЛЬКО ГОТОВНОСТЬ ТРАНСПОРТА и AUTH
	// не шлёт вовсе — его отправляет authRung ниже, уже одному
	// победителю, после того как проигравшие погашены. То есть опасность
	// закрыта не осторожностью, а устройством: отправить AUTH
	// проигравшему здесь физически некому.
	//
	// Фора без DTLS в чисто потоковой гонке не включается: у потоков
	// useDTLS = false у всех, hasDTLS выходит false, и ветка форы не
	// исполняется ни разу.
	//
	// ГОДНОСТЬ — ПО ПРИНЯТЫМ ВНИЗ БАЙТАМ, а не по поднявшемуся
	// соединению: TCP connect удаётся всегда, если порт открыт. У нас
	// это ловит authRung+proveRung: поток, поднявший connect, но не
	// получивший ответ на AUTH и эхо на метку, падает на "шлюз не
	// ответил"/"не несёт трафик" и не запоминается — прилипнуть к
	// немому TCP нельзя. Гонка этого не трогает.
	streamRound := 0
	for len(streams) > 0 {
		streamRound++
		left := ladderLeft()
		if left < minCandidateBudget {
			s.logf("лестница: общий срок исчерпан, потоковые ступени не пробовались")
			break
		}
		hsBudget := minDuration(streamHandshakeBudget, left-firstRungAuth)
		if hsBudget < minCandidateBudget {
			hsBudget = minCandidateBudget
		}
		names := make([]string, 0, len(streams))
		for _, c := range streams {
			names = append(names, c.name+"/"+streamKindText(c.transport))
		}
		var won *rung
		var err error
		if streamRound == 1 && early.started() {
			// Первый круг уже идёт с середины гонки UDP — ждём его итога.
			s.logf("потоковые ступени, круг 1: гонка запущена заранее, жду итога")
			won, err = early.take()
		} else {
			s.logf("потоковые ступени наперегонки, круг %d: %s",
				streamRound, strings.Join(names, ", "))
			won, err = s.race(s.ctx, gateway, streams, password, prot, ladder.failDirect, hsBudget)
		}
		if err != nil {
			if isNetworkGone(err) || errors.Is(err, errNetworkGone) {
				s.logf("сеть сменилась во время потоковой гонки — прекращаю попытку целиком")
				return "", errNetworkGone
			}
			s.logf("потоковая гонка не дала победителя: %v", err)
			lastErr = err
			note(err)
			break
		}

		addr, aerr := s.authRung(won, password, deviceID,
			minDuration(firstRungAuth, ladderLeft()))
		if aerr == nil {
			s.winner = won.cand.name
			s.winCand = won.cand
			return addr, nil
		}
		if fatalForLadder(aerr) {
			return "", aerr
		}
		if isNetworkGone(aerr) || errors.Is(aerr, errNetworkGone) {
			s.logf("сеть сменилась во время потоковой ступени — прекращаю попытку целиком")
			return "", errNetworkGone
		}
		s.logf("потоковая ступень %s: AUTH не прошёл: %v", won.cand.name, aerr)
		lastErr = aerr
		note(aerr)

		// Победитель, не прошедший AUTH, выбывает — остальным даём круг.
		// Тот же порядок, что у прямых: релей только когда откажут все.
		before := len(streams)
		streams = dropCandidate(streams, won.cand.name)
		if len(streams) == before {
			s.logf("лестница: победитель %s не найден в списке — второй круг не делаю",
				won.cand.name)
			break
		}
	}

	// 4. Релейные ступени — последовательно, каждая со своим релеем.
	//
	// В гонку их не берём: TURN-аллокация это лишний обмен с третьей
	// стороной, и гонять их наперегонки с прямыми значило бы тратить
	// креды и аллокации там, где прямой путь и так работает.
	relayTried := false
	s.hadRelay = len(relays) > 0
	for _, c := range relays {
		left := ladderLeft()
		// Откат релея (SetRelayTarget): вторая релейная ступень идёт после
		// первой, чей провал мог съесть остаток срока лестницы. Общий срок
		// релей и так не ограничивает (см. ниже), так что откату его
		// нехватка не помеха.
		if relayTried && left < minCandidateBudget {
			left = minCandidateBudget
		}
		relayTried = true
		if left < minCandidateBudget {
			s.logf("лестница: общий срок исчерпан, релейная ступень %s не пробовалась", c.name)
			break
		}
		// Время релейной ступени замеряем отдельно, и вот почему.
		//
		// Общий срок лестницы её НЕ покрывает: добыча кредов идёт
		// цепочкой в пять шагов, у каждого свой срок в 10 секунд, и
		// сроку лестницы они не подчинены. В худшем случае релейная
		// ступень одна может занять дольше, чем все 25 секунд, отведённые
		// на лестницу целиком.
		//
		// Обрывать её по общему сроку было бы неправильно: релей —
		// последняя надежда, и бросать его на середине цепочки значит
		// остаться совсем без связи. Поэтому замеряем и показываем, а
		// решение по сроку принимаем по живым числам.
		relayStart := time.Now()
		s.logf("ступень %s — пробую (общий срок лестницы её не ограничивает)", c.name)
		addr, err := s.dialOne(s.ctx, gateway, c, password, deviceID, prot,
			false, relayHandshakeBudget, minDuration(firstRungAuth, left))
		if err == nil {
			s.winner = c.name
			s.winCand = c
			s.logf("ступень %s — успех за %s", c.name,
				time.Since(relayStart).Round(time.Millisecond))
			// Многослот только отсюда: остальные слоты поднимаются той
			// же релейной ступенью, на тех же кредах, в фоне после
			// подъёма туннеля.
			if s.wantSlots > 1 {
				s.dialer = &slotDialer{
					gateway:  gateway,
					password: password,
					deviceID: deviceID,
					prot:     prot,
					cand:     c,
				}
			}
			return addr, nil
		}
		if fatalForLadder(err) {
			return "", err
		}
		if isNetworkGone(err) || errors.Is(err, errNetworkGone) {
			s.logf("сеть сменилась во время подъёма релея — прекращаю попытку целиком")
			return "", errNetworkGone
		}
		s.logf("ступень %s — неудача за %s: %v", c.name,
			time.Since(relayStart).Round(time.Millisecond), err)
		// Первая релейная неудача содержательнее второй: откат на
		// relay.target идёт с теми же хешами и повторит ту же беду с кредами.
		if s.relayErr == nil {
			s.relayErr = err
		}
		lastErr = err
		note(err)
	}

	// Молчание шлюза — самая содержательная из всех неудач лестницы.
	if silent != nil {
		lastErr = silent
	}
	if lastErr == nil {
		lastErr = errors.New("в лестнице нет ни одной ступени")
	}
	return "", fmt.Errorf("лестница пройдена без успеха, последняя ошибка: %w", lastErr)
}

// dialOne поднимает ОДНУ ступень целиком: транспорт и AUTH.
// Последовательный путь, используется для запомненной ступени.
func (s *session) dialOne(
	ctx context.Context, gateway string, c candidate, password, deviceID string,
	prot Protector, failDirect bool, hsBudget, authBudget time.Duration,
) (string, error) {
	r, err := s.raise(ctx, gateway, c, password, prot, failDirect, hsBudget)
	if err != nil {
		return "", err
	}
	return s.authRung(r, password, deviceID, authBudget)
}

// authRung отправляет AUTH по уже поднятому транспорту и принимает его
// в собственность сессии.
//
// Отдельно от raise намеренно: ровно здесь занимается слот по паролю на
// шлюзе, и вызов обязан быть ровно один на попытку.
// errAuthSilent — шлюз не ответил на AUTH ВООБЩЕ НИЧЕГО.
//
// Отдельная от прочих намеренно: это не "отказал", а "промолчал", и
// разница для человека огромная. Шлюз молчит, когда не может разобрать
// пакет — то есть когда ключ обфускации, выведенный из пароля, ему
// незнаком. Отвечать ему нечем: до разбора пароля дело не доходит,
// FATAL_AUTH шлётся уже ПОСЛЕ успешного расшифровывания.
//
// Самый частый случай — ключ выдан только что. Шлюз перечитывает
// список паролей раз в минуту, и всё это время свежий ключ для него
// не существует. 26.08 в 08:28 это дало шесть отказов подряд за сорок
// секунд, а в 08:32 тот же ключ подключился.
//
// Лестница предпочитает эту ошибку всем прочим в своём итоге, см.
// climb: сказать "сервер не ответил" честнее и полезнее, чем назвать
// последнюю по счёту неудачу.
var errAuthSilent = errors.New("шлюз не ответил на AUTH")

// heartbeat — ПУЛЬС СРЕДЫ ИСПОЛНЕНИЯ на время подъёма.
//
// Разделяет два совершенно разных объяснения задержек, которые иначе
// неразличимы:
//
//	замерла ВСЯ среда движка — пульс пропускает удары вместе со всем
//	  остальным. Значит нас заморозила система: процессу или его
//	  потокам не давали работать, и наши сроки тут ни при чём;
//	замерла ОДНА горутина — пульс идёт ровно, а сон в проверке
//	  растянулся. Значит дело в нашем коде, и чинить надо его.
//
// Повод: 27.08 сон на 1,5 секунды занял 9,4 при том, что эхо в той же
// проверке возвращалось за 73 мс. Обрезка длинных строк в logcat до
// этого уменьшила перебор вчетверо, но не убрала — значит осталась
// вторая причина, и какая, без пульса не сказать.
//
// Тикает раз в полсекунды и молчит, пока укладывается. Живёт только
// пока идёт подъём: постоянный тикер на всю сессию — это лишняя работа
// ради вопроса, который стоит только здесь.
func (s *session) heartbeat(ctx context.Context) {
	const beat = 500 * time.Millisecond
	t := time.NewTicker(beat)
	defer t.Stop()
	last := time.Now()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			// ВРЕМЯ БЕРЁМ СЕЙЧАС, А НЕ ИЗ ТИКА, и это не мелочь —
			// на этом я уже ошибся 27.08.
			//
			// В канале тикера помещается ровно один удар, лишние он
			// ВЫБРАСЫВАЕТ, а у дошедшего в значении лежит время, когда
			// он сработал, а не когда мы его забрали. Считая разницу по
			// этим значениям, замершая на семь секунд горутина увидит
			// ровный шаг в полсекунды и промолчит — что и вышло: сон
			// растянулся до 7,3 секунды, а пульс не сказал ничего.
			//
			// Разницу надо мерить между СЕЙЧАС и прошлым СЕЙЧАС: только
			// так видно, что нас не будили.
			now := time.Now()
			if gap := now.Sub(last); gap > beat+timingSlack {
				s.frozeAt.Store(now.UnixNano())
				// В копилку идёт лишнее сверх шага: сам шаг — не заморозка.
				s.frozenNs.Add(int64(gap - beat))
				s.logf("ПУЛЬС ПРОПАЛ на %s — среду движка останавливали целиком",
					gap.Round(time.Millisecond))
			}
			last = now
		}
	}
}

// errRungMute — ступень поднялась, но трафик по ней не идёт.
//
// Для лестницы это ОБЫЧНЫЙ отказ ступени, такой же как несостоявшееся
// рукопожатие: не фатальный, не уход сети. Лестница идёт дальше.
var errRungMute = errors.New("ступень не несёт трафик: шлюз не отвечает на метку")

// proveRung — доказательство, что по ступени ДЕЙСТВИТЕЛЬНО ходит трафик.
//
// Зачем она вообще, если AUTH только что прошёл. Затем, что "AUTH
// ответили" и "канал работает" оказались разными вещами. В логе 26.08
// три сессии подряд: AUTH проходит, шлюз выдаёт адрес, туннель встаёт —
// и дальше ноль встречных пакетов и ноль эха. Человек видел поднятый
// туннель без интернета и жал кнопку по три раза.
//
// Проверка стоит ЗДЕСЬ, в лестнице, а не в работающей сессии, и это
// принципиально. Ступень, не прошедшая проверку, — это ступень, которая
// не поднялась; лестница берёт следующую, а приложение о происходящем
// даже не знает. Ровно для этого лестница и заведена. Гасить и
// перезапускать уже поднятый туннель — не её способ работы.
//
// ДВЕ МЕТКИ, РАЗНЕСЁННЫЕ НА rungProofGap. Одной мало: ступень успевает
// ответить на AUTH и оглохнуть через секунду, см. rungProofGap.
//
// Отвечать годится ЧЕМ УГОДНО — эхом метки или встречным пакетом:
// доказываем не вид ответа, а сам факт, что шлюз нас слышит. Пакет,
// съеденный проверкой, не теряется ни для кого: TUN ещё не подключён,
// и читать эти байты всё равно некому.
//
// Шлюз без эха (echoConf=false) проверить нечем — тогда пропускаем.
// Молча признать ступень годной честнее, чем забраковать без оснований.
func (s *session) proveRung(r *rung) error {
	if !s.echoConf {
		s.logf("%s: шлюз без эха — проверить ступень нечем, беру как есть", r.cand.name)
		return nil
	}

	buf := make([]byte, 2048)
	// Повтор из-за замирания даётся ОДИН раз на всю проверку: нас
	// останавливают подряд, но ждать бесконечно нельзя — иначе мёртвая
	// ступень будет держать лестницу сколько угодно.
	retried := false

	// ЗАПОМНЕННОЙ СТУПЕНИ — ОДНА МЕТКА (решение владельца 24.09, вариант 2).
	//
	// Пауза перед второй меткой — полторы секунды на КАЖДОМ подключении, а
	// запомненная ступень на этой сети уже работала. Поломку «ответила на
	// AUTH и оглохла через секунду» здесь больше не ловим до подъёма: её
	// поймает сторож немоты уже в поднятом туннеле (suspectSilenceLimit),
	// переподключение забудет немой путь (forgetMutePath) и пойдёт гонкой.
	// Цена промаха — секунды переподключения вместо следующей ступени.
	//
	// Только при первом заходе к ней: вернувшись в гонку после провала
	// (spent), она проверяется полностью, как любая.
	//
	// ПОТОКУ (TCP/TLS) — ТОЖЕ ОДНА. Вторая метка ловит беду UDP: первый
	// обмен в потоке датаграмм проходит, следующие режут (26.08, 24.09 —
	// B ответила на метку 1 и умерла до метки 2). У TCP доставка своя, а
	// резать поток после подъёма оператор начинает через секунды, не через
	// полторы — это ловит сторож немоты и память пути (PathMemory,
	// MUTE_SUFFIX), вторая метка его не видит. Платить за неё полторы
	// секунды на каждом подъёме потоком не за что (лог 24.09 20:46:13).
	marks := 2
	switch {
	case r.cand.remembered && !r.cand.spent:
		marks = 1
		s.logf("%s: запомненная ступень — проверяю одной меткой", r.cand.name)
	case r.cand.transport == transTCP || r.cand.transport == transTLS:
		marks = 1
		s.logf("%s: поток — проверяю одной меткой", r.cand.name)
	}

	for i := 1; i <= marks; i++ {
		if i > 1 {
			gapFrom := time.Now()
			select {
			case <-s.ctx.Done():
				return errSessionStopped
			case <-time.After(rungProofGap):
			}
			if slept := time.Since(gapFrom); slept > rungProofGap+timingSlack {
				s.logf("%s: ЗАМЕР — пауза между метками просили %s, вышло %s",
					r.cand.name, rungProofGap, slept.Round(time.Millisecond))
			}
		}
		if _, err := r.link.Write(keepaliveMarker); err != nil {
			return fmt.Errorf("метка проверки не ушла: %w", err)
		}

		// ЖДЁМ ИМЕННО ЭХО, А НЕ ЛЮБОЙ ПАКЕТ.
		//
		// Раньше годился первый попавшийся ответ, и лог 27.08 показал,
		// чего это стоило: строки "метка 2 — шлюз ответил, 76 байт" и
		// "107 байт" — это не эхо, а встречный трафик. Шлюз шлёт его на
		// наш адрес в туннеле, потому что адрес выдаётся по хешу пароля
		// и достаётся тот же, что был у прошлой сессии.
		//
		// Ущерб двойной. Ступень признавалась годной, хотя её метка НЕ
		// подтверждена ничем: сессия 00:17:31 прошла проверку по такому
		// пакету и через восемь секунд оказалась немой. А эхо на ту же
		// метку оставалось в буфере и всплывало уже после подъёма, за
		// 64-67 мс — это и были "ранние короткие".
		//
		// Встречный пакет доказывает только, что шлюз шлёт В НАШУ
		// сторону. Вопрос же стоит обратный: доходит ли до него НАШЕ.
		// Ответить на него может лишь отражение нашей собственной метки.
		//
		// Пропущенные пакеты не теряются ни для кого: TUN ещё не
		// подключён, и читать их всё равно некому.
		sentAt := time.Now()
		deadline := sentAt.Add(rungProofWait)
		skipped := 0
		for {
			_ = r.link.SetReadDeadline(deadline)
			n, err := r.link.Read(buf)
			if err != nil {
				_ = r.link.SetReadDeadline(time.Time{})
				if isTimeout(err) {
					// ЗАМЕР В СТРОКЕ, а не отдельной: срок мы просили
					// один, а ждали, судя по логам, иногда вчетверо
					// дольше. Без этой цифры отличить "ступень оглохла"
					// от "нас самих задержали" нечем.
					// Число отброшенных — вторая половина замера кота 1.
					// Он показал, что шлюз эхо отправил; если здесь ноль,
					// до нас оно не дошло вовсе, а если не ноль — дошло,
					// и мы сами его не приняли.
					s.logf("%s: эха на метку %d нет за %s (просили %s, "+
						"встречных пакетов %d, отброшено негодных %d); "+
						"метка ушла в %s UTC",
						r.cand.name, i, time.Since(sentAt).Round(time.Millisecond),
						rungProofWait, skipped, r.droppedCount(),
						utcMilli(sentAt))

					// КОНТРОЛЬНЫЙ AUTH ПРЯМО ЗДЕСЬ, а не в стороже
					// немого туннеля.
					//
					// Он там и стоял, и ни разу не сработал: с тех пор
					// как ступень проверяется ДО подъёма, немым туннель
					// больше не встаёт — беду ловят здесь. Развилка, ради
					// которой контрольный AUTH делался, так и оставалась
					// непройденной.
					//
					// Ступень уже забракована, терять нечего. Новый сокет
					// с новым исходящим портом, тот же путь, тот же
					// пароль: ответ пришёл — путь и сеть живы, глохнет
					// именно это соединение; ответа нет — до шлюза не
					// доходит ничего.
					// НЕ СУДИМ СТУПЕНЬ ПО ОКНУ, В КОТОРОМ НАС НЕ БЫЛО.
					//
					// Срок чтения задан абсолютным временем. Замер
					// процесса до срока и пробуждение после дают "истёк"
					// даже тогда, когда ответ уже лежит в буфере сокета.
					// Ступень при этом исправна, а мы её вычёркиваем и
					// уходим на релей: подключение из одной секунды
					// становится десятью.
					//
					// Пульс 27.08 показал, что нас останавливают на
					// 2,7-7,1 секунды подряд, и происходит это когда
					// человек сворачивает приложение. Окно проверки при
					// этом съедается целиком и не по вине ступени.
					// ПОВТОР — ТОЛЬКО ПОСЛЕ ДОКАЗАННОГО ЗАМИРАНИЯ.
					//
					// Была короткая версия «повторять всегда»: гипотеза
					// кота 1, что вторая метка теряется из-за спящего
					// радио, и повтор по разбуженному каналу её спасёт.
					// Гипотеза опровергнута двумя независимыми замерами.
					//
					// Первый — живой, 27.08 19:09:28: повтор сработал, а
					// эха всё равно нет. Радио к этому мигу заведомо не
					// спало — за секунду до того AUTH и метка 1 получили
					// эхо, — а вторая метка не дошла и на повторе.
					//
					// Второй — калибровка часов у кота 1: его «медленный
					// восходящий 234-258 мс» оказался сдвигом часов
					// телефона (+202 мс). За вычетом сдвига остаётся
					// обычные 31-55 мс. Медленного восходящего не было, и
					// промотирование радио тут ни при чём.
					//
					// Потеря второй метки — на обратном проводе (кот 1:
					// эхо отправлено, у нас отброшено негодных 0), и
					// повтор её не лечит. Держать его «на всякий» значило
					// бы дарить каждому провалу лишние 1,2 с ожидания.
					//
					// А замирание среды — причина ДОКАЗАННАЯ, пультом.
					// Срок чтения абсолютный: замороженный до срока и
					// разбуженный после получает тайм-аут при живом ответе
					// в буфере. Здесь повтор оправдан — в первый раз нас
					// просто не было. Повтор ОДИН: ветка ошибки без
					// предела недопустима.
					// ЗАМИРАНИЕ МЕРИМ И САМИ, не только по пульсу.
					//
					// 02.09 10:18:20: очнулись после 33 с, чтение вернуло
					// "истёк", а пульс ещё не успел тикнуть — frozeAt
					// был старым, повтор не сработал, ступень ушла в
					// брак (строка «ПУЛЬС ПРОПАЛ» в логе стоит НИЖЕ
					// «контрольный AUTH»). Гонка с пульсом проигрывается
					// ровно тогда, когда нужна. Поэтому второй признак:
					// просили rungProofWait, а ждали заметно дольше —
					// значит, нас не было, и это не зависит ни от кого.
					waited := time.Since(sentAt)
					stalled := waited > rungProofWait+timingSlack
					froze := s.frozeAt.Load()
					if (froze > sentAt.UnixNano() || stalled) && !retried {
						retried = true
						s.logf("%s: нас останавливали во время ожидания — "+
							"повторяю метку %d, ступень тут ни при чём",
							r.cand.name, i)
						sentAt = time.Now()
						deadline = sentAt.Add(rungProofWait)
						if _, err := r.link.Write(keepaliveMarker); err != nil {
							return fmt.Errorf("метка проверки не ушла: %w", err)
						}
						continue
					}

					s.probeAuthNow(r.cand)
					return errRungMute
				}
				return err
			}
			if n >= 20 {
				skipped++
				continue
			}
			s.logf("%s: метка %d — эхо вернулось за %s, %d байт "+
				"(встречных до него %d); метка ушла в %s UTC",
				r.cand.name, i, time.Since(sentAt).Round(time.Millisecond),
				n, skipped, utcMilli(sentAt))
			break
		}
	}
	// Срок снимаем: дальше сроками чтения распоряжается насос.
	_ = r.link.SetReadDeadline(time.Time{})
	return nil
}

func (s *session) authRung(r *rung, password, deviceID string, budget time.Duration) (string, error) {
	// Последняя проверка перед тем, как занять слот по паролю. Между
	// подъёмом транспорта и этой строкой прошло время — при форе без
	// DTLS до полутора секунд, — и сеть за него могла смениться. AUTH с
	// сокета, привязанного к исчезнувшему адресу, уйдёт в никуда, а мы
	// спишем ступень со счетов ни за что.
	if s.networkChanged() {
		r.close()
		return "", errNetworkGone
	}

	// Многослот включается ТОЛЬКО на релейной ступени: на прямом пути
	// он у роутера неприменим вовсе — там нет шейпа на аллокацию,
	// наращивать нечего (спецификация-2, C.5). Поэтому caps прямых
	// ступеней остаётся прежним "echo", байт в байт.
	slots := 1
	if r.cand.isRelay && s.wantSlots > 1 {
		slots = s.wantSlots
	}

	// НУЖЕН LИ NOISE NK — документ Кота1, раздел 3: TLS-поток уже защищён
	// своей пиновкой (tlspin.go), DTLS-путь только что проверен отпечатком
	// выше (dialDTLS). Все остальные — прямой UDP без DTLS, релей через VK
	// (тоже UDP без DTLS), TCP-поток без TLS — идут голым текстом и
	// нуждаются в NK.
	needsNK := r.cand.transport != transTLS && !r.cand.useDTLS

	addr, err := s.auth(r.link, r.pc, password, deviceID, budget,
		authCaps(slots, s.sessionGen), needsNK)
	if err != nil {
		r.close()
		return "", err
	}

	// ПРОВЕРКА ДО ПРИНЯТИЯ. Ступень, которая не несёт трафик, для
	// лестницы такая же неудача, как несостоявшееся рукопожатие.
	if err := s.proveRung(r); err != nil {
		r.close()
		return "", err
	}

	// Ступень поднялась — только теперь ресурсы становятся сессионными.
	// Если сессию успели остановить, пока мы поднимались, прибираем за
	// собой немедленно: оставить работающий сокет без хозяина нельзя.
	if !s.adoptFirst(r) {
		r.close()
		return "", errSessionStopped
	}
	s.logf("MTU туннеля для этой ступени: %d", r.cand.mtu)
	return addr, nil
}

// isTimeout — истёк ли срок. Сокет и dtls.Conn сообщают об этом
// по-разному, поэтому проверок две.
func isTimeout(err error) bool {
	if errors.Is(err, os.ErrDeadlineExceeded) {
		return true
	}
	var ne net.Error
	return errors.As(err, &ne) && ne.Timeout()
}

func minDuration(a, b time.Duration) time.Duration {
	if a < b {
		return a
	}
	return b
}

// dialDTLS поднимает DTLS поверх obfs.
func (s *session) dialDTLS(
	ctx context.Context, c candidate,
	obfs *obfsPacketConn, raddr net.Addr, udp net.PacketConn, budget time.Duration,
) (packetLink, error) {
	cert, err := selfsign.GenerateSelfSigned()
	if err != nil {
		return nil, fmt.Errorf("генерация сертификата: %w", err)
	}

	// Сертификат шлюза не проверяется НАМЕРЕННО, как и в роутерном клиенте:
	// подлинность канала держится не на PKI, а на общем ключе обфускации,
	// выведенном из пароля. Без верного пароля клиент до DTLS не доберётся.
	// Connection ID не запрашиваем — на этом стеке от него нет выгоды,
	// а накладные расходы реальны.
	cfg := &dtls.Config{
		Certificates:         []tls.Certificate{cert},
		InsecureSkipVerify:   true,
		ExtendedMasterSecret: dtls.RequireExtendedMasterSecret,
		CipherSuites:         []dtls.CipherSuiteID{dtls.TLS_ECDHE_ECDSA_WITH_AES_128_GCM_SHA256},
		MTU:                  dtlsMTU,
	}

	// ВНИМАНИЕ. dtls.Client рукопожатия НЕ делает: createConn лишь
	// собирает структуру и возвращает её (pion/dtls v3.1.5 conn.go:244-275),
	// в сеть при этом не уходит ни байта. Само рукопожатие отложено до
	// первого Read/Write, и там оно идёт через c.Handshake() →
	// HandshakeContext(context.Background()) (conn.go:449, 496, 286-288),
	// то есть БЕЗ какого бы то ни было срока. Отсюда и висело молча.
	conn, err := dtls.Client(obfs, raddr, cfg)
	if err != nil {
		return nil, fmt.Errorf("создание клиента DTLS: %w", err)
	}
	s.logf("%s: транспорт создан, срок рукопожатия %s", c.name, budget)

	// Рукопожатие запускаем сами: HandshakeContext — единственный способ
	// поставить на него срок. Контекст приходит снаружи и наследуется от
	// s.ctx, поэтому Stop() снимает застрявшее рукопожатие. В гонке тот
	// же контекст отменяется победителем — так проигравшие обрываются
	// сразу, а не досиживают свой срок до конца.
	hsCtx, hsCancel := context.WithTimeout(ctx, budget)
	_ = udp.SetDeadline(time.Now().Add(budget + deadlineSlack))
	err = conn.HandshakeContext(hsCtx)
	hsCancel()
	if err != nil {
		conn.Close()
		return nil, fmt.Errorf("рукопожатие DTLS: %w", err)
	}
	s.logf("%s: рукопожатие прошло", c.name)

	// ПРОВЕРКА ПОДЛИННОСТИ ШЛЮЗА ДО ПАРОЛЯ (документ Кота1,
	// MOBILNYJ-KLIENT-PROTOKOL.md, e6afeb4, раздел 3.2). Сертификат
	// самоподписанный (см. InsecureSkipVerify выше — цепочки доверия для
	// него нет и не будет), поэтому подлинность держится не на PKI, а на
	// совпадении с зашитым отпечатком. Сертификат шлюза постоянный, тот же
	// используется и для TCP-TLS (nknoise.go).
	state, ok := conn.ConnectionState()
	if !ok || len(state.PeerCertificates) == 0 {
		conn.Close()
		return nil, errGatewayNotAuthentic
	}
	sum := sha256.Sum256(state.PeerCertificates[0])
	if hex.EncodeToString(sum[:]) != gatewayDTLSFingerprint {
		conn.Close()
		return nil, errGatewayNotAuthentic
	}
	s.logf("%s: отпечаток шлюза подтверждён", c.name)
	return conn, nil
}

// auth проходит AUTH и разбирает ответ шлюза.
//
// needsNK — нужно ли ЗАВЕРНУТЬ обмен в Noise NK (документ Кота1, раздел 3.1)
// перед отправкой пароля: да для прямого UDP без DTLS, релея и TCP-потока;
// нет для DTLS (отпечаток уже проверен в dialDTLS) и TLS-потока (свой пин,
// tlspin.go). Разбор ответа "OK|.../FATAL_..." НЕ меняется вообще — меняется
// только то, что расшифровывается перед тем, как в него попасть.
func (s *session) auth(
	link packetLink, udp net.PacketConn, password, deviceID string,
	budget time.Duration, caps string, needsNK bool,
) (string, error) {
	var nkSend, nkRecv *cipherState

	if needsNK {
		ni, err := newNKInitiator(gatewayStaticPublicKey)
		if err != nil {
			return "", fmt.Errorf("Noise NK: %w", err)
		}
		msg1, err := ni.writeMsg1([]byte{nkProtocolVersion})
		if err != nil {
			return "", fmt.Errorf("Noise NK, сборка msg1: %w", err)
		}
		_ = link.SetWriteDeadline(time.Now().Add(budget))
		if _, err := link.Write(msg1); err != nil {
			return "", fmt.Errorf("отправка msg1: %w", err)
		}
		buf := make([]byte, 2048)
		_ = link.SetReadDeadline(time.Now().Add(budget))
		n, err := link.Read(buf)
		if err != nil {
			// Тишина в ответ на msg1 — тот же исход, что и провал
			// отпечатка на DTLS: подлинность не подтверждена, пароль
			// не уходит вовсе (см. errGatewayNotAuthentic).
			return "", errGatewayNotAuthentic
		}
		if _, err := ni.readMsg2(buf[:n]); err != nil {
			return "", errGatewayNotAuthentic
		}
		send, recv := ni.split()
		nkSend, nkRecv = &send, &recv
		s.logf("проверка подлинности шлюза (Noise NK) пройдена")
	}

	// AUTH|<пароль>|<устройство>|<возможности>
	// Пароль в лог не попадает никогда. Возможности — попадают: там нет
	// ничего тайного, а видеть, ушёл ли multi с поколением, надо.
	authMsg := fmt.Sprintf("AUTH|%s|%s|%s", password, deviceID, caps)
	s.logf("отправляю AUTH (%s), срок ответа %s", caps, budget)

	// Дедлайн сокета взводится на срок AUTH и НЕ снимается до конца
	// обмена: участок обязан оставаться под предохранителем.
	//
	// udp может быть nil — у ПОТОКОВОЙ ступени (TCP/TLS) отдельного
	// UDP-сокета нет, транспорт целиком в link. Срок чтения там ставится
	// на сам link ниже (SetReadDeadline), а вызов udp.SetDeadline по
	// nil-интерфейсу — паника и нативный краш процесса.
	if udp != nil {
		_ = udp.SetDeadline(time.Now().Add(budget + deadlineSlack))
	}
	_ = link.SetWriteDeadline(time.Now().Add(budget))
	wireMsg := []byte(authMsg)
	if nkSend != nil {
		enc, err := nkSend.encrypt(nil, wireMsg)
		if err != nil {
			return "", fmt.Errorf("шифрование AUTH (Noise NK): %w", err)
		}
		wireMsg = enc
	}
	if _, err := link.Write(wireMsg); err != nil {
		return "", fmt.Errorf("отправка AUTH: %w", err)
	}
	s.logf("AUTH отправлен, жду ответ")

	// ЖДЁМ ИМЕННО ОТВЕТ НА AUTH, А НЕ ПЕРВЫЙ ПАКЕТ.
	//
	// Раньше читали один раз и судили по тому, что пришло. 27.08 в
	// 20:14:00 это стоило ступени: вместо ответа шлюза первым пришёл
	// встречный ПАКЕТ ДАННЫХ — сырой IP с TLS внутри, начинающийся с
	// 0x45 ("E\x00\x00T5\xa5@\x009\x065&h..."). Ступень забраковали со
	// словами "непонятный ответ на AUTH", лестница ушла на релей.
	//
	// Откуда он берётся. Адрес в туннеле шлюз выдаёт по хешу пароля, и
	// достаётся тот же, что был у прошлой сессии. Пока шлюз не узнал о
	// нашем уходе (а мы ему о нём не сообщаем — UDP, никакого
	// прощания), он продолжает слать на этот адрес нисходящий трафик
	// прошлой сессии. Он и приходит поверх нашего свежего сокета.
	//
	// Ровно та же болезнь уже была вылечена в proveRung: там встречный
	// пакет принимался за эхо. Здесь она осталась незамеченной, потому
	// что случается реже — нужно, чтобы встречный успел раньше ответа.
	//
	// Различаем по форме, а не по длине: ответ шлюза — текст, он либо
	// "OK|...", либо "FATAL_...". Пакет данных начинается с версии IP
	// (0x45 для IPv4, 0x6 для IPv6) и ни тем, ни другим быть не может.
	// Всё, что не похоже на ответ, пропускаем и читаем дальше, пока не
	// вышел срок.
	//
	// Пропущенное не теряется ни для кого: TUN ещё не подключён, и
	// читать эти байты некому.
	buf := make([]byte, 2048)
	authDeadline := time.Now().Add(budget)
	var resp string
	skipped := 0
	for {
		_ = link.SetReadDeadline(authDeadline)
		n, err := link.Read(buf)
		if err != nil {
			// Тишина в ответ — отдельный исход, не то же самое, что
			// отказ. Шлюз молчит, если AUTH негоден синтаксически.
			if skipped > 0 {
				s.logf("ответа на AUTH нет, встречных пакетов отброшено %d", skipped)
			}
			return "", fmt.Errorf("%w: %v", errAuthSilent, err)
		}
		raw := buf[:n]
		var cand string
		if nkRecv != nil {
			pt, err := nkRecv.decrypt(nil, raw)
			if err != nil {
				// Не расшифровалось — тем же способом, что и "не похоже
				// на ответ" в открытом виде ниже: пропускаем, читаем
				// дальше. Чаще всего это тот же встречный пакет прошлой
				// сессии, что описан выше, только теперь он не пройдёт
				// AEAD и не притворится ответом случайно.
				skipped++
				continue
			}
			cand = string(pt)
		} else {
			cand = string(raw)
		}
		if strings.HasPrefix(cand, "OK|") || strings.HasPrefix(cand, "FATAL_") {
			resp = cand
			break
		}
		skipped++
	}
	if skipped > 0 {
		s.logf("ответ на AUTH получен, встречных пакетов до него %d", skipped)
	}

	if strings.HasPrefix(resp, "FATAL_") {
		// Ответ шлюза уходит в лог ЦЕЛИКОМ, обрезанный по длине.
		//
		// Ради того же, ради чего в задаче 51.2 логируется незнакомый
		// вердикт API: если шлюз уже сегодня добавляет к FATAL_AUTH
		// какой-то суффикс, мы увидим его в первом же живом случае и
		// добавим в таблицу — вместо того чтобы гадать о форме.
		//
		// Пароль сюда попасть не может: это ответ шлюза, а не наш
		// запрос.
		s.logf("шлюз отклонил подключение, ответ: %q", cut([]byte(resp), 120))
		return "", classifyAuthRefusal(resp)
	}

	parts := strings.Split(resp, "|")
	if len(parts) < 4 || parts[0] != "OK" {
		return "", fmt.Errorf("непонятный ответ на AUTH: %q", resp)
	}

	// ВАЖНО: маска приходит как net.IPMask.String() в Go — это ХЕКС
	// ("ffffff00"), а НЕ точечно-десятичная запись ("255.255.255.0").
	prefix, err := maskHexToPrefix(parts[3])
	if err != nil {
		return "", fmt.Errorf("разбор маски %q: %w", parts[3], err)
	}

	if len(parts) >= 5 && strings.Contains(parts[4], "echo") {
		s.echoConf = true
	}
	s.logf("шлюз %s, маска /%d, эхо-keepalive=%v", parts[2], prefix, s.echoConf)
	lastAuthGateway.Store(parts[2])
	lastAuthMaskHex.Store(parts[3])

	// Сроки снимаются ТОЛЬКО здесь — когда позади и рукопожатие, и AUTH.
	// Снять их раньше означало бы вернуть молчаливое зависание.
	if udp != nil {
		_ = udp.SetDeadline(time.Time{})
	}
	_ = link.SetReadDeadline(time.Time{})
	_ = link.SetWriteDeadline(time.Time{})

	return parts[1] + "/" + strconv.Itoa(prefix), nil
}

// maxWire — самый крупный пакет, ушедший на провод за сессию.
// Ноль, если ступень так и не поднялась.
func (s *session) maxWire() uint64 {
	var max uint64
	for _, r := range s.slotList() {
		// Считает и UDP, и поток — как droppedCount. Пропускать поток
		// (obfs у него пуст) значило бы писать в итог ноль там, где на
		// провод ушли килобайты.
		var w uint64
		switch {
		case r.obfs != nil:
			w = r.obfs.maxWire()
		default:
			if sl, ok := r.link.(*streamLink); ok {
				w = sl.maxFrame.Load()
			}
		}
		if w > max {
			max = w
		}
	}
	return max
}

func maskHexToPrefix(hexMask string) (int, error) {
	if len(hexMask) != 8 {
		return 0, fmt.Errorf("ожидалось 8 hex-символов, получено %d", len(hexMask))
	}
	v, err := strconv.ParseUint(hexMask, 16, 32)
	if err != nil {
		return 0, err
	}
	return bits.OnesCount32(uint32(v)), nil
}

// start принимает дескриптор TUN от VpnService и запускает перекачку.
func (s *session) start(fd int) error {
	// ПРОВЕРКА НА КОНКРЕТНОМ ТИПЕ И ДО ПРИСВОЕНИЯ В ИНТЕРФЕЙС.
	//
	// Нулевой *os.File, положенный в io.ReadWriteCloser, даёт НЕ-nil
	// интерфейс: stop() со своим `if s.tun != nil` вызвал бы Close() на
	// нулевом указателе. Порядок здесь — часть правки, а не стиль.
	f := os.NewFile(uintptr(fd), "tun")
	if f == nil {
		return errors.New("неверный дескриптор TUN")
	}
	s.tun = f
	return s.startPumps()
}

// startFlow — то же, но для платформы без дескриптора TUN.
func (s *session) startFlow(flow PacketFlow) error {
	if flow == nil {
		return errors.New("поток пакетов не передан")
	}
	s.tun = newFlowConn(flow, s.logf)
	return s.startPumps()
}

// startPumps — общая часть обоих входов. Всё, что ниже, к источнику
// пакетов отношения не имеет и о нём не знает.
func (s *session) startPumps() error {

	// Насосы под счётчиком: сессия не считается остановленной, пока не
	// вышел последний. Закрытый сокет ещё не значит завершённую горутину.
	//
	// Насос чтения — СВОЙ НА КАЖДЫЙ слот: слоты читаются одновременно,
	// а пишутся в один TUN. Насосы слотов, поднятых позже, добавляются
	// в ту же группу из addSlot.
	s.upAt = time.Now()

	list := s.slotList()
	s.armStun()
	s.wg.Add(2 + len(list))
	go func() { defer s.wg.Done(); s.tunToNet() }()
	go func() { defer s.wg.Done(); s.keepalive() }()
	// Сторож немого туннеля. В группу насосов НЕ входит: он только
	// смотрит и спит, держать из-за него остановку незачем.
	go s.muteWatch()
	// Первый отпечаток — сразу после подъёма. С ним будет сравниваться
	// тот, что снимет сторож немоты.
	go s.probeStunNow("подъём")
	for _, r := range list {
		r := r
		go func() { defer s.wg.Done(); s.netToTun(r) }()
	}

	// Дополнительные слоты поднимаются в фоне, уже после того как
	// туннель встал: человек начинает пользоваться связью сразу, а
	// слоты присоединяются по мере готовности. Раздача вверх подхватит
	// их сама, как только состав изменится.
	if s.dialer != nil && s.wantSlots > 1 {
		go s.openExtraSlots()
	}
	// Автоподбор — только на релее и только если его не выключили
	// вручную. Признак релея — наличие dialer: он ставится ровно на
	// релейной ступени.
	if s.dialer != nil && s.slotsAuto {
		go s.runAutoSlots()
	}
	return nil
}

func (s *session) tunToNet() {
	buf := make([]byte, tunMTU+80)
	for {
		n, err := s.tun.Read(buf)
		if err != nil {
			// Инвариант: ветка ошибки НИКОГДА не делает continue без паузы.
			// Ровно так на роутере родились 118 МБ лога за 19 минут.
			// Здесь выход из цикла и остановка сессии целиком.
			s.logf("чтение TUN прекращено: %v", err)
			s.stop("ошибка чтения TUN")
			return
		}
		if n == 0 {
			continue
		}
		// IPv6 ГАСИМ ЗДЕСЬ. Разбор — у поля v6Dropped.
		//
		// Это НЕ ветка ошибки: чтение удалось, пакет целый, мы просто
		// не умеем его доставить. Крутиться на месте она не может —
		// следующий оборот начинается с чтения из TUN.
		//
		// Версия IP — старшая половина первого байта. Проверка дешевле
		// любой другой: один байт, без разбора заголовка.
		if buf[0]>>4 == 6 {
			if s.v6Dropped.Add(1) == 1 {
				s.logf("IPv6 из TUN отброшен: шлюз v6 не несёт, " +
					"маршрут забран в туннель чтобы не текло мимо")
			}
			continue
		}
		// Раздача вверх: round-robin пачками по slotChunk. При одном
		// слоте это просто он сам.
		r := s.nextSlot()
		if r == nil {
			s.logf("слотов не осталось, перекачка вверх прекращена")
			s.stop("нет слотов")
			return
		}
		if _, err := r.link.Write(buf[:n]); err != nil {
			if r.retired.Load() {
				// Слот сняли планово прямо во время записи.
				// Пакет теряем, сессию не трогаем.
				continue
			}
			s.logf("запись в туннель прекращена: %v", err)
			s.stop("ошибка записи в туннель")
			return
		}
		s.txBytes.Add(uint64(n))
		if s.txCount.Add(1) == 1 {
			s.logf("первый пакет ушёл в туннель, %d байт", n)
		}
	}
}

// netToTun — насос чтения ОДНОГО слота. Слотов может быть несколько,
// TUN один: пишут в него все, каждый своим вызовом.
func (s *session) netToTun(r *rung) {
	buf := make([]byte, 2048)
	for {
		// Скользящий срок чтения, как у роутерного клиента
		// (спецификация 1.7). Ставится ТОЛЬКО при подтверждённом echo:
		// без него шлюз не обязан слать в простое вообще ничего, и
		// тишина означала бы не смерть канала, а отсутствие трафика
		// (спецификация 1.5). Убить исправный простаивающий туннель
		// было бы хуже, чем не заметить мёртвый.
		if s.echoConf {
			_ = r.link.SetReadDeadline(time.Now().Add(rxSilenceLimit))
		}
		n, err := r.link.Read(buf)
		if err != nil {
			if isTimeout(err) {
				s.logf("тишина в туннеле дольше %s", rxSilenceLimit)
				s.stop("канал молчит")
				return
			}
			if r.retired.Load() {
				// Плановое снятие слота: насос уходит тихо.
				return
			}
			s.logf("чтение туннеля прекращено: %v", err)
			s.stop("ошибка чтения туннеля")
			return
		}
		// Всё короче 20 байт — не IP-пакет: это эхо keepalive.
		if n < 20 {
			// ЭХО ЗАСЧИТЫВАЕТСЯ ТОЛЬКО ПОСЛЕ ТОГО, КАК УШЛА НАША МЕТКА.
			//
			// Смысл счётчика — ответить на вопрос «слышит ли нас шлюз
			// СЕЙЧАС». Ответить на него может только отклик на то, что
			// мы сами послали ПОСЛЕ подъёма туннеля. Короткий пакет,
			// прилетевший раньше первой метки, на этот вопрос не
			// отвечает: он мог остаться в буфере сокета от проверки
			// ступени, которая шлёт свои метки ещё в лестнице.
			//
			// Разница не умозрительная. Сторож немоты судит по
			// echoCount, и засчитанный ранний пакет заставил бы его
			// промолчать на туннеле, который умер сразу после подъёма,
			// — то есть ровно в том случае, ради которого он и заведён.
			//
			// Ранние считаем отдельно и говорим о первом вслух: именно
			// они объясняют, почему эхо стало возвращаться за 66-96 мс
			// вместо трёх секунд. Ответ на этот вопрос — в логе, а не в
			// рассуждении.
			if !s.echoArmed.Load() {
				if s.echoEarly.Add(1) == 1 {
					s.logf("короткий пакет ДО первой метки, через %s, %d байт — "+
						"эхом не считаю, он отвечает не на наш вопрос",
						time.Since(s.upAt).Round(time.Millisecond), n)
				}
				continue
			}
			if s.echoCount.Add(1) == 1 {
				s.logf("ЭХО от шлюза вернулось через %s — шлюз нас слышит и отвечает",
					time.Since(s.upAt).Round(time.Millisecond))
			}
			continue
		}
		s.rxBytes.Add(uint64(n))
		if s.rxCount.Add(1) == 1 {
			s.logf("первый пакет пришёл из туннеля, %d байт", n)
		}
		if _, err := s.tun.Write(buf[:n]); err != nil {
			s.logf("запись в TUN прекращена: %v", err)
			s.stop("ошибка записи в TUN")
			return
		}
	}
}

// muteWatch — сторож туннеля, который встал и не понёс ничего.
//
// Отличается от rxSilenceLimit тем, ЧТО именно сторожит. Тот следит за
// смертью живого канала: срок сдвигается на каждом принятом пакете, и
// пока хоть что-то идёт, он молчит. Здесь случай другой — канал не ожил
// НИ РАЗУ. Такой туннель до сих пор жил до девяноста секунд или до тех
// пор, пока человек не выключит его руками, и выглядело это как
// "подключается, но интернета нет".
//
// РАЗБОР ВИНЫ ЗДЕСЬ ЖЕ, и ради него сторож и заведён. Три случая:
//
//	эхо есть, полезного нет — шлюз нас слышит и отвечает, но встречный
//	  трафик до нас не доходит. Наша отправка исправна;
//	эха нет вовсе — до шлюза не доезжает ничего, включая метку. Ломается
//	  раньше шлюза: у нас или по дороге;
//	ничего не отправляли — сторожить нечего, туннель просто простаивал.
func (s *session) muteWatch() {
	select {
	case <-s.ctx.Done():
		return
	case <-time.After(muteLimit):
	}

	tx := s.txCount.Load()
	rx := s.rxCount.Load()
	echo := s.echoCount.Load()

	// Судим ПО ЭХУ, а не по счётчику принятого, и вот почему.
	//
	// 26.08 в 10:52:08 в немую сессию пришёл РОВНО ОДИН пакет. Условие
	// "принято ноль" на нём и споткнулось: сессия считалась живой,
	// туннель молчал восемнадцать секунд, человек выключил руками.
	//
	// Эхо такой лазейки не даёт: метку шлём мы сами, и её возврат
	// означает работающий канал, а не удачу.
	if !s.echoConf || tx == 0 || echo > 0 {
		return
	}

	// Сеть под нами — первое, что надо знать: если её больше нет, дело
	// не в шлюзе и не в дороге, а в том, что сокет прибит к тому,
	// чего не стало.
	gone := ""
	if s.networkChanged() {
		gone = " СЕТЬ ПОД НАМИ СМЕНИЛАСЬ — сокет прибит к прежней."
	}
	// Локальный порт и возраст — чтобы строку можно было сопоставить с
	// журналом шлюза, не отыскивая порт вручную выше по логу.
	// АДРЕС БЕРЁМ И У ПОТОКА ТОЖЕ.
	//
	// pc пуст у потоковой ступени (TCP/TLS) — своего UDP-сокета у неё
	// нет, — и первый вариант этой проверки писал в отчёт "сокет ?".
	// Ровно на потоке отчёт и понадобился: 03.09 немел именно он, а
	// сопоставить строку с журналом шлюза стало нечем.
	//
	// ОТБРОШЕННЫЕ КАДРЫ — ВТОРАЯ ПОЛОВИНА УЛИКИ. Без них "принято 0"
	// толкуется двояко: провод молчал или мы сами роняли пришедшее,
	// не пройдя проверку целостности. Ноль здесь означает, что до нас
	// не дошло ничего, и вина не наша.
	local, dropped := "?", uint64(0)
	if list := s.slotList(); len(list) > 0 {
		if list[0].pc != nil {
			local = list[0].pc.LocalAddr().String()
		} else if sl, ok := list[0].link.(*streamLink); ok {
			local = sl.conn.LocalAddr().String() + " (поток)"
		}
		dropped = list[0].droppedCount()
	}
	s.logf("НЕМОЙ ТУННЕЛЬ: отправлено %d, принято %d, эха 0, отброшено негодных %d, "+
		"сокет %s, сессии %s. До шлюза не доезжает даже метка keepalive.%s",
		tx, rx, dropped, local, time.Since(s.upAt).Round(time.Millisecond), gone)

	// Вторая проба отображения — ПЕРЕД остановкой, пока сокет жив.
	// Ответ придёт в насос чтения, который ещё работает.
	s.probeStunNow("немой туннель")
	time.Sleep(stunAnswerWait)

	// Контрольный AUTH — ПОСЛЕДНИМ измерением, перед самой остановкой.
	// Он перепривязывает адрес в туннеле на новый сокет, поэтому идти
	// он обязан после всего остального.
	s.probeAuthNow(s.winCand)

	s.stop("обратного трафика нет")
}

// armStun вешает разбор ответов STUN на все слоты сессии.
//
// Зовётся ДО запуска насосов и больше не трогается: onRaw читается из
// насоса чтения, и менять его на ходу означало бы гонку.
func (s *session) armStun() {
	if s.probeStun == "" {
		return
	}
	for _, r := range s.slotList() {
		// Потоковая ступень своего obfsPacketConn не имеет: STUN-проба
		// отображения NAT — про UDP-сокет, к потоку неприменима.
		if r.obfs == nil {
			continue
		}
		r.obfs.onRaw = s.noteStun
	}
}

// probeStun спрашивает у STUN, каким наш адрес видно снаружи.
//
// ЗАПРОС УХОДИТ С ТОГО ЖЕ САМОГО СОКЕТА, и в этом весь смысл: с любого
// другого измерялось бы чужое отображение. Ответ придёт в насос чтения
// и попадёт в noteStun через onRaw — блокирующего чтения тут нет и быть
// не может, насос уже работает.
//
// Только в отладочной сборке: голый пакет STUN с боевого сокета меняет
// наш профиль на проводе. Признак задаёт Kotlin пустым или непустым
// адресом, см. Ladder.SetProbeStun.
func (s *session) probeStunNow(why string) {
	if s.probeStun == "" {
		return
	}
	addr, err := net.ResolveUDPAddr("udp4", s.probeStun)
	if err != nil {
		return
	}
	list := s.slotList()
	// pc пуст у потоковой ступени: STUN — про отображение UDP-сокета,
	// по TCP/TLS спрашивать нечего и не с чего.
	if len(list) == 0 || list[0].pc == nil {
		return
	}
	m, err := stun.Build(stun.TransactionID, stun.BindingRequest)
	if err != nil {
		return
	}
	if _, err := list[0].pc.WriteTo(m.Raw, addr); err != nil {
		s.logf("проба NAT (%s): запрос не ушёл: %v", why, err)
		return
	}
	s.logf("проба NAT (%s): спросил, каким нас видно снаружи", why)
}

// noteStun разбирает ответ и говорит, СМЕНИЛОСЬ ЛИ отображение.
//
// Само по себе значение адреса мало что даёт; ценность в сравнении с
// тем, что было при подъёме. Совпало — гипотеза про переназначение NAT
// не подтверждается, и искать надо в другом месте. Разошлось — она
// подтверждена, и дальше это уже разговор про то, что с этим делать.
func (s *session) noteStun(raw []byte) {
	m := &stun.Message{Raw: raw}
	if err := m.Decode(); err != nil {
		return
	}
	var xor stun.XORMappedAddress
	if err := xor.GetFrom(m); err != nil {
		return
	}
	now := xor.String()
	prev, _ := s.stunSeen.Load().(string)
	if prev == "" {
		s.stunSeen.Store(now)
		s.logf("проба NAT: снаружи нас видно как %s", now)
		return
	}
	if prev == now {
		s.logf("проба NAT: отображение ПРЕЖНЕЕ (%s) — NAT ни при чём", now)
		return
	}
	s.logf("проба NAT: ОТОБРАЖЕНИЕ СМЕНИЛОСЬ, было %s, стало %s — "+
		"для шлюза мы теперь чужой", prev, now)
}

// probeAuthNow — КОНТРОЛЬНЫЙ AUTH СО ВТОРОГО СОКЕТА в момент немоты.
//
// Ради чего он существует. Дефект "принято 0" сузился до двух веток, и
// обе назвал кот 1 по своему журналу:
//
//	наши пакеты доходят до УЖЕ УСТАНОВЛЕННОГО соединения, и там
//	  систематически проваливается расшифровка — на шлюзе это невидимо,
//	  потому что одна битая посылка и сплошной провал глотаются там
//	  одинаково;
//	наши пакеты не доходят до сокета шлюза вовсе.
//
// Со стороны клиента обе выглядят одинаково: тишина. Ни счётчики, ни
// проба NAT их не разделяют — отображение мы уже проверили, оно
// стабильно.
//
// Разделяет их вот что: НОВЫЙ сокет с новым исходящим портом, но тот же
// путь, тот же адрес, тот же пароль.
//
//	ответ на AUTH ПРИШЁЛ — путь до шлюза жив, сеть жива, оператор ни
//	  при чём. Ломается ИМЕННО ЭТО соединение, то есть первая ветка;
//	ответа НЕТ — до шлюза не доходит ничего, каким бы сокетом ни идти.
//	  Вторая ветка, и искать надо между телефоном и Aeza.
//
// Цена — один сокет и до трёх секунд, и только когда сессия уже
// приговорена сторожем. Терять нечего: второй AUTH перепривяжет адрес
// в туннеле на новый сокет, но мы всё равно гасим сессию следующей
// строкой.
//
// ТОЛЬКО В ОТЛАДОЧНОЙ СБОРКЕ. Лишний AUTH на проводе — лишний
// отпечаток, а вся необнаружимость держится на неотличимости от
// роутерного клиента.
//
// Релейную ступень не проверяем: там перед AUTH стоит добыча кредов и
// TURN-аллокация, это минуты и чужая инфраструктура. Вопрос же стоит
// про прямой путь.
func (s *session) probeAuthNow(c candidate) {
	if !s.deepProbe || c.isRelay || c.name == "" {
		return
	}
	ctx, cancel := context.WithTimeout(context.Background(), probeAuthBudget)
	defer cancel()

	s.logf("контрольный AUTH: пробую тот же путь НОВЫМ сокетом")
	r, err := s.raise(ctx, s.gateway, c, s.password, s.prot, false, probeAuthBudget)
	if err != nil {
		s.logf("контрольный AUTH: сокет поднять не вышло: %v", err)
		return
	}
	defer r.close()

	// caps ровно "echo", как у обычной прямой ступени: профиль на
	// проводе не должен отличаться от боевого ни на байт — в том числе
	// нужен ли Noise NK, тем же условием, что и в authRung.
	needsNK := c.transport != transTLS && !c.useDTLS
	if _, err := s.auth(r.link, r.pc, s.password, s.deviceID, probeAuthBudget, "echo", needsNK); err != nil {
		s.logf("КОНТРОЛЬНЫЙ AUTH НЕ ПРОШЁЛ (%v) — "+
			"до шлюза не доходит ничего, дело НЕ в этом соединении", err)
		return
	}
	s.logf("КОНТРОЛЬНЫЙ AUTH ПРОШЁЛ — путь и сеть живы, " +
		"ломается именно прежнее соединение")
}

// probeNow — внеочередная проверка живости канала по внешнему сигналу.
//
// ЗАЧЕМ. Сторож тишины даёт каналу 90 секунд, и это правильно, пока мы
// ничего не знаем. Но Android знает раньше нас: он сам проверяет связь
// на нижней сети и снимает NET_CAPABILITY_VALIDATED, когда та ломается.
// В логе владельца 09.09 этот сигнал пришёл — и был только напечатан:
// подключить его было не к чему, и полторы минуты мы досиживали по
// сторожу, уже зная, что связи нет.
//
// ЧТО ДЕЛАЕТ. Шлёт метку вне очереди во ВСЕ живые слоты и укорачивает
// срок чтения до suspectSilenceLimit. Дальше ничего своего: ответит
// шлюз — насос чтения при следующем витке вернёт обычные 90 секунд;
// не ответит — сработает тот же самый сторож и та же остановка
// "канал молчит". Отдельного пути гашения не заводим намеренно.
//
// СРОК СТАВИТСЯ СНАРУЖИ, а не флагом для насоса. Насос в этот момент
// стоит внутри Read с прежним сроком в 90 секунд, и никакая переменная
// его оттуда не поднимет: подействует только SetReadDeadline на самом
// соединении, который разрешено звать из чужой горутины.
//
// ПРИ ШЛЮЗЕ БЕЗ ЭХА НЕ ДЕЛАЕМ НИЧЕГО. Условие ровно то же, по которому
// насос вообще ставит срок (echoConf): без эха шлюз не обязан слать в
// простое ничего, и молчание означало бы не смерть канала, а
// отсутствие трафика.
//
// Возвращает true, если проверка началась.
func (s *session) probeNow(why string) bool {
	if !s.echoConf {
		return false
	}
	select {
	case <-s.ctx.Done():
		return false
	default:
	}

	list := s.slotList()
	live := make([]*rung, 0, len(list))
	for _, r := range list {
		if !r.retired.Load() {
			live = append(live, r)
		}
	}
	if len(live) == 0 {
		return false
	}

	deadline := time.Now().Add(suspectSilenceLimit)
	for _, r := range live {
		_, _ = r.link.Write(keepaliveMarker)
		_ = r.link.SetReadDeadline(deadline)
	}
	s.logf("канал под подозрением (%s): метка вне очереди в %d слот(а/ов), ответ жду %s вместо %s",
		why, len(live), suspectSilenceLimit, rxSilenceLimit)

	// Повтор на случай одиночной потери. Срок НЕ продлеваем: он и
	// отсчитывается от первой метки, а повтор лишь закрывает дыру.
	s.wg.Add(1)
	go func() {
		defer s.wg.Done()
		t := time.NewTimer(probeRepeatGap)
		defer t.Stop()
		select {
		case <-s.ctx.Done():
			return
		case <-t.C:
		}
		for _, r := range live {
			if r.retired.Load() {
				continue
			}
			_, _ = r.link.Write(keepaliveMarker)
		}
	}()
	return true
}

func (s *session) keepalive() {
	// Первая метка уходит рано — см. keepaliveFirst. Дальше обычный шаг.
	first := time.NewTimer(keepaliveFirst)
	defer first.Stop()
	t := time.NewTicker(keepaliveInterval)
	defer t.Stop()
	for {
		select {
		case <-s.ctx.Done():
			return
		case <-first.C:
			// ВЗВОДИМ СЧЁТЧИК ЭХА ДО ОТПРАВКИ, а не после.
			//
			// Порядок важен: эхо может вернуться быстрее, чем нам
			// отдадут управление после Write. Взведя флаг позже, мы
			// потеряли бы самый первый отклик — и, что хуже, потеряли
			// бы его молча.
			s.echoArmed.Store(true)
			s.logf("метка keepalive ушла через %s после подъёма",
				time.Since(s.upAt).Round(time.Millisecond))
			for _, r := range s.slotList() {
				_, _ = r.link.Write(keepaliveMarker)
			}
		case <-t.C:
			// В КАЖДЫЙ слот, не только в первый. Срок чтения на шлюзе
			// считается по каждому слоту отдельно (спецификация 3.4),
			// и молчащий слот закроется, даже если остальные живы.
			//
			// Ошибка одного слота цикл не прерывает: остальные должны
			// продолжать получать метки. Мёртвый слот заметит его
			// собственный насос чтения.
			for _, r := range s.slotList() {
				_, _ = r.link.Write(keepaliveMarker)
			}
		}
	}
}

func (s *session) stop(reason string) {
	s.mu.Lock()
	if s.stopped {
		s.mu.Unlock()
		return
	}
	s.stopped = true
	s.mu.Unlock()

	// ПЕРВОЙ СТРОКОЙ, ДО ЗАКРЫТИЯ TUN НИЖЕ. Разбор — у OnStopping в
	// engine.go: только так замена интерфейса на стороне Kotlin
	// проходит АТОМАРНО, без окна без защиты. Флаг s.stopped выше уже
	// сделал этот путь одноразовым — второй звонок сюда не попадёт.
	if s.listener != nil {
		s.listener.OnStopping(reason)
	}

	// Числа переживают сессию: приложение спросит их после остановки,
	// когда самой сессии уже нет. См. LastTx/LastRx в engine.go.
	lastTx.Store(s.txCount.Load())
	lastRx.Store(s.rxCount.Load())

	early := ""
	if e := s.echoEarly.Load(); e > 0 {
		early = fmt.Sprintf(", ранних коротких %d", e)
	}
	slow := ""
	if n := s.slowLogs.Load(); n > 0 {
		slow = fmt.Sprintf(", МЕДЛЕННЫХ ЗАПИСЕЙ В ЛОГ %d, худшая %s",
			n, time.Duration(s.slowLogMax.Load()).Round(time.Millisecond))
	}
	// Отброшенный v6 показываем ТОЛЬКО когда он был: на сети без v6
	// лишнее поле в каждой строке итога — шум.
	v6 := ""
	if n := s.v6Dropped.Load(); n > 0 {
		v6 = fmt.Sprintf(", IPv6 погашено %d", n)
	}
	s.logf("итог: отправлено %d, принято %d пакетов, эха %d%s, слотов %d, максимум после обфускации %d байт%s%s",
		s.txCount.Load(), s.rxCount.Load(), s.echoCount.Load(), early,
		len(s.slotList()), s.maxWire(), slow, v6)
	if reason != "" {
		s.logf("сессия остановлена: %s", reason)
	}
	if s.cancel != nil {
		s.cancel()
	}
	for _, r := range s.slotList() {
		r.close()
	}
	if s.tun != nil {
		_ = s.tun.Close()
	}

	// Дожидаться насосов ЗДЕСЬ нельзя: stop() зовётся из них самих —
	// tunToNet и netToTun гасят сессию, наткнувшись на ошибку, — и
	// горутина ждала бы собственного завершения. Поэтому ожидание и
	// завершающие действия уезжают в отдельную горутину.
	go s.reap(reason)
}

// reap дожидается насосов и только потом объявляет сессию мёртвой.
//
// Порядок здесь важен: сначала выходят насосы, затем обнуляется current
// (через onStop), затем закрывается done, и лишь в самом конце
// извещается приложение. Обнулить current раньше означало бы пустить
// новую сессию к шлюзу, пока старая ещё дышит, — а адрес в туннеле
// выдаётся по хешу пароля, и второй AUTH выбьет первый.
func (s *session) reap(reason string) {
	if !waitTimeout(&s.wg, pumpDrainLimit) {
		// Дескриптор TUN может оказаться непригодным для поллера, и
		// тогда закрытие не разбудит чтение. Место освобождаем всё
		// равно, но громко: висящий насос — это дефект, а не мелочь.
		s.logf("насосы не завершились за %s, освобождаю место всё равно", pumpDrainLimit)
	}
	if s.onStop != nil {
		s.onStop()
	}
	close(s.done)
	// Слушатель — последним: ресурсы закрыты, насосы вышли, current уже
	// обнулён. Флаг s.stopped делает этот вызов РОВНО ОДНИМ на сессию,
	// сколько бы путей ни привело в stop().
	if s.listener != nil {
		s.listener.OnStopped(reason)
	}
}

// waitTimeout ждёт группу не дольше срока. true — дождались.
func waitTimeout(wg *sync.WaitGroup, d time.Duration) bool {
	ch := make(chan struct{})
	go func() {
		wg.Wait()
		close(ch)
	}()
	select {
	case <-ch:
		return true
	case <-time.After(d):
		return false
	}
}

// utcMilli — время в том же виде, в каком его печатает шлюз.
//
// Заведено 27.08 под сверку с котом 1. Он печатает время отправки эха с
// миллисекундами и в UTC; у нас в логе стоит МСК и точность до секунды.
// Сопоставлять "эхо ушло в 14:16:49.221" с нашим "17:16:49" нечем:
// внутри этой секунды помещается и отправка метки, и срок ожидания.
//
// UTC, а не МСК, намеренно — чтобы поле совпадало с его журналом байт в
// байт и не пришлось гадать, что уже переведено, а что нет. Разница с
// временем самой строки лога ровно три часа.
func utcMilli(t time.Time) string {
	return t.UTC().Format("15:04:05.000")
}

// dropCandidate — убрать ступень из списка по имени.
//
// Имена ступеней уникальны в пределах лестницы: их раздаёт приложение по
// одному на узел (C, A, B, R).
func dropCandidate(list []candidate, name string) []candidate {
	out := make([]candidate, 0, len(list))
	for _, c := range list {
		if c.name != name {
			out = append(out, c)
		}
	}
	return out
}
