// Package engine — движок Meridian для мобильного клиента.
//
// Всё, что экспортируется отсюда, видно из Kotlin через gomobile.
// Ограничения gomobile: допустимы string, bool, int32/int64, []byte,
// error и интерфейсы, объявленные в этом же пакете. Go-шный int
// отображается в Java long, поэтому везде явный int32.
package engine

import (
	"errors"
	"sync"
	"sync/atomic"
	"time"
)

// Logger — строки движка уезжают на экран приложения.
// Реализуется на стороне Kotlin.
type Logger interface {
	Log(line string)
}

// Protector — доступ к VpnService.protect().
// Без него сокет до шлюза уйдёт в собственный туннель.
type Protector interface {
	Protect(fd int32) bool
}

// NetworkGuard — проверка, что сеть под нами не сменилась.
//
// Движок не имеет доступа к ConnectivityManager, а знать это обязан:
// между подъёмом транспорта и отправкой AUTH проходит время (при форе
// без DTLS — до полутора секунд), и ровно в это окно человек успевает
// войти в зону Wi-Fi. AUTH при этом уходит с сокета, привязанного к
// исчезнувшему адресу, то есть в никуда.
//
// Реализуется на стороне Kotlin сравнением активной не-VPN сети с той,
// что была запомнена в начале попытки.
type NetworkGuard interface {
	// SameNetwork — та же ли сеть, что в начале попытки.
	SameNetwork() bool
}

// StateListener — извещение приложения о том, что сессия погасла.
//
// Внутренняя остановка (обрыв, ошибка чтения) случается в goroutine
// движка, и приложение о ней иначе не узнаёт: кнопка остаётся в
// положении "Отключить", хотя туннеля уже нет. Обратный вызов приходит
// НЕ с главного потока Android.
type StateListener interface {
	// OnStopping — сессия НАЧАЛА останавливаться, TUN ЕЩЁ НЕ ЗАКРЫТ.
	//
	// Заведён 15.09 ради Kill Switch. Единственная причина его
	// существования: дать приложению шанс подменить интерфейс VPN на
	// свой ДО того, как session.stop() закроет настоящий, — тогда
	// Android заменяет интерфейс АТОМАРНО (establish() второй раз сам
	// гасит прежний, чем бы он ни был), и окна без защиты не остаётся
	// вовсе. Пришли бы этим же путём после закрытия — какое-то время
	// трафик остальных приложений уже шёл бы настоящей сетью, и это и
	// была утечка, которую Kill Switch чинит.
	//
	// ВЫЗЫВАЕТСЯ СИНХРОННО И МОЖЕТ ПРИЙТИ ИЗ ГОРУТИНЫ НАСОСА, КОТОРАЯ
	// САМА ЖЕ И ОБНАРУЖИЛА ОБРЫВ (session.stop() зовётся из tunToNet и
	// netToTun напрямую). Реализация обязана отработать быстро и не
	// блокироваться на сети — она лишь переставляет системный интерфейс,
	// сетевого обмена в ней быть не должно. Любая задержка здесь
	// отодвигает выход насосов, а с ним и OnStopped ниже.
	//
	// НЕ ПУТАТЬ С OnStopped: тот приходит ПОСЛЕДНИМ, когда сессия уже
	// мертва целиком и путь свободен для новой попытки (см. reap()).
	// Этот — первым, пока прежний туннель формально ещё жив. Звать
	// Connect() отсюда нельзя — вот для этого и остаётся OnStopped.
	OnStopping(reason string)

	OnStopped(reason string)
}

// errSessionLive — Connect позвали, когда сессия уже работает.
//
// ЭТО НЕ ОТКАЗ ПОДКЛЮЧЕНИЯ, а сообщение "делать нечего, всё уже
// поднято", и приложение обязано отличать его от настоящей неудачи.
// Оно этого не делало с 22-й задачи: ошибка уходила в общий catch, тот
// звал stopTunnel(), и ЛИШНЯЯ попытка подключения гасила РАБОТАЮЩИЙ
// туннель. Разбор — в MeridianVpnService, ветка про живую сессию.
//
// Текст связан с Kotlin по подстроке "уже поднята"; компилятор эту
// связь не сторожит, менять — в двух местах разом.
var errSessionLive = errors.New("сессия уже поднята")

var (
	mu      sync.Mutex
	current *session

	// Счётчики последней сессии, см. LastTx и LastRx.
	lastTx atomic.Uint64
	lastRx atomic.Uint64
)

// Connect проходит лестницу транспорта и поднимает сессию на первой
// ступени, которая ответила.
//
// Возвращает выданный шлюзом адрес в виде "10.77.77.5/16" —
// ПРЕФИКС ЗДЕСЬ ПРИМЕР, А НЕ КОНСТАНТА: он разбирается из маски,
// присланной шлюзом (maskHexToPrefix), и ничего не зашито. На 07.09
// живой шлюз даёт /16; прежний пример /24 устарел и вводил в
// заблуждение —
// разбирается на стороне Kotlin для VpnService.Builder. Имя победившей
// ступени доступно через Winner().
func Connect(gateway string, ladder *Ladder, password string, deviceID string, prot Protector, guard NetworkGuard, captcha CaptchaSolver, log Logger, listener StateListener) (string, error) {
	if ladder == nil || len(ladder.items) == 0 {
		return "", errors.New("лестница пуста: ни одной ступени")
	}

	mu.Lock()
	if current != nil {
		mu.Unlock()
		return "", errSessionLive
	}
	s := newSession(log)
	s.guard = guard
	s.captcha = captcha
	// onStop назначается ДО того, как сессия станет current: неудачная
	// лестница обязана прибрать за собой сама, через s.stop().
	s.onStop = func() { clearCurrent(s) }
	current = s
	mu.Unlock()

	// ВАЖНО: мьютекс отпущен на всё время лазания. Лестница живёт до
	// ladderBudget, и держать mu столько нельзя: Stop() из onDestroy
	// приходит с главного потока Android, и заблокировать его на двадцать
	// секунд означает ANR. Побочная выгода — Stop() во время лазания
	// теперь действительно обрывает его: current уже указывает на s,
	// значит s.stop() отменит s.ctx, а от него наследуются сроки ступеней.
	addr, err := s.climb(gateway, ladder, password, deviceID, prot)
	if err != nil {
		s.stop("")
		return "", err
	}

	// Слушатель назначается только успешной сессии. О неудаче лестницы
	// приложение узнаёт по возвращённой ошибке, извещать его вторично
	// незачем — иначе на один провал придут два сообщения.
	s.listener = listener
	return addr, nil
}

// clearCurrent обнуляет current, если он всё ещё указывает на s.
// Нужна, чтобы не затереть current, если за это время успел подняться
// новый Connect.
func clearCurrent(s *session) {
	mu.Lock()
	defer mu.Unlock()
	if current == s {
		current = nil
	}
}

// Winner — имя ступени, которой поднялась текущая сессия.
// Пусто, если сессии нет. Приложение запоминает его для этой сети.
func Winner() string {
	mu.Lock()
	defer mu.Unlock()
	if current == nil {
		return ""
	}
	return current.winner
}

// Start принимает дескриптор TUN, полученный из VpnService.Builder.establish().
// Дескриптор переходит во владение движка: закрывать его на стороне Kotlin
// не нужно и нельзя, иначе получится двойное закрытие.
func Start(fd int32) error {
	mu.Lock()
	defer mu.Unlock()

	if current == nil {
		return errors.New("нет соединения: сначала Connect")
	}
	return current.start(int(fd))
}

// StartFlow — то же, что Start, но для платформы без дескриптора TUN.
//
// Нужен на iOS: у NEPacketTunnelProvider дескриптора нет вовсе, пакеты
// ходят через readPackets/writePackets. Договор о потоке — у PacketFlow
// в flowconn.go, там же разбор, почему приём пачками, а запись по
// одному пакету.
//
// Start(fd) при этом НЕ меняется и продолжает работать как работал:
// Android идёт через него.
func StartFlow(flow PacketFlow) error {
	mu.Lock()
	defer mu.Unlock()

	if current == nil {
		return errors.New("нет соединения: сначала Connect")
	}
	return current.startFlow(flow)
}

// SuspectNetwork — сигнал приложения: нижняя сеть под подозрением.
//
// Зовётся, когда Android снял с сети под нами NET_CAPABILITY_VALIDATED,
// то есть сам перестал видеть в ней связь. Сеть при этом жива как
// объект, интерфейс не переименовался, onLost не придёт — и до этой
// правки такое событие только печаталось в лог.
//
// НЕ ГАСИТ СЕССИЮ. Сигнал шумный: проверка связи у Android мигает и на
// исправных сетях. Поэтому здесь только внеочередная метка и
// укороченный срок ожидания ответа — приговор выносит обычный сторож
// тишины, если ответа не будет. Разбор — у probeNow.
//
// Возвращает true, если проверка началась. false означает "делать
// нечего": сессии нет, слотов нет или шлюз работает без эха.
//
// Смену АДРЕСА на выжившей сети сюда слать не надо: там сокет мёртв
// достоверно, и приложение обязано переподключаться само, не тратя
// шести секунд на проверку.
func SuspectNetwork(why string) bool {
	mu.Lock()
	s := current
	mu.Unlock()

	if s == nil {
		return false
	}
	return s.probeNow(why)
}

// Stop гасит сессию целиком и закрывает дескриптор TUN.
//
// Возвращается СРАЗУ, не дожидаясь завершения насосов: её зовут в том
// числе с главного потока Android (onDestroy), и ждать там нельзя — это
// ANR. Дождаться полной остановки можно через AwaitStopped, но только с
// фонового потока.
//
// current здесь БОЛЬШЕ НЕ ОБНУЛЯЕТСЯ. Раньше обнулялся, и это было
// дырой: между снятием мьютекса и вызовом s.stop() место считалось
// свободным, хотя сокет прежней сессии был ещё открыт. Теперь место
// освобождает reap — после того, как насосы вышли.
func Stop() {
	mu.Lock()
	s := current
	mu.Unlock()

	if s != nil {
		s.stop("по команде приложения")
	}
}

// AwaitStopped ждёт, пока текущая сессия не будет остановлена ПОЛНОСТЬЮ:
// ресурсы закрыты, насосы вышли, место освобождено.
//
// Возвращает true, если сессии к моменту возврата нет. false — не
// дождались за отведённый срок; начинать новую в этом случае нельзя,
// иначе на шлюзе окажутся две сессии на одном адресе.
//
// ЗВАТЬ ТОЛЬКО С ФОНОВОГО ПОТОКА: функция блокирующая.
func AwaitStopped(timeoutMs int32) bool {
	mu.Lock()
	s := current
	mu.Unlock()

	if s == nil {
		return true
	}
	select {
	case <-s.done:
		return true
	case <-time.After(time.Duration(timeoutMs) * time.Millisecond):
		return false
	}
}

// Счётчики ПОСЛЕДНЕЙ сессии: сколько пакетов ушло и пришло.
//
// Живут отдельно от сессии и переживают её смерть намеренно: спросить
// их приложение может только после остановки, когда самой сессии уже
// нет, а числа нужны — по ним видно «встали, но обратного потока не
// было», а это самый частый вид поломки.
//
// Отдаются числами, а не строкой: приложению они нужны для своего
// текста, а не для показа нашего.
func LastTx() int64 { return int64(lastTx.Load()) }

func LastRx() int64 { return int64(lastRx.Load()) }

// Active — поднята ли сессия.

func Active() bool {
	mu.Lock()
	defer mu.Unlock()
	return current != nil
}

// MTU туннеля ДЛЯ ПОДНЯВШЕЙСЯ СТУПЕНИ.
//
// Спрашивать его нужно ПОСЛЕ Connect: до прохода лестницы неизвестно,
// какая ступень выиграет, а MTU у них разное. Ступень с DTLS отдаёт
// полный tunMTU (pion всё равно режет по dtlsMTU), ступень без DTLS —
// уменьшенный rawTunMTU, потому что резать там некому.
//
// Отдельной функции не завёл намеренно: MTU() и раньше вызывался из
// Kotlin ровно там, где нужно — между Connect и Builder.setMtu, — так
// что порядок вызовов менять не пришлось вовсе.
//
// Без сессии возвращается МЕНЬШЕЕ из значений. Такого вызова быть не
// должно, но если он случится, ошибиться в сторону меньшего пакета
// безопаснее: это стоит немного скорости, тогда как ошибка в большую
// сторону роняет крупные пакеты без единого симптома.
func MTU() int32 {
	mu.Lock()
	defer mu.Unlock()
	if current == nil || current.mtu == 0 {
		return rawTunMTU
	}
	return current.mtu
}
