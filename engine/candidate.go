package engine

import "net"

// transportKind — каким транспортом идёт ПРЯМАЯ ступень.
//
// Заведено под ступени 3-4 (спецификация кота 2, 31.08): на сетях, где
// UDP к шлюзу мёртв, а TCP жив, идём потоком. Умолчание (нулевое
// значение) — UDP, чтобы старые ступени не меняли ни строки.
type transportKind int

const (
	transUDP transportKind = iota // UDP; DTLS решает useDTLS
	transTCP                      // TCP-поток, кадры obfs (порт 56004, без DTLS)
	transTLS                      // TLS-поток, кадры obfs внутри (порт 443, SNI + отпечаток)
)

// streamKindText — короткое имя транспорта для лога.
func streamKindText(t transportKind) string {
	switch t {
	case transTCP:
		return "TCP"
	case transTLS:
		return "TLS"
	default:
		return "UDP"
	}
}

// candidate — одна ступень лестницы: куда стучимся и на каких условиях.
//
// Поля не экспортируются: снаружи ступени добавляются методами Ladder,
// потому что gomobile не умеет передавать срезы структур.
//
// Сроков у ступени БОЛЬШЕ НЕТ. Они оказались свойством не порта, а
// МЕСТА в лестнице: первой ступени нужно много времени, потому что она
// чаще всего и есть рабочая, а последним — мало, потому что до них
// очередь доходит уже на исходе общего срока. Место же зависит от
// памяти пути и известно только здесь, при проходе. См. rungBudget.
type candidate struct {
	name string // человекочитаемое имя для лога

	// isRelay — ступень релейная: поднимается через TURN-аллокацию,
	// см. raiseRelay, но дальше идёт по тем же слоям и тому же AUTH.
	// В гонку релейные ступени не берутся: аллокация — лишний обмен с
	// третьей стороной, и гонять её наперегонки с прямыми значило бы
	// тратить креды там, где прямой путь и так работает.
	isRelay bool

	// host — адрес ИМЕННО ЭТОЙ ступени.
	//
	// Появился вместе с /v1/params: служба отдаёт список записей, и
	// адрес в каждой свой. Отдельного поля с общим адресом шлюза в её
	// ответе НЕТ вовсе — это ответ кота 2 на прямой вопрос.
	//
	// Пусто — берётся общий адрес, переданный в Connect. Так работает
	// лестница из зашитых настроек и релейная ступень, которая идёт на
	// шлюз через TURN.
	host string

	port    int32
	useDTLS bool // false — obfs единственный слой (порт 56005)

	// transport — UDP (умолчание), TCP или TLS. Для TCP/TLS useDTLS не
	// смотрится вовсе: свой транспорт и своё крипто-плечо.
	transport transportKind

	// sni — имя для TLS-ступени, приходит из /v1/params (привязано к IP,
	// переезжает вместе с host). Пусто — движок берёт запаску
	// tlsGatewaySNI.
	sni string

	// turnAddr — ЗАПАСНОЙ адрес релея из настроек.
	//
	// Рабочий адрес приходит от цепочки: шаг 5 отдаёт turn_server.urls,
	// и это релеи, назначенные VK ИМЕННО под выданные креды. Настроечный
	// остаётся на случай, когда цепочка адресов не вернула.
	//
	// Кредов здесь нет вовсе — они только от цепочки, см. turnCreds.
	turnAddr  string
	turnRealm string

	// hashes — ссылки VK, из которых креды добываются цепочкой.
	//
	// ЕДИНСТВЕННЫЙ источник кредов. Пусты — релейная ступень откажет
	// с внятным текстом: идти ей больше некуда.
	hashes []string

	// remembered — эта ступень запомнена как рабочая для текущей сети.
	//
	// Такая ступень пробуется ОДНА и без гонки: гонка нужна незнакомой
	// сети, а в знакомой она только тратила бы сокеты и время на заведомо
	// худшие варианты.
	remembered bool

	// spent — эту ступень в текущей попытке уже пробовали.
	//
	// Ставится, когда запомненная ступень провалилась и возвращается в
	// гонку. Смысл ровно один: не платить за неё форой дважды.
	//
	// Замер 27.08, 17:16:47 и 17:17:00 — два цикла подряд, оба
	// одинаковые. Запомненная C отвечает на AUTH, отвечает на первую
	// метку за 70 мс и молчит на вторую. Контрольный AUTH с нового
	// сокета проходит мгновенно, и в гонке та же C с нового сокета
	// проводит обе метки (70 и 120 мс) и поднимает туннель. То есть
	// ступень не при чём: не держится первый сокет попытки.
	//
	// Дальше C идёт в гонку заново и по общему правилу уступает 1,5 с
	// форы ступеням с DTLS. Но фора заведена, чтобы дать себя показать
	// тому, кого ещё не пробовали. C уже пробовали — она первой и шла.
	// Отдавать полторы секунды второй раз не за что.
	//
	// Из шести секунд подъёма полторы уходили сюда.
	//
	// ОГОВОРКА, чтобы не приписать этой правке лишнего. В том же логе A
	// и B кончают "handshake error: context canceled", но это НАША
	// отмена после победы C, а не их отказ. Сказать по нему можно ровно
	// одно: за отведённые полторы секунды рукопожатие они не закончили,
	// и встречного за это время на их сокетах не было ни байта. Годятся
	// они на этой сети или нет — из этого лога не следует, и фору для
	// НЕпробованных ступеней правка не трогает.
	spent bool

	// mtu — MTU туннеля ИМЕННО ДЛЯ ЭТОЙ ступени.
	//
	// Считается здесь, а не в приложении: размер обвязки — знание
	// движка, приложению незачем помнить, что заголовок obfs 12 байт,
	// тег 16, а набивка до 24.
	mtu int32
}

// Ladder — лестница транспорта: список ступеней в порядке перебора.
//
// Собирается на стороне Kotlin, потому что порядок зависит от вещей,
// которых движок не знает: режим из настроек, запомненный для этой сети
// удачный путь. Движок лестницу только проходит.
type Ladder struct {
	items []candidate

	// probeStun — адрес STUN для отладочной проверки отображения NAT.
	//
	// ПУСТО В РЕЛИЗЕ, и решает это Kotlin, а не движок: признак
	// отладочной сборки живёт в BuildConfig, а движку про него знать
	// неоткуда. Пусто — проба не делается вовсе, ни одного лишнего
	// пакета на провод не уходит.
	probeStun string

	// deepProbe — разрешена ли ГЛУБОКАЯ диагностика.
	//
	// Сегодня это одно: контрольный AUTH со второго сокета в момент,
	// когда сторож объявил туннель немым. Он разделяет две оставшиеся
	// ветки дефекта "принято 0", и другого способа их разделить со
	// стороны клиента нет.
	//
	// ЛОЖЬ В РЕЛИЗЕ, и решают это раздельные исходники, а не флаг:
	// лишний AUTH на проводе — это лишний отпечаток, а вся наша
	// необнаружимость держится на неотличимости от роутерного клиента.
	deepProbe bool

	// slots — сколько слотов просить на старте. Ноль означает
	// "не задано" и читается как один.
	slots int

	// slotsMax — верхний предел автоподбора, slotsAuto — включён ли он.
	slotsMax  int
	slotsAuto bool

	// failDirect — режим отладки: все прямые ступени проваливаются, не
	// доходя до сети. Нужен, чтобы проверять переход на релей, ничего не
	// выключая на самом устройстве.
	failDirect bool

	// simVKTimeout — режим отладки: ПЕРВЫЙ пробуемый хеш VK делает
	// вид, что не ответил за срок. Нужен, чтобы проверить отсрочку
	// хеша там, где сеть исправна и настоящего тайм-аута не добиться.
	simVKTimeout bool

	// secondRoundMs — срок гонки на втором круге, в миллисекундах.
	//
	// Приходит из настройки сервера (ladder.second_round_ms), приложение
	// вкладывает его сюда. Ноль означает "не задано" — тогда берётся
	// зашитое умолчание rerunHandshakeBudget. Проверку на вменяемость
	// делает приложение, движку сюда попадает уже разумное число.
	secondRoundMs int32
}

// NewLadder создаёт пустую лестницу.
func NewLadder() *Ladder {
	return &Ladder{}
}

// AddDirect добавляет прямую ступень.
// host пустой — берётся общий адрес из Connect; непустой — адрес этой
// ступени, как его отдала служба в /v1/params.
func (l *Ladder) AddDirect(name, host string, port int32, useDTLS bool) {
	l.items = append(l.items, candidate{
		name:    name,
		host:    host,
		port:    port,
		useDTLS: useDTLS,
		mtu:     mtuFor(useDTLS),
	})
}

// AddTCP — СТУПЕНЬ 3: прямой TCP с кадрированием obfs, без DTLS и без
// RTP-обёртки на уровне кадра (заголовок RTP остаётся ВНУТРИ кадра, там
// же, где на UDP). Для сетей, режущих UDP.
func (l *Ladder) AddTCP(name, host string, port int32) {
	l.items = append(l.items, candidate{
		name:      name,
		host:      host,
		port:      port,
		transport: transTCP,
		mtu:       mtuFor(false),
	})
}

// AddTLS — СТУПЕНЬ 4: TLS с SNI и сверкой отпечатка сертификата, кадры
// obfs внутри TLS. Адрес, порт и SNI задаёт приложение (SNI — из
// /v1/params, привязан к IP); отпечаток — константа движка, см. tlspin.go.
// Пустой sni движок заменит запаской tlsGatewaySNI.
func (l *Ladder) AddTLS(name, host string, port int32, sni string) {
	l.items = append(l.items, candidate{
		name:      name,
		host:      host,
		port:      port,
		transport: transTLS,
		sni:       sni,
		mtu:       mtuFor(false),
	})
}

// AddDirectRemembered добавляет прямую ступень, запомненную как рабочая
// для текущей сети.
//
// Такая ступень пробуется первой, одна и без гонки. Приложение помечает
// её само: какая сеть под нами и что для неё запомнено — знание
// приложения, движок про это не знает и знать не должен.
func (l *Ladder) AddDirectRemembered(name, host string, port int32, useDTLS bool) {
	l.items = append(l.items, candidate{
		name:       name,
		host:       host,
		port:       port,
		useDTLS:    useDTLS,
		remembered: true,
		mtu:        mtuFor(useDTLS),
	})
}

// SetRelayTarget задаёт ЗАПАСНОЙ конечный адрес релея из поля relay.target
// ответа /v1/params. Зовётся ПОСЛЕ AddRelay и AddRelayHash.
//
// Порядок — решение владельца от 24.09: СНАЧАЛА релей на адрес шлюза из
// Connect (edge, как было), и только если он не поднялся — на target
// (Париж). Причина: TURN VK 193.203.43.* не доставляет на Париж с 22.09,
// какой TURN выпадет — решает VK; на вход работает любой.
//
// Каждая релейная ступень раздваивается: первая прежняя (host пуст), следом
// копия с target. Релейные ступени идут последовательно. Порт прежний (56005).
//
// Значение — только IPv4-литерал без порта. Иное (имя, приватный адрес,
// мусор) не принимается: возвращает false, лестница не меняется.
func (l *Ladder) SetRelayTarget(host string) bool {
	ip := net.ParseIP(host)
	if ip == nil || ip.To4() == nil || isPrivateOrSpecial(host) {
		return false
	}
	out := make([]candidate, 0, len(l.items)+1)
	for _, c := range l.items {
		out = append(out, c)
		if c.isRelay && c.host == "" {
			via := c
			via.host = host
			out = append(out, via)
		}
	}
	l.items = out
	return true
}

// AddRelayдобавляет релейную ступень.
//
// Кредов на входе НЕТ: они добываются цепочкой vkcalls из хешей,
// добавленных через AddRelayHash. turnAddrBackup — запасной адрес
// релея на случай, когда цепочка адресов не вернула.
//
// gatewayPort — порт ШЛЮЗА, к которому идём через релей.
func (l *Ladder) AddRelay(
	name string, turnAddrBackup, turnRealm string,
	gatewayPort int32, useDTLS bool,
) {
	l.items = append(l.items, candidate{
		name:      name,
		isRelay:   true,
		port:      gatewayPort,
		useDTLS:   useDTLS,
		turnAddr:  turnAddrBackup,
		turnRealm: turnRealm,
		mtu:       mtuFor(useDTLS),
	})
}

// AddRelayHash добавляет хеш VK к последней релейной ступени.
//
// Комплекты кредов добываются из хешей на лету анонимной цепочкой
// vkcalls. Хеш пачки номер N берётся как hashes[N % len(hashes)] — тем
// же способом, каким это делает WG-путь.
func (l *Ladder) AddRelayHash(hash string) {
	for i := len(l.items) - 1; i >= 0; i-- {
		if l.items[i].isRelay {
			l.items[i].hashes = append(l.items[i].hashes, hash)
			return
		}
	}
}

// SetSlots задаёт желаемое число слотов.
//
// Действует ТОЛЬКО на релейной ступени: на прямом пути многослот
// неприменим — там нет шейпа на аллокацию, наращивать нечего
// (спецификация-2, C.5). Прямые ступени остаются односложными, и их
// AUTH не меняется ни на байт.
//
// Значение обрезается по slotsMax. У шлюза свой предел, 16 соединений
// на IP (спецификация 3.4), и наш потолок оставляет от него запас.
// Параметр НЕ называется auto: gomobile генерирует C-обвязку, а там
// auto — спецификатор класса хранения, и сборка падает на
// "invalid storage class specifier in function declarator".
// SetProbeStun задаёт адрес STUN для отладочной проверки отображения
// NAT. Пусто (умолчание) — проверки нет.
//
// Зачем она: дефект "принято 0" переживает три версии, и главная
// гипотеза — операторский NAT переназначает наше отображение посреди
// сессии. Шлюз различает клиентов по адресу источника, и с этой секунды
// наши пакеты для него приходят от чужого. Сравнение отражённого адреса
// при подъёме и в момент немоты подтверждает это или закрывает.
func (l *Ladder) SetProbeStun(addr string) {
	l.probeStun = addr
}

// SetDeepProbe разрешает глубокую диагностику. Ложь (умолчание) — её
// нет вовсе, ни одного лишнего пакета на провод.
func (l *Ladder) SetDeepProbe(on bool) {
	l.deepProbe = on
}

func (l *Ladder) SetSlots(start, upper int32, enabled bool) {
	l.slots = clampSlots(start)
	l.slotsMax = clampSlots(upper)
	l.slotsAuto = enabled
}

// SetSecondRoundMs задаёт срок гонки на втором круге из настройки
// сервера. Ноль — оставить зашитое умолчание. Разумность значения —
// забота приложения; движок доверяет тому, что ему передали.
func (l *Ladder) SetSecondRoundMs(ms int32) {
	l.secondRoundMs = ms
}

func clampSlots(n int32) int {
	switch {
	case n < 1:
		return 1
	case int(n) > slotsMax:
		return slotsMax
	default:
		return int(n)
	}
}

// FailDirect включает имитацию закрытого прямого пути.
// SimulateVKTimeout — отладка: первый пробуемый хеш VK притворяется
// не ответившим за срок. Только для отладочных сборок; в релизе
// вызывающая сторона его не зовёт (проверка BuildConfig.DEBUG).
func (l *Ladder) SimulateVKTimeout() {
	l.simVKTimeout = true
}

func (l *Ladder) FailDirect() {
	l.failDirect = true
}

// Len — сколько ступеней в лестнице.
func (l *Ladder) Len() int32 {
	return int32(len(l.items))
}

// mtuFor — MTU туннеля для ступени.
//
// Со DTLS: pion сам режет записи по dtlsMTU (1100), и на провод уходит
// заведомо меньше порога, поэтому туннелю можно оставить полный tunMTU.
//
// Без DTLS резать некому — над obfs нет никого. Полный пакет уходит как
// tunMTU + 12 заголовка + 16 тега + до 24 набивки = до 1252 байт данных
// UDP, плюс 8 UDP и 20 IP — это 1280 байт IP-пакета, ровно минимальный
// MTU IPv6 и типовой потолок мобильного канала. Отсюда rawTunMTU.
func mtuFor(useDTLS bool) int32 {
	if useDTLS {
		return tunMTU
	}
	return rawTunMTU
}
