#!/bin/sh
# Релизная сборка для Play: бандл и APK для проверки.
#
# Скрипт существует ради ОДНОГО: движок пересобирается под все три
# архитектуры ВСЕГДА, а не когда вспомнишь.
#
# Отладочный AAR лежит по тому же пути и под тем же именем, но собран
# только под arm64 — отличить их глазом нельзя. Поэтому здесь не
# «проверь, что собрано правильно», а «собери заново». Лишние двенадцать
# секунд дешевле бандла, в котором на половине устройств нет движка.
#
# Вторая проверка стоит в app/build.gradle.kts и смотрит внутрь AAR: она
# уронит сборку, если архитектур в нём меньше трёх. Одна защита здесь,
# вторая там — на случай, если релиз соберут не этим скриптом.

set -e

cd "$(dirname "$0")"

echo "1/3 движок, три архитектуры"
bash engine/build-aar.sh --all

echo "2/3 бандл для Play (вариант play)"
./gradlew.bat bundlePlayRelease

echo "3/3 APK для прямой раздачи (вариант direct)"
./gradlew.bat assembleDirectRelease

# ГОТОВЫЕ СБОРКИ — В ОДНОМ МЕСТЕ И С ЧЕЛОВЕЧЕСКИМИ ИМЕНАМИ.
#
# Gradle раскладывает выходные файлы по своим правилам и под своими
# именами: apk/direct/release/app-direct-release.apk и
# bundle/playRelease/app-play-release.aab. Два разных каталога, два
# невнятных имени, и по имени не видно ни версии, ни свежести.
#
# Хуже другое: старые сборки в этих каталогах остаются лежать. Так
# рядом с нынешним бандлом нашёлся bundle/release/app-release.aab —
# добандловый, ещё до разделения на play и direct, без биллинга вовсе.
# Загрузить его в Play вместо нужного было бы делом одного промаха
# мышью.
#
# Поэтому: обе готовые сборки переезжают СЮДА, с версией в имени, а
# рабочие каталоги Gradle чистятся.
#
# Переносим, а не копируем: две одинаковые сборки рядом — способ
# однажды отдать не ту.
#
# Делать это из build.gradle.kts нельзя без внутренних классов AGP,
# которые ломаются молча от версии к версии. Две строки на shell
# надёжнее.
VER=$(grep -oE 'code=[0-9]+' app/version.properties | cut -d= -f2)
OUT="app/build/outputs/release"

# КАТАЛОГ ОЧИЩАЕТСЯ ПЕРЕД КАЖДОЙ СБОРКОЙ.
#
# Иначе прошлые версии остаются лежать рядом с новой, и мы возвращаемся
# ровно к тому, ради чего скрипт и заводился: два файла рядом, по имени
# видно версию, но не видно, какой из них сейчас нужен. Так уже дважды
# едва не раздали не то — сначала APK, потом добандловый .aab.
#
# Готовая сборка вся здесь и вся свежая. Прошлые версии, если понадобятся,
# берутся из git по номеру, а не из мусора в каталоге.
rm -rf "$OUT"
mkdir -p "$OUT"

APK_SRC="app/build/outputs/apk/direct/release/app-direct-release.apk"
AAB_SRC="app/build/outputs/bundle/playRelease/app-play-release.aab"
APK_DST="$OUT/meridian_0.1.${VER}.apk"
AAB_DST="$OUT/meridian_0.1.${VER}.aab"

[ -f "$APK_SRC" ] && mv -f "$APK_SRC" "$APK_DST"
[ -f "$AAB_SRC" ] && mv -f "$AAB_SRC" "$AAB_DST"

# Каталог добандловых сборок. Пустой он не нужен, а непустой опасен.
rm -rf app/build/outputs/bundle/release

# ОПИСАНИЕ РЕЛИЗА ДЛЯ ОБНОВЛЕНИЯ — СОБИРАЕТСЯ ОТСЮДА, НЕ РУКАМИ.
#
# Приложение в прямой раздаче читает этот файл, чтобы узнать о новой
# версии: Update.kt, адрес releases/latest/download/latest.json.
#
# Писать его руками нельзя. Размер и сумма берутся из ТОЛЬКО ЧТО
# собранного APK, и разойтись с ним они не могут; набранные вручную —
# разойдутся в первый же раз, а признак у этого один: приложение
# скачает сборку и молча её отбросит.
#
# version_code берётся из того же version.properties, что и versionCode
# в build.gradle.kts, — сравнение на стороне приложения идёт числом.
if [ -f "$APK_DST" ]; then
    SUM=$(sha256sum "$APK_DST" | cut -d" " -f1)
    SIZE=$(stat -c%s "$APK_DST")
    cat > "$OUT/latest.json" <<JSON
{
  "version_code": ${VER},
  "version_name": "0.1.${VER}",
  "sha256": "${SUM}",
  "size": ${SIZE},
  "url": "https://github.com/JinComputers/meridian-android/releases/download/v0.1.${VER}/meridian_0.1.${VER}.apk",
  "min_sdk": 26
}
JSON
fi

echo
echo "APK для раздачи:  $APK_DST"
echo "Бандл для Play:   $AAB_DST"
echo "Описание релиза:  $OUT/latest.json"
echo
echo "ПРОВЕРЬ ПОДПИСЬ ПЕРЕД ЗАГРУЗКОЙ. Без keystore.properties сборка"
echo "подписана отладочным ключом и в Play не пойдёт — она об этом"
echo "предупреждает отдельной строкой выше."
